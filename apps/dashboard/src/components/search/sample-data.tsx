type Hit = { _id: string; _score?: number | null; _source?: Record<string, unknown> };
type Bucket = { key: unknown; key_as_string?: string; doc_count: number; [sub: string]: unknown };

/** Dotted paths of a document's leaves, in its own order. */
function flatten(o: Record<string, unknown>, prefix = "", out: [string, unknown][] = []): [string, unknown][] {
  for (const [k, v] of Object.entries(o)) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === "object" && !Array.isArray(v)) flatten(v as Record<string, unknown>, key, out);
    else out.push([key, v]);
  }
  return out;
}

const show = (v: unknown) => (v === null || v === undefined ? "—" : typeof v === "object" ? JSON.stringify(v) : String(v));

/** A search's hits as a table, its aggregations as bucket lists, or ES|QL's columns and rows. */
function Results({ value, took }: { value: unknown; took: number | null }) {
  const v = value as { hits?: { total?: { value: number; relation?: string } | number; hits: Hit[] }; aggregations?: Record<string, { buckets?: Bucket[] | Record<string, Bucket> }>; columns?: { name: string }[]; values?: unknown[][] };
  const meta = (n: string) => (
    <p className="mb-2 font-mono text-[11px] text-subtle">
      {n}
      {took != null && ` · ${took} ms`}
    </p>
  );

  if (v?.columns && v.values) {
    return (
      <div>
        {meta(`${v.values.length} rows`)}
        <Table head={v.columns.map((c) => c.name)} rows={v.values.map((r) => r.map(show))} />
      </div>
    );
  }
  const total = v?.hits?.total;
  const count = typeof total === "number" ? total : total ? `${total.value}${total.relation === "gte" ? "+" : ""}` : 0;
  if (v?.aggregations && Object.keys(v.aggregations).length) {
    return (
      <div>
        {meta(`${count} documents`)}
        <div className="grid gap-3 sm:grid-cols-2">
          {Object.entries(v.aggregations).map(([name, agg]) => {
            const buckets = Array.isArray(agg.buckets) ? agg.buckets : Object.entries(agg.buckets ?? {}).map(([key, b]) => ({ ...b, key }));
            const max = Math.max(1, ...buckets.map((b) => b.doc_count));
            const sub = (b: Bucket) => Object.entries(b).find(([k, x]) => !["key", "key_as_string", "doc_count", "from", "to"].includes(k) && x && typeof x === "object" && "doc_count" in (x as object));
            return (
              <div key={name} className="min-w-0">
                <p className="mb-1 text-[12px] text-subtle">{name}</p>
                <ul className="space-y-1">
                  {buckets.map((b) => {
                    const s = sub(b);
                    return (
                      <li key={String(b.key)} className="relative overflow-hidden rounded-md px-2 py-1 text-[12px]">
                        <span className="absolute inset-y-0 left-0 bg-panel-2" style={{ width: `${(b.doc_count / max) * 100}%` }} aria-hidden />
                        <span className="relative flex items-baseline justify-between gap-2">
                          <span className="truncate">{b.key_as_string ?? String(b.key)}</span>
                          <span className="shrink-0 font-mono tabular-nums">
                            {b.doc_count}
                            {s && <span className={(s[1] as { doc_count: number }).doc_count ? "text-danger" : "text-subtle"}> · {(s[1] as { doc_count: number }).doc_count} {s[0]}</span>}
                          </span>
                        </span>
                      </li>
                    );
                  })}
                </ul>
              </div>
            );
          })}
        </div>
      </div>
    );
  }
  const hits = v?.hits?.hits ?? [];
  if (!hits.length) return meta("No hits");
  const rows = hits.map((h) => flatten(h._source ?? {}));
  const head = [...new Set(rows.flatMap((r) => r.map(([k]) => k)))];
  return (
    <div>
      {meta(`${count} hits`)}
      <Table head={head} rows={rows.map((r) => head.map((k) => show(r.find(([x]) => x === k)?.[1])))} />
    </div>
  );
}

function Table({ head, rows }: { head: string[]; rows: string[][] }) {
  return (
    <div className="overflow-x-auto rounded-lg border border-line">
      <table className="w-full text-[12px]">
        <thead>
          <tr className="border-b border-line text-left text-[11px] text-subtle">
            {head.map((h) => (
              <th key={h} className="px-2.5 py-1.5 font-normal whitespace-nowrap">
                {h}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {rows.map((r, i) => (
            <tr key={i} className="border-b border-line last:border-0">
              {r.map((c, j) => (
                <td key={j} className={`max-w-64 truncate px-2.5 py-1.5 ${/^-?[\d.]+$/.test(c) ? "text-right font-mono tabular-nums" : ""}`} title={c}>
                  {c}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}
