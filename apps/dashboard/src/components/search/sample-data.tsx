type Job = { id: SampleId; step: string; sent: number; error?: string };

/** The key the first queries' code carries: made here, kept only while the panel is open. */
type MadeKey = { key: NewSearchKey; open: boolean } | { making: true } | { error: string };

/** What a key fills into the copied code (OpenSearch-flavor keys are a user and password). */
function snippetKey(k: NewSearchKey): SnippetKey | undefined {
  if (k.api_key) return { apiKey: k.api_key };
  if (k.username && k.password) return { username: k.username, password: k.password };
  return undefined;
}

/**
 * Sample data in one click, then three ready queries on it (Kibana's sample data, Meilisearch's
 * movies): shown on a new cluster's Overview and from the Indices tab.
 */
export function SampleData({
  cluster,
  present,
  onChanged,
  onOpenConsole,
  onManageKeys,
  onClose,
}: {
  cluster: SearchCluster;
  /** The datasets known to be loaded. */
  present: ReadonlySet<SampleId>;
  onChanged: (id: SampleId, loaded: boolean) => void;
  onOpenConsole: (text: string) => void;
  /** Settings → API keys. */
  onManageKeys: () => void;
  onClose?: () => void;
}) {
  const [job, setJob] = useState<Job | null>(null);
  const [key, setKey] = useState<MadeKey | null>(null);
  const [selected, setSelected] = useState<SampleId | null>(() => SAMPLES.find((s) => present.has(s.id))?.id ?? null);
  // A load in flight stops when the panel goes (closed, or the page left).
  const alive = useRef(true);
  useEffect(() => {
    alive.current = true;
    return () => {
      alive.current = false;
    };
  }, []);
  const busy = job !== null && !job.error;
  const shown = selected && present.has(selected) ? sample(selected) : null;

  const load = async (set: SampleDataset) => {
    const update = (j: Partial<Job>) => alive.current && setJob((p) => ({ id: set.id, step: "", sent: 0, ...p, ...j }));
    setJob({ id: set.id, step: "Preparing…", sent: 0 });
    try {
      // A reload starts clean: the logs' timestamps follow the load time.
      await removeAll(cluster.id, set);
      for (const r of set.setup) await esRaw(cluster.id, r.method, r.path, r.body);
      const pages = bulkPages(set, Date.now(), pageLimit(cluster.max_body_mb));
      let sent = 0;
      for (const p of pages) {
        if (!alive.current) return;
        update({ step: "Indexing", sent });
        const r = await esRaw(cluster.id, "POST", "/_bulk", p.body);
        const failed = bulkFailures(r.value);
        if (failed.length) throw new Error(`${failed.length} documents failed: ${failed[0].reason}`);
        sent += p.docs;
      }
      update({ step: "Refreshing", sent });
      await esRaw(cluster.id, "POST", `/${set.id}/_refresh`);
      if (!alive.current) return;
      setJob(null);
      setSelected(set.id);
      onChanged(set.id, true);
    } catch (e) {
      update({ error: e instanceof Error ? e.message : String(e) });
    }
  };

  // A data key for 30 days: enough to try the copied code, never the cluster's password.
  const makeKey = async () => {
    setKey({ making: true });
    try {
      const k = await searchApi.createKey(cluster.id, "first queries", "data", 30 * 86_400);
      if (alive.current) setKey({ key: k, open: true });
    } catch (e) {
      if (alive.current) setKey({ error: e instanceof Error ? e.message : String(e) });
    }
  };

  const remove = async (set: SampleDataset) => {
    setJob({ id: set.id, step: "Removing…", sent: 0 });
    try {
      await removeAll(cluster.id, set);
      if (!alive.current) return;
      setJob(null);
      if (selected === set.id) setSelected(null);
      onChanged(set.id, false);
    } catch (e) {
      setJob({ id: set.id, step: "", sent: 0, error: e instanceof Error ? e.message : String(e) });
    }
  };

  return (
    <Panel
      title="Sample data"
      aside={
        <span className="flex items-center gap-2">
          <span className="hidden text-[12px] text-subtle sm:inline">generated by roll, yours to delete</span>
          {onClose && (
            <button onClick={onClose} className="rounded-md p-1 text-subtle transition hover:text-fg" title="Close" aria-label="Close sample data">
              <X className="size-3.5" />
            </button>
          )}
        </span>
      }
    >
      <div className="grid gap-3 px-5 py-4 sm:grid-cols-2">
        {SAMPLES.map((s) => {
          const on = present.has(s.id);
          const mine = job?.id === s.id ? job : null;
          return (
            <div key={s.id} className={`flex flex-col gap-3 rounded-lg border p-4 transition ${s.id === shown?.id ? "border-line-2 bg-panel-2/60" : "border-line"}`}>
              <div className="min-w-0 space-y-1">
                <p className="flex items-baseline justify-between gap-2">
                  <span className="text-[14px] font-medium">{s.title}</span>
                  <span className="truncate font-mono text-[11px] text-subtle">
                    {s.kind} {s.id}
                  </span>
                </p>
                <p className="text-[13px] text-muted">{s.about}</p>
              </div>
              {mine && !mine.error ? (
                <div className="mt-auto space-y-1.5" role="status">
                  <div className="h-1 overflow-hidden rounded-full bg-line">
                    <div className="h-full rounded-full bg-accent transition-[width] duration-300 motion-reduce:transition-none" style={{ width: `${(mine.sent / s.docs) * 100}%` }} />
                  </div>
                  <p className="font-mono text-[11px] text-subtle">
                    <span className="shimmer">{mine.step}</span>
                    {mine.step === "Indexing" && ` ${formatCount(mine.sent)} of ${formatCount(s.docs)}`}
                  </p>
                </div>
              ) : (
                <div className="mt-auto flex flex-wrap items-center gap-2">
                  {on ? (
                    <>
                      <button onClick={() => setSelected(s.id)} disabled={busy} className={s.id === shown?.id ? primary : btn}>
                        <Play className="size-3.5" /> Try a query
                      </button>
                      <button onClick={() => remove(s)} disabled={busy} className={`${btn} hover:border-danger/50 hover:text-danger`} title={`Delete the ${s.kind} ${s.id}`}>
                        <Trash2 className="size-3.5" /> Remove
                      </button>
                      <button onClick={() => load(s)} disabled={busy} className="text-[12px] text-subtle transition hover:text-fg disabled:opacity-40">
                        Reload
                      </button>
                    </>
                  ) : (
                    <button onClick={() => load(s)} disabled={busy} className={primary}>
                      Load {formatCount(s.docs)} documents
                    </button>
                  )}
                </div>
              )}
              {mine?.error && <p className="text-[12px] text-danger">{mine.error}</p>}
            </div>
          );
        })}
      </div>
      {shown && (
        <FirstQueries
          key={shown.id}
          cluster={cluster}
          set={shown}
          onOpenConsole={onOpenConsole}
          keyLine={<KeyLine cluster={cluster} made={key} onMake={makeKey} onSaved={() => key && "key" in key && setKey({ ...key, open: false })} onManage={onManageKeys} />}
          snippetKey={key && "key" in key ? snippetKey(key.key) : undefined}
        />
      )}
      <p className="border-t border-line px-5 py-3 text-[12px] text-subtle">
        Remove deletes the index (products) or the data stream and its template (logs). Nothing else on the cluster changes.
      </p>
    </Panel>
  );
}

/** Deletes what the dataset made; what's already gone is fine. */
async function removeAll(id: string, set: SampleDataset) {
  for (const r of set.remove) {
    const res = await searchApi.request(id, r.method, r.path);
    if (res.status < 400 || res.status === 404) continue;
    let body: unknown = res.body;
    try {
      body = JSON.parse(res.body);
    } catch {
      // Not JSON: the status says enough.
    }
    throw new Error(esReason(body, res.status));
  }
}

type Outcome = { ok: true; took: number | null; value: unknown } | { ok: false; error: string };

/** Where the copied code's credentials come from: a key made in place, shown once. */
function KeyLine({ cluster, made, onMake, onSaved, onManage }: { cluster: SearchCluster; made: MadeKey | null; onMake: () => void; onSaved: () => void; onManage: () => void }) {
  const { copied, copy } = useCopy();
  const manage = (
    <button onClick={onManage} className="text-subtle transition hover:text-fg">
      manage keys
    </button>
  );
  if (made && "key" in made) {
    const k = made.key;
    const expires = k.expires_at ? ` · expires ${day(k.expires_at * 1000)}` : "";
    if (!made.open) {
      return (
        <p className="text-[11px] text-subtle">
          The code carries the data key <span className="font-mono">{k.name}</span>
          {expires}. {manage}
        </p>
      );
    }
    return (
      <div className="rise space-y-2.5 rounded-lg border border-line bg-bg p-3" role="group" aria-label="New key">
        <div className="flex items-center justify-between gap-3">
          <span className="flex items-center gap-2 text-[12px] font-medium">
            <KeyRound className="size-3.5 text-accent" /> A data key for {k.name}
          </span>
          <span className="text-[11px] text-subtle">shown once</span>
        </div>
        {k.api_key ? (
          <SecretField id="key" value={k.api_key} masked="••••••••••••••••••••••••" copied={copied} onCopy={copy} />
        ) : (
          <div className="grid gap-2 sm:grid-cols-2">
            <SecretField id="user" value={k.username ?? ""} masked={k.username ?? ""} copied={copied} onCopy={copy} />
            <SecretField id="pw" value={k.password ?? ""} masked="••••••••••••••••••••••••" copied={copied} onCopy={copy} />
          </div>
        )}
        <p className="text-[11px] text-muted">
          Copied code now carries it{expires}. roll can&apos;t show it again: save it, or revoke it in Settings.
        </p>
        <div className="flex items-center gap-3 text-[11px]">
          {manage}
          <button onClick={onSaved} className={`${btn} ml-auto`}>
            I&apos;ve saved it
          </button>
        </div>
      </div>
    );
  }
  return (
    <p className="text-[11px] text-subtle">
      The code reads {cluster.flavor === "opensearch" ? "$OPENSEARCH_USERNAME and $OPENSEARCH_PASSWORD" : `$${KEY_ENV}`}, never a real key.{" "}
      {made && "making" in made ? (
        <span className="shimmer">Making a key…</span>
      ) : (
        <button onClick={onMake} className="inline-flex items-center gap-1 text-accent hover:underline">
          <KeyRound className="size-3" /> Make a key
        </button>
      )}{" "}
      · {manage}
      {made && "error" in made && <span className="block text-danger">{made.error}</span>}
    </p>
  );
}

/** Three ready queries on a loaded dataset, each runnable in place. */
function FirstQueries({
  cluster,
  set,
  onOpenConsole,
  keyLine,
  snippetKey,
}: {
  cluster: SearchCluster;
  set: SampleDataset;
  onOpenConsole: (text: string) => void;
  keyLine: ReactNode;
  snippetKey: SnippetKey | undefined;
}) {
  const queries = set.queries(cluster.flavor);
  const [at, setAt] = useState(queries[0].id);
  const [results, setResults] = useState<Record<string, Outcome | "running">>({});
  const { copied, copy } = useCopy();
  const q = queries.find((x) => x.id === at) ?? queries[0];
  const text = consoleText(q.request.method, q.request.path, q.request.body);

  const run = async (query: SampleQuery) => {
    setResults((r) => ({ ...r, [query.id]: "running" }));
    const started = performance.now();
    let out: Outcome;
    try {
      const { value } = await esRaw(cluster.id, query.request.method, query.request.path, query.request.body);
      const took = (value as { took?: number } | null)?.took;
      out = { ok: true, took: typeof took === "number" ? took : Math.round(performance.now() - started), value };
    } catch (e) {
      out = { ok: false, error: e instanceof Error ? e.message : String(e) };
    }
    setResults((r) => ({ ...r, [query.id]: out }));
  };

  // Each query runs the first time it's picked, so its results are there without a click.
  useEffect(() => {
    if (results[q.id] === undefined) run(q);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [q.id]);

  const result = results[q.id];
  const esql = q.request.path === "/_query";
  const snippet = (lang: (typeof SNIPPET_LANGUAGES)[number]) =>
    esql
      ? esqlSnippet(lang, (q.request.body as { query: string }).query, cluster.url, snippetKey && "apiKey" in snippetKey ? snippetKey.apiKey : undefined)
      : copyAs(lang, { method: q.request.method, path: q.request.path, body: JSON.stringify(q.request.body) }, { url: cluster.url, flavor: cluster.flavor, key: snippetKey });

  return (
    <div className="rise border-t border-line">
      <div className="flex gap-1 overflow-x-auto px-5 pt-3" role="tablist" aria-label={`Queries on ${set.title.toLowerCase()}`}>
        {queries.map((x, i) => (
          <button
            key={x.id}
            role="tab"
            aria-selected={x.id === q.id}
            onClick={() => setAt(x.id)}
            className={`shrink-0 rounded-md px-2.5 py-1 text-[12px] transition ${x.id === q.id ? "bg-panel-2 text-fg" : "text-muted hover:text-fg"}`}
          >
            <span className="mr-1.5 font-mono text-subtle">{i + 1}</span>
            {x.title}
          </button>
        ))}
      </div>
      <div className="grid gap-4 px-5 py-4 lg:grid-cols-2">
        <div className="min-w-0 space-y-2">
          <p className="text-[13px] text-muted">{q.about}</p>
          <pre className="max-h-72 overflow-auto rounded-lg border border-line bg-bg px-3 py-2 font-mono text-[12px] leading-relaxed">
            <span className="text-muted">
              {q.request.method} {q.request.path}
            </span>
            {"\n"}
            {esql ? <span className="text-muted">{(q.request.body as { query: string }).query}</span> : <JsonText text={JSON.stringify(q.request.body, null, 2)} />}
          </pre>
          <div className="flex flex-wrap items-center gap-2">
            <button onClick={() => run(q)} disabled={result === "running"} className={primary}>
              <Play className="size-3.5" /> Run
            </button>
            <button onClick={() => onOpenConsole(text)} className={btn}>
              <SquareTerminal className="size-3.5" /> Open in Console
            </button>
            <span className="flex items-center gap-1 text-[12px] text-subtle">
              Copy as
              {SNIPPET_LANGUAGES.map((lang) => (
                <button key={lang} onClick={() => copy(lang, snippet(lang))} className="rounded-md px-1.5 py-0.5 font-mono text-[11px] text-muted transition hover:bg-panel-2 hover:text-fg">
                  {copied === lang ? "copied" : lang}
                </button>
              ))}
            </span>
          </div>
          {keyLine}
        </div>
        <div className="min-w-0" aria-live="polite">
          {result === undefined || result === "running" ? (
            <p className="py-2 text-[13px] text-subtle">
              <span className="shimmer">Running…</span>
            </p>
          ) : result.ok ? (
            <Results value={result.value} took={result.took} />
          ) : (
            <p className="rounded-lg border border-danger/40 bg-danger/10 px-3 py-2 text-[13px] text-danger">{result.error}</p>
          )}
        </div>
      </div>
    </div>
  );
}

