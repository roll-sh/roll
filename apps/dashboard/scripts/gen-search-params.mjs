// Generates src/lib/search-params.generated.ts: the URL query parameters of the Elasticsearch
// REST APIs the console completes, from Elasticsearch's REST API spec (rest-api-spec/api/*.json,
// downloaded by scripts/search-yaml-suites.sh into target/search-yaml/es-<version>/).
// Only facts of the API are kept (paths, methods, parameter names, types and allowed values);
// no descriptions.
//
//   node apps/dashboard/scripts/gen-search-params.mjs target/search-yaml/es-9.5.5/rest-api-spec/api
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) throw new Error("usage: gen-search-params.mjs <rest-api-spec/api dir>");
const NAMESPACES = new Set(["", "indices", "cat", "cluster", "nodes", "tasks", "ingest", "snapshot", "enrich", "async_search"]);
const METHODS = ["GET", "POST", "PUT", "DELETE", "HEAD"];

const common = JSON.parse(readFileSync(join(dir, "_common.json"), "utf8")).params;
const params = []; // [name, type, options?]
const paramIds = new Map();
function paramId(name, p) {
  const type = p.type === "enum" ? "enum" : p.type === "boolean" ? "boolean" : ["number", "int", "long", "double"].includes(p.type) ? "number" : p.type === "time" ? "time" : p.type === "list" ? "list" : "string";
  const opts = (type === "enum" || type === "list") && Array.isArray(p.options) ? p.options.map(String) : undefined;
  const key = JSON.stringify([name, type, opts]);
  if (!paramIds.has(key)) {
    paramIds.set(key, params.length);
    params.push(opts ? [name, type, opts] : [name, type]);
  }
  return paramIds.get(key);
}
const commonIds = Object.entries(common).map(([n, p]) => paramId(n, p));

const apis = []; // [methodsMask, path, paramIds]
for (const f of readdirSync(dir).sort()) {
  if (!f.endsWith(".json") || f.startsWith("_")) continue;
  const spec = JSON.parse(readFileSync(join(dir, f), "utf8"));
  const [name, api] = Object.entries(spec)[0];
  const ns = name.includes(".") ? name.split(".")[0] : "";
  if (!NAMESPACES.has(ns) || api.visibility === "private") continue;
  const ids = Object.entries(api.params ?? {})
    .map(([n, p]) => paramId(n, p))
    .sort((a, b) => a - b);
  for (const p of api.url.paths) {
    const mask = p.methods.reduce((m, x) => m | (1 << METHODS.indexOf(x)), 0);
    apis.push([mask, p.path, ids]);
  }
}

const out = `// Generated by apps/dashboard/scripts/gen-search-params.mjs from Elasticsearch's REST API spec. Do not edit.
// Parameters: [name, type, allowed values (enums, lists of enums)?]. APIs: [methods (bit i = ${METHODS.join(", ")}), path, parameter indexes].

export type ParamType = "boolean" | "enum" | "number" | "time" | "list" | "string";
export type ParamSpec = readonly [string, ParamType] | readonly [string, ParamType, readonly string[]];

export const PARAMS: readonly ParamSpec[] = ${JSON.stringify(params)};

export const COMMON_PARAMS: readonly number[] = ${JSON.stringify(commonIds)};

export const API_PATHS: readonly (readonly [number, string, readonly number[]])[] = ${JSON.stringify(apis)};
`;
writeFileSync(new URL("../src/lib/search-params.generated.ts", import.meta.url), out);
console.log(`${apis.length} paths, ${params.length} parameters, ${out.length} bytes`);
