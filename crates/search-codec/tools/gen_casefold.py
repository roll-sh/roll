#!/usr/bin/env python3
"""Generates src/automaton/casefold.rs: the case variants Lucene's RegExp CASE_INSENSITIVE matching
expands every character to (CaseFolding.expand: the character, Java's simple upper and lower case
mappings, and a table of special variants such as KELVIN SIGN for k).

Usage: python3 -I tools/gen_casefold.py UnicodeData.txt CaseFolding.java > src/automaton/casefold.rs
  UnicodeData.txt: https://www.unicode.org/Public/16.0.0/ucd/UnicodeData.txt (Java's
  Character.toUpperCase/toLowerCase use its simple mappings)
  CaseFolding.java: lucene/core/src/java/org/apache/lucene/util/automaton/CaseFolding.java
  (Apache-2.0; only its table of special variants is read)
"""

import re
import sys

ucd, lucene = sys.argv[1], sys.argv[2]
upper, lower = [], []
for line in open(ucd, encoding="utf-8"):
    f = line.rstrip("\n").split(";")
    cp = int(f[0], 16)
    if f[12]:
        upper.append((cp, int(f[12], 16)))
    if f[13]:
        lower.append((cp, int(f[13], 16)))

src = open(lucene, encoding="utf-8").read()
body = src[src.index("switch (c)"):]
special = []
for key, block in re.findall(r"case (0x[0-9A-Fa-f]+):(.*?)break;", body, re.S):
    for v in re.findall(r"fn\.accept\((0x[0-9A-Fa-f]+)\)", block):
        special.append((int(key, 16), int(v, 16)))
special.sort()


def table(name, pairs, doc):
    out = ["/// %s" % doc, "pub(crate) static %s: &[(u32, u32)] = &[" % name]
    row = []
    for a, b in pairs:
        row.append("(0x%X, 0x%X)," % (a, b))
        if len(row) == 6:
            out.append("    " + " ".join(row))
            row = []
    if row:
        out.append("    " + " ".join(row))
    out.append("];")
    return "\n".join(out)


print("//! Case variants for Lucene's case-insensitive `RegExp` matching (`CaseFolding.expand`),")
print("//! generated by `tools/gen_casefold.py` from UnicodeData.txt 16.0.0 (Java's simple case")
print("//! mappings) and Lucene's table of special variants. Do not edit.")
print()
print(table("SIMPLE_UPPER", upper, "Simple uppercase mappings (`Character.toUpperCase`), sorted by code point."))
print()
print(table("SIMPLE_LOWER", lower, "Simple lowercase mappings (`Character.toLowerCase`), sorted by code point."))
print()
print(table("SPECIAL", special, "Extra variants beyond the simple mappings, sorted by code point (keys repeat)."))
