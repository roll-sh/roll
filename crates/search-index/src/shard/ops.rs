//! Write operations and their outcomes, with Elasticsearch's versioning rules.
//!
//! Version checks follow `InternalEngine.planIndexingAsPrimary` / `planDeletionAsPrimary` and
//! `VersionType` exactly: `if_seq_no`/`if_primary_term` compare-and-set, `op_type=create`
//! (internally `MATCH_DELETED`), external versions (`external`: newer only, `external_gte`:
//! newer or equal). Outcomes are data ([`OpResult`]); [`VersionConflict::reason`] renders
//! Elasticsearch's message for `version_conflict_engine_exception` (status 409).

use bytes::Bytes;

use crate::doc::IndexableDoc;

/// `Versions.MATCH_ANY`.
pub const MATCH_ANY: i64 = -3;
/// `Versions.NOT_FOUND`.
pub const NOT_FOUND: i64 = -1;
/// `SequenceNumbers.UNASSIGNED_SEQ_NO`.
pub const UNASSIGNED_SEQ_NO: i64 = -2;
/// `SequenceNumbers.NO_OPS_PERFORMED`.
pub const NO_OPS_PERFORMED: i64 = -1;

/// `version_type`.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum VersionType {
    #[default]
    Internal,
    External,
    ExternalGte,
}

/// `op_type` of an index operation.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum OpType {
    #[default]
    Index,
    /// Fails if the document exists.
    Create,
}

/// Who issued an operation.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum Origin {
    /// A client write: checks versions and assigns the next sequence number.
    #[default]
    Primary,
    /// A replayed (WAL recovery) or replicated operation: it carries its sequence number,
    /// term and resulting version; stale operations (older than the doc's current state) are
    /// skipped, operations apply in any order.
    Replay { seq_no: i64, primary_term: i64, version: i64 },
}

/// Index (create or overwrite) a document.
#[derive(Clone, Debug, Default)]
pub struct IndexOp {
    pub doc: IndexableDoc,
    pub op_type: OpType,
    /// Expected version (`version` parameter); `None` = `MATCH_ANY`.
    pub version: Option<i64>,
    pub version_type: VersionType,
    pub if_seq_no: Option<i64>,
    pub if_primary_term: Option<i64>,
    pub origin: Origin,
    /// The id was generated by the server (append-only): no lookup of an existing version.
    pub auto_generated_id: bool,
}

impl IndexOp {
    pub fn new(doc: IndexableDoc) -> IndexOp {
        IndexOp { doc, ..Default::default() }
    }
}

/// Delete a document by id.
#[derive(Clone, Debug, Default)]
pub struct DeleteOp {
    pub id: Bytes,
    pub version: Option<i64>,
    pub version_type: VersionType,
    pub if_seq_no: Option<i64>,
    pub if_primary_term: Option<i64>,
    pub origin: Origin,
}

impl DeleteOp {
    pub fn new(id: impl Into<Bytes>) -> DeleteOp {
        DeleteOp { id: id.into(), ..Default::default() }
    }
}

/// Why an operation was rejected.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ConflictKind {
    /// `if_seq_no` / `if_primary_term` did not match; `current` is `None` when there is no doc.
    SeqNo { if_seq_no: i64, if_primary_term: i64, current: Option<(i64, i64)> },
    /// The version check of `version_type` failed (`current` is `-1` when not found).
    Version { version_type: VersionType, current: i64, expected: i64, deleted: bool },
    /// `op_type=create` on an existing doc.
    Exists { current: i64 },
}

/// A rejected write (`version_conflict_engine_exception`).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct VersionConflict {
    /// The `_id` bytes as the caller encoded them.
    pub id: Bytes,
    pub kind: ConflictKind,
}

impl VersionConflict {
    /// Elasticsearch's reason text, with the caller's rendering of the id.
    pub fn reason(&self, id: &str) -> String {
        match &self.kind {
            ConflictKind::SeqNo { if_seq_no, if_primary_term, current } => {
                let tail = match current {
                    None => "but no document was found".to_string(),
                    Some((s, t)) => format!("current document has seqNo [{s}] and primary term [{t}]"),
                };
                format!(
                    "[{id}]: version conflict, required seqNo [{if_seq_no}], primary term [{if_primary_term}]. {tail}"
                )
            }
            ConflictKind::Exists { current } => {
                format!("[{id}]: version conflict, document already exists (current version [{current}])")
            }
            ConflictKind::Version { version_type, current, expected, .. } => {
                let why = match version_type {
                    VersionType::Internal => {
                        format!("current version [{current}] is different than the one provided [{expected}]")
                    }
                    VersionType::External => {
                        format!("current version [{current}] is higher or equal to the one provided [{expected}]")
                    }
                    VersionType::ExternalGte => {
                        format!("current version [{current}] is higher than the one provided [{expected}]")
                    }
                };
                format!("[{id}]: version conflict, {why}")
            }
        }
    }
}

/// Outcome of a write.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum OpResult {
    /// Indexed: `created` is false when it replaced a live doc.
    Indexed { seq_no: i64, primary_term: i64, version: i64, created: bool },
    /// Deleted: `found` is false when there was no live doc (Elasticsearch `not_found`; the
    /// operation still gets a sequence number and a tombstone).
    Deleted { seq_no: i64, primary_term: i64, version: i64, found: bool },
    /// Rejected by a version check; no sequence number was used.
    Conflict(VersionConflict),
    /// A replayed operation older than the doc's current state: nothing changed, but its
    /// sequence number is marked processed.
    Stale { seq_no: i64 },
}

/// `VersionType.isVersionConflictForWrites`.
pub fn is_conflict(vt: VersionType, current: i64, expected: i64, _deleted: bool) -> bool {
    match vt {
        VersionType::Internal => {
            if expected == MATCH_ANY {
                false
            } else {
                current != expected
            }
        }
        VersionType::External => {
            if current == NOT_FOUND {
                false
            } else if expected == MATCH_ANY {
                true
            } else {
                current >= expected
            }
        }
        VersionType::ExternalGte => {
            if current == NOT_FOUND {
                false
            } else if expected == MATCH_ANY {
                true
            } else {
                current > expected
            }
        }
    }
}

/// `VersionType.updateVersion`.
pub fn update_version(vt: VersionType, current: i64, expected: i64) -> i64 {
    match vt {
        VersionType::Internal => {
            if current == NOT_FOUND {
                1
            } else {
                current + 1
            }
        }
        _ => expected,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn version_rules() {
        assert!(!is_conflict(VersionType::Internal, 5, MATCH_ANY, false));
        assert!(is_conflict(VersionType::Internal, 5, 4, false));
        assert!(!is_conflict(VersionType::External, NOT_FOUND, 3, true));
        assert!(is_conflict(VersionType::External, 3, 3, false));
        assert!(!is_conflict(VersionType::External, 3, 4, false));
        assert!(!is_conflict(VersionType::ExternalGte, 3, 3, false));
        assert!(is_conflict(VersionType::ExternalGte, 4, 3, false));
        assert_eq!(update_version(VersionType::Internal, NOT_FOUND, MATCH_ANY), 1);
        assert_eq!(update_version(VersionType::Internal, 4, MATCH_ANY), 5);
        assert_eq!(update_version(VersionType::External, 4, 9), 9);
        let c = VersionConflict {
            id: Bytes::from_static(b"1"),
            kind: ConflictKind::SeqNo { if_seq_no: 3, if_primary_term: 1, current: None },
        };
        assert_eq!(
            c.reason("1"),
            "[1]: version conflict, required seqNo [3], primary term [1]. but no document was found"
        );
    }
}
