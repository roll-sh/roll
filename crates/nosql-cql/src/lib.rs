//! The CQL language of Apache Cassandra 5.0 and ScyllaDB 2026.x: a lexer, a parser and the
//! syntax tree, with the syntax errors each server reports.
//!
//! - [`parse_statement`] parses one statement the way a server parses the text of a `QUERY` or
//!   `PREPARE` message: one statement, optionally followed by `;`. On failure the
//!   [`SyntaxError`] carries the reference's exact message, for example Cassandra's
//!   `line 1:9 mismatched input 'FRM' expecting K_FROM (SELECT * [FRM]...)` or ScyllaDB's
//!   `line 1:9 : Missing K_FROM`.
//! - [`parse`] splits a script on `;` (keeping `BEGIN BATCH ... APPLY BATCH` whole) and parses
//!   each statement as a server would, so errors are positioned within their statement, as
//!   `cqlsh` reports them.
//! - [`Dialect`] selects the grammar: keywords (and which are reserved), statements and clauses
//!   only one product has, the lexer's differences and the error format. Syntax of the other
//!   product fails with the error that product's server gives; the tree records
//!   dialect-specific syntax so the engine can tell what a statement uses.
//!
//! The tree ([`ast`]) keeps names and literals as written; the engine resolves them. Every node
//! prints back as valid CQL ([`display`]). Bind markers are numbered in source order.
//!
//! # How the errors match
//!
//! Cassandra's parser is generated by ANTLR 3 from `Parser.g`, and its messages depend on how
//! the generated code decides (inline tests or prediction tables), how far it has looked ahead
//! (the snippet), and what its actions do after an error (a few `NullPointerException`s). The
//! parser here ports the generated control flow rule by rule, runs the same prediction tables
//! (extracted by `tools/gen_dfa.py`), rebuilds the snippet from the fetched token stream, and
//! reproduces the actions' checks and the common post-error exceptions.
//!
//! ScyllaDB's parser is also ANTLR 3 (C++ target) with its own grammar and reporting. Its source
//! is not used: its behaviour was learnt from the 2026.3.3 image (keywords per context, every
//! clause, thousands of malformed statements). It reports no snippet, "no viable alternative" at
//! the token where a decision started (or, for a few decisions, where it failed), and failed
//! matches through single-token recovery: `Unexpected 'x'`, `Missing X` or `Syntax error`. Its
//! token stream is lexed before parsing, so a lexer error always wins.
//!
//! `tests/data/*_reference.tsv` hold over 6,000 statements per dialect with the reference's
//! answer; `tests/reference.rs` requires the same answer for all but `*_known_gaps.txt`:
//!
//! - Cassandra resolves `FUNCTION ks.f(types)` resources against the schema while parsing
//!   (`Keyspace ks doesn't exist`); the engine has to.
//! - ScyllaDB validates service level and table properties while preparing, with
//!   `SyntaxException`s (`Unknown property 'x'`, `marshaling error: Unable to convert 'x' to a
//!   duration`); the engine has to. It also reports `Multiple incompatible setting of column x`
//!   (an invalid request) when preparing, where Cassandra rejects it while parsing.
//! - ScyllaDB ignores an unwanted empty string literal in some positions (`MBEAN '' TO r`).
//!
//! Beyond the corpora: Cassandra keeps parsing after an error and a handful of its later
//! `NullPointerException`s are not reproduced (they need a missing name followed by more
//! syntax); deeply nested statements (over 128 levels) fail with a stack overflow message where
//! Cassandra's own parser takes exponential time.
//!
//! `examples/cql_check.rs` prints this parser's answer for a file of statements, to compare with
//! a reference.
//!
//! # Performance
//!
//! Lexing is a single pass; prediction looks a bounded number of tokens ahead; syntactic
//! predicates are memoised per position, so parsing is linear in the input. The tree borrows
//! from the query text ([`IntoStatic`] detaches it). Input is never trusted: no panic is
//! reachable, and nesting is bounded.

