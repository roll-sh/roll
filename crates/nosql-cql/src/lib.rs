/// The product whose CQL dialect to parse.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub enum Dialect {
    /// ScyllaDB 2026.x.
    #[default]
    Scylla,
    /// Apache Cassandra 5.0.
    Cassandra,
}

/// Parses a script of `;`-separated statements. Each statement is parsed on its own text, as a
/// client that splits scripts sends them; spans are relative to `src`.
pub fn parse(src: &str, dialect: Dialect) -> Result<Vec<Statement<'_>>, SyntaxError> {
    let mut out = Vec::new();
    for (start, end) in split_statements(src, dialect) {
        let piece = &src[start..end];
        let mut stmt = parse_statement(piece, dialect)?;
        stmt.span = Span { start: start as u32 + stmt.span.start, end: start as u32 + stmt.span.end };
        out.push(stmt);
    }
    Ok(out)
}

/// The byte ranges of the statements of a script: split at top-level `;`, except inside
/// `BEGIN ... APPLY BATCH`. Empty statements are skipped.
pub fn split_statements(src: &str, dialect: Dialect) -> Vec<(usize, usize)> {
    use tokens as t;
    let lexed = lexer::lex(src, dialect, false);
    let mut out = Vec::new();
    let mut start: Option<usize> = None;
    let mut in_batch = false;
    let mut after_last = 0usize;
    let toks = &lexed.tokens;
    for (i, tok) in toks.iter().enumerate() {
        if tok.ty == t::EOF {
            break;
        }
        if start.is_none() {
            if tok.ty == t::SEMI {
                after_last = tok.end as usize;
                continue;
            }
            start = Some(tok.start as usize);
            in_batch = tok.ty == t::K_BEGIN;
        }
        if tok.ty == t::K_APPLY && toks.get(i + 1).is_some_and(|n| n.ty == t::K_BATCH) {
            in_batch = false;
        }
        if tok.ty == t::SEMI && !in_batch {
            if let Some(s) = start.take() {
                out.push((s, tok.start as usize));
            }
            after_last = tok.end as usize;
        }
    }
    if let Some(s) = start {
        // The rest of the input, including anything the lexer could not tokenise.
        out.push((s, src.len()));
    } else if lexed.error.is_some() {
        out.push((after_last, src.len()));
    }
    out
}

