#!/usr/bin/env python3
"""Generate src/parser/dfa_tables.rs from the parser ANTLR 3.5.2 builds for Cassandra's Cql.g.

Cassandra's build runs:
    java -cp antlr-complete-3.5.2.jar org.antlr.Tool -Xconversiontimeout 10000 \
         -Xmaxinlinedfastates 10 -o out Cql.g
on src/antlr/{Cql,Parser,Lexer}.g. Run that, then:
    python3 tools/gen_dfa.py out/Cql_Parser.java > src/parser/dfa_tables.rs

The tables keep ANTLR's run-length packing (pairs of count, value); the parser unpacks them once.
"""
import re
import sys

src = open(sys.argv[1]).read()


def java_unescape(s):
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c == '\\':
            n = s[i + 1]
            if n == 'u':
                out.append(int(s[i + 2:i + 6], 16)); i += 6
            elif n in '01234567':
                j = i + 1
                while j < len(s) and j < i + 4 and s[j] in '01234567':
                    j += 1
                out.append(int(s[i + 1:j], 8)); i = j
            else:
                out.append({'n': 10, 't': 9, 'r': 13, '"': 34, "'": 39, '\\': 92, 'b': 8, 'f': 12}[n]); i += 2
        else:
            out.append(ord(c)); i += 1
    return out


def get_str(name):
    m = re.search(r'static final String ' + re.escape(name) + r' =\s*((?:"(?:[^"\\]|\\.)*"\s*\+?\s*)+);', src)
    return java_unescape(''.join(re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1))))


def get_arr(name):
    m = re.search(r'static final String\[\] ' + re.escape(name) + r' = \{(.*?)\};', src, re.S)
    items = re.findall(r'((?:"(?:[^"\\]|\\.)*"\s*\+?\s*)+)(?:,|$)', m.group(1))
    return [java_unescape(''.join(re.findall(r'"((?:[^"\\]|\\.)*)"', it))) for it in items]


def arr(v):
    return '&[' + ', '.join(str(x) for x in v) + ']'


print('//! Prediction tables for the decisions ANTLR 3.5.2 compiles to table-driven DFAs when it builds')
print('//! Cassandra 5.0.9\'s `Parser.g` (Apache-2.0) with Cassandra\'s build flags. Generated by')
print('//! `tools/gen_dfa.py`; do not edit. Each array keeps ANTLR\'s packing: (count, value) pairs.')
print()
print('use std::sync::OnceLock;')
print()
print('use super::dfa::Dfa;')
print()
for m in re.finditer(r'protected class DFA(\d+) extends DFA', src):
    d = int(m.group(1))
    body = re.search(r'protected class DFA%d extends DFA.*?(?=protected class DFA|\Z)' % d, src, re.S).group(0)
    desc = re.search(r'return "(.*?)";', body).group(1)
    specials = []
    for cm in re.finditer(r'case (\d+) :.*?if \( \(synpred(\d+)_Parser\(\)\) \) \{s = (\d+);\}\s*else if \( \(true\) \) \{s = (\d+);\}', body, re.S):
        specials.append((int(cm.group(1)), int(cm.group(2)), int(cm.group(3)), int(cm.group(4))))
    trans = get_arr(f'DFA{d}_transitionS')
    print(f'/// `{desc[:100]}`')
    print(f'pub(crate) static DFA{d}: Dfa = Dfa {{')
    print(f'    decision: {d},')
    for f in ('eot', 'eof', 'min', 'max', 'accept', 'special'):
        print(f'    {f}: {arr(get_str(f"DFA{d}_{f}S"))},')
    print('    transition: &[')
    for t in trans:
        print(f'        {arr(t)},')
    print('    ],')
    print('    specials: &[' + ', '.join(f'({a}, {b}, {c}, {e})' for a, b, c, e in specials) + '],')
    print('    cache: OnceLock::new(),')
    print('};')
    print()
