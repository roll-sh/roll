//! Builds the vendored Lua 5.4 core (base, coroutine, string and table libraries) and our glue
//! into one static library.
//!
//! rolld links this and `redis-lua` (Lua 5.1) into the same binary, and both export Lua's
//! symbol names. So the core is compiled as one translation unit with its internal functions
//! `static` (as Lua's own `onelua.c` does), and every public API name (`lua_*`, `luaL_*`,
//! `luaopen_*`) is renamed `nosql_<name>` by a header forced into each unit; `src/lib.rs`
//! links to the renamed symbols.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::PathBuf;

const CORE: &[&str] = &[
    "lzio", "lctype", "lopcodes", "lmem", "lundump", "ldump", "lstate", "lgc", "llex", "lcode", "lparser", "ldebug",
    "lfunc", "lobject", "ltm", "lstring", "ltable", "ldo", "lvm", "lapi", "lauxlib", "lbaselib", "lcorolib", "lstrlib",
    "ltablib",
];

/// The API functions a header declares (`LUA_API int (lua_gettop) (lua_State *L);`, and
/// `LUALIB_API` / `LUAMOD_API` likewise).
fn api_names(header: &str, out: &mut BTreeSet<String>) {
    let text = std::fs::read_to_string(header).expect("lua header");
    for line in text.lines().map(str::trim_start) {
        if !["LUA_API", "LUALIB_API", "LUAMOD_API"].iter().any(|m| line.starts_with(m)) {
            continue;
        }
        let Some(open) = line.find("(lua") else { continue };
        let rest = &line[open + 1..];
        let end = rest.find(|c: char| !(c.is_ascii_alphanumeric() || c == '_')).unwrap_or(rest.len());
        if rest[end..].starts_with(')') {
            out.insert(rest[..end].to_string());
        }
    }
}

fn main() {
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let mut names = BTreeSet::from(["lua_ident".to_string()]);
    for h in ["lua/lua.h", "lua/lauxlib.h", "lua/lualib.h"] {
        println!("cargo:rerun-if-changed={h}");
        api_names(h, &mut names);
    }
    let mut prefix = String::from("/* generated by build.rs: Lua's API under roll nosql's names */\n");
    for n in &names {
        writeln!(prefix, "#define {n} nosql_{n}").unwrap();
    }
    let prefix_h = out.join("nosql_lua_prefix.h");
    std::fs::write(&prefix_h, prefix).unwrap();

    let mut one = String::from(
        "#include \"lprefix.h\"\n#include <assert.h>\n#include <ctype.h>\n#include <errno.h>\n#include <float.h>\n\
         #include <limits.h>\n#include <locale.h>\n#include <math.h>\n#include <setjmp.h>\n#include <signal.h>\n\
         #include <stdarg.h>\n#include <stddef.h>\n#include <stdio.h>\n#include <stdlib.h>\n#include <string.h>\n\
         #include <time.h>\n#define LUA_CORE\n#define LUA_LIB\n#define ltable_c\n#define lvm_c\n#include \"luaconf.h\"\n\
         #undef LUAI_FUNC\n#undef LUAI_DDEC\n#undef LUAI_DDEF\n#define LUAI_FUNC static\n#define LUAI_DDEC(def)\n\
         #define LUAI_DDEF static\n",
    );
    for f in CORE {
        println!("cargo:rerun-if-changed=lua/{f}.c");
        writeln!(one, "#include \"{f}.c\"").unwrap();
    }
    let one_c = out.join("nosql_onelua.c");
    std::fs::write(&one_c, one).unwrap();

    println!("cargo:rerun-if-changed=glue.c");
    cc::Build::new()
        .file(&one_c)
        .file("glue.c")
        .include("lua")
        .flag("-include")
        .flag(prefix_h.to_str().unwrap())
        .define("LUA_USE_POSIX", None)
        .opt_level(2)
        .warnings(false)
        .compile("lua54nosql");
}
