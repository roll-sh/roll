    fn sorted_and_found() {
        assert!(super::ACTIONS.windows(2).all(|w| w[0].0 < w[1].0));
        assert_eq!(super::action_name("connector.put"), Some("cluster:admin/xpack/connector/put"));
        assert_eq!(super::action_name("watcher.get_watch"), Some("cluster:monitor/xpack/watcher/watch/get"));
        assert_eq!(super::action_name("no.such_api"), None);
    }
