//! (`GET _cluster/settings?include_defaults`, plugins of the official image included). Whether
//! the cluster settings API may update each was checked against OpenSearch one by one (a
//! `null` update: dynamic ones are acknowledged, the others fail as not dynamically updateable,
//! final, or persistent-only). Generated; edit by hand only to track a new OpenSearch version.

