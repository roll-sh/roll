//! Generates the route tables from the vendored REST API specs: Elasticsearch's
//! (`spec/api/*.json`) and OpenSearch's (`spec/opensearch/api/*.json`).
//!
//! The output (`$OUT_DIR/spec.rs`) is an `Api` enum with one variant per API of either spec and
//! one static `ApiSpec` array per dialect indexed by it (an API a dialect lacks has an empty,
//! `present: false` entry), so request dispatch is a `match` on a `Copy` enum and no JSON is
//! parsed at startup. The path tries are built from these statics on first use (`routes.rs`).

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::Path;

fn load(dir: &Path) -> (BTreeMap<String, serde_json::Value>, serde_json::Value) {
    let mut files: Vec<_> = std::fs::read_dir(dir).unwrap().map(|e| e.unwrap().path()).filter(|p| p.extension().is_some_and(|e| e == "json")).collect();
    files.sort();
    let mut apis: BTreeMap<String, serde_json::Value> = BTreeMap::new();
    let mut common = serde_json::Value::Null;
    for f in &files {
        let v: serde_json::Value = serde_json::from_slice(&std::fs::read(f).unwrap()).unwrap_or_else(|e| panic!("{}: {e}", f.display()));
        if f.file_name().unwrap() == "_common.json" {
            common = v;
            continue;
        }
        for (name, api) in v.as_object().unwrap() {
            apis.insert(name.clone(), api.clone());
        }
    }
    (apis, common)
}

fn main() {
    let root = Path::new(&std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("spec");
    println!("cargo:rerun-if-changed=spec/api");
    println!("cargo:rerun-if-changed=spec/opensearch/api");
    let (es, es_common) = load(&root.join("api"));
    let (os, os_common) = load(&root.join("opensearch/api"));
    let names: BTreeSet<&String> = es.keys().chain(os.keys()).collect();

    let mut out = String::new();
    out.push_str("// @generated by build.rs from spec/api/*.json and spec/opensearch/api/*.json. Do not edit.\n\n");

    // The `Api` enum: every API of either dialect's spec.
    let mut variants = BTreeSet::new();
    out.push_str("/// Every API of the Elasticsearch and OpenSearch REST specs, in name order.\n");
    out.push_str("#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug, PartialOrd, Ord)]\n#[repr(u16)]\n#[allow(dead_code)]\npub enum Api {\n");
    for (i, name) in names.iter().enumerate() {
        let v = variant(name);
        assert!(variants.insert(v.clone()), "duplicate variant {v}");
        writeln!(out, "    /// `{name}`\n    {v} = {i},").unwrap();
    }
    out.push_str("}\n\n");
    writeln!(out, "pub const API_COUNT: usize = {};\n", names.len()).unwrap();
    out.push_str("pub static ALL_APIS: [Api; API_COUNT] = [\n");
    for name in &names {
        writeln!(out, "    Api::{},", variant(name)).unwrap();
    }
    out.push_str("];\n\n");
    out.push_str("pub static API_NAMES: [&str; API_COUNT] = [\n");
    for name in &names {
        writeln!(out, "    {name:?},").unwrap();
    }
    out.push_str("];\n\n");

    for (label, common) in [("COMMON_PARAMS", &es_common), ("OS_COMMON_PARAMS", &os_common)] {
        writeln!(out, "pub static {label}: &[ParamSpec] = &[").unwrap();
        let mut cp: Vec<_> = common["params"].as_object().unwrap().iter().collect();
        cp.sort_by(|a, b| a.0.cmp(b.0));
        for (n, p) in cp {
            out.push_str(&param(n, p));
        }
        out.push_str("];\n\n");
    }

    for (label, apis) in [("APIS", &es), ("OS_APIS", &os)] {
        writeln!(out, "pub static {label}: [ApiSpec; API_COUNT] = [").unwrap();
        for name in &names {
            match apis.get(*name) {
                Some(api) => spec(&mut out, name, api),
                None => {
                    writeln!(out, "    ApiSpec {{ name: {name:?}, present: false, stability: \"stable\", visibility: \"public\", body: BodySpec::None, accept: &[], content_type: &[], paths: &[], params: &[] }},").unwrap();
                }
            }
        }
        out.push_str("];\n\n");
    }

    let dest = Path::new(&std::env::var("OUT_DIR").unwrap()).join("spec.rs");
    std::fs::write(dest, out).unwrap();
}

fn spec(out: &mut String, name: &str, api: &serde_json::Value) {
    out.push_str("    ApiSpec {\n");
    writeln!(out, "        name: {name:?},").unwrap();
    out.push_str("        present: true,\n");
    writeln!(out, "        stability: {:?},", api["stability"].as_str().unwrap_or("stable")).unwrap();
    writeln!(out, "        visibility: {:?},", api["visibility"].as_str().unwrap_or("public")).unwrap();
    let body = match api.get("body") {
        None | Some(serde_json::Value::Null) => "BodySpec::None",
        Some(b) if b["required"].as_bool() == Some(true) => "BodySpec::Required",
        Some(_) => "BodySpec::Optional",
    };
    writeln!(out, "        body: {body},").unwrap();
    let strs = |v: &serde_json::Value| -> String {
        let items: Vec<String> = v.as_array().map(|a| a.iter().map(|s| format!("{:?}", s.as_str().unwrap())).collect()).unwrap_or_default();
        format!("&[{}]", items.join(", "))
    };
    writeln!(out, "        accept: {},", strs(&api["headers"]["accept"])).unwrap();
    writeln!(out, "        content_type: {},", strs(&api["headers"]["content_type"])).unwrap();
    out.push_str("        paths: &[\n");
    for p in api["url"]["paths"].as_array().unwrap() {
        let mut methods = Vec::new();
        for m in p["methods"].as_array().unwrap() {
            methods.push(format!("Method::{}.bit()", title(m.as_str().unwrap())));
        }
        out.push_str("            PathSpec {\n");
        writeln!(out, "                path: {:?},", p["path"].as_str().unwrap()).unwrap();
        writeln!(out, "                methods: {},", methods.join(" | ")).unwrap();
        writeln!(out, "                deprecated: {},", p.get("deprecated").is_some()).unwrap();
        out.push_str("                parts: &[");
        if let Some(parts) = p["parts"].as_object() {
            for (pn, pv) in parts {
                let ty = ptype(pv["type"].as_str().unwrap_or("string"));
                write!(out, "PartSpec {{ name: {pn:?}, ty: {ty}, options: {} }}, ", strs(&pv["options"])).unwrap();
            }
        }
        out.push_str("],\n            },\n");
    }
    out.push_str("        ],\n");
    out.push_str("        params: &[\n");
    if let Some(params) = api["params"].as_object() {
        let mut ps: Vec<_> = params.iter().collect();
        ps.sort_by(|a, b| a.0.cmp(b.0));
        for (n, p) in ps {
            out.push_str(&param(n, p));
        }
    }
    out.push_str("        ],\n");
    out.push_str("    },\n");
}

fn param(n: &str, p: &serde_json::Value) -> String {
    let ty = ptype(p["type"].as_str().unwrap_or("string"));
    let options: Vec<String> = p["options"].as_array().map(|a| a.iter().map(|s| format!("{:?}", s.as_str().unwrap_or_default())).collect()).unwrap_or_default();
    let default = match &p["default"] {
        serde_json::Value::Null => "None".to_string(),
        serde_json::Value::String(s) => format!("Some({s:?})"),
        other => format!("Some({:?})", other.to_string()),
    };
    let deprecated = p.get("deprecated").is_some();
    format!("            ParamSpec {{ name: {n:?}, ty: {ty}, options: &[{}], default: {default}, deprecated: {deprecated} }},\n", options.join(", "))
}

fn ptype(t: &str) -> &'static str {
    match t {
        "boolean" => "ParamType::Boolean",
        "time" => "ParamType::Time",
        "list" => "ParamType::List",
        "string" => "ParamType::String",
        "enum" => "ParamType::Enum",
        "int" => "ParamType::Int",
        "long" => "ParamType::Long",
        "date" => "ParamType::Date",
        "number" => "ParamType::Number",
        "double" => "ParamType::Double",
        "number|string" => "ParamType::NumberOrString",
        "boolean|long" => "ParamType::BooleanOrLong",
        other => panic!("unknown param type {other}"),
    }
}

fn title(m: &str) -> String {
    let mut s = m.to_ascii_lowercase();
    s[..1].make_ascii_uppercase();
    s
}

fn variant(name: &str) -> String {
    let mut out = String::new();
    for part in name.split(['.', '_']) {
        if part.is_empty() {
            continue;
        }
        let mut c = part.chars();
        out.extend(c.next().unwrap().to_uppercase());
        out.push_str(c.as_str());
    }
    out
}
