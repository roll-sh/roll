pub fn register(r: &mut Registry) {
    for &(name, op, left, right) in OP_FUNCS {
        if r.funcs.contains_key(name) {
            continue;
        }
        let Some(rt) = DataType::from_name(right) else {
            continue;
        };
        let (cands, inputs) = if left.is_empty() {
            (r.prefix.get(op), vec![rt])
        } else {
            let Some(lt) = DataType::from_name(left) else {
                continue;
            };
            (r.binops.get(op), vec![lt, rt])
        };
        let Some(cands) = cands else { continue };
        let Ok(Some(res)) = select_candidate(cands, &inputs, !left.is_empty()) else {
            continue;
        };
        r.next_oid += 1;
        let d = &res.def;
        let def = FuncDef {
            oid: r.next_oid,
            name,
            args: res.arg_types.clone(),
            variadic: false,
            spread: false,
            ret: Ret::Fixed(res.ret.clone()),
            strict: d.strict,
            volatility: d.volatility,
            imp: d.imp,
            min_args: res.arg_types.len(),
            srf: None,
            out_cols: Vec::new(),
            arg_names: Vec::new(),
            defaults: Vec::new(),
            coll: None,
        };
        r.funcs.entry(name).or_default().push(Arc::new(def));
    }
}
