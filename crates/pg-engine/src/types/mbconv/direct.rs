/// The second SJIS byte of a JIS X 0213 row ("ku") parity and cell ("ten").
fn sjis2004_odd_ten(ku: i32, ten: i32, s: &[u8], out: &mut Vec<u8>) -> Result<()> {
    if ku % 2 != 0 {
        if (1..=63).contains(&ten) {
            out.push((ten + 0x3f) as u8);
        } else if (64..=94).contains(&ten) {
            out.push((ten + 0x40) as u8);
        } else {
            return Err(invalid_encoding(EUC_JIS_2004, s));
        }
    } else {
        out.push((ten + 0x9e) as u8);
    }
    Ok(())
}

fn euc_jis_2004_to_sjis_2004(src: &[u8]) -> Result<Vec<u8>> {
    each_mb(src, EUC_JIS_2004, |s, l, out| {
        let c1 = s[0];
        if c1 == SS2 && l == 2 {
            out.push(s[1]);
        } else if c1 == SS3 && l == 3 {
            let ku = s[1] as i32 - 0xa0;
            let ten = s[2] as i32 - 0xa0;
            match ku {
                1 | 3 | 4 | 5 | 8 | 12 | 13 | 14 | 15 => {
                    out.push((((ku + 0x1df) >> 1) - (ku >> 3) * 3) as u8)
                }
                78..=94 => out.push(((ku + 0x19b) >> 1) as u8),
                _ => return Err(invalid_encoding(EUC_JIS_2004, s)),
            }
            sjis2004_odd_ten(ku, ten, s, out)?;
        } else if l == 2 {
            let ku = c1 as i32 - 0xa0;
            let ten = s[1] as i32 - 0xa0;
            match ku {
                1..=62 => out.push(((ku + 0x101) >> 1) as u8),
                63..=94 => out.push(((ku + 0x181) >> 1) as u8),
                _ => return Err(invalid_encoding(EUC_JIS_2004, s)),
            }
            sjis2004_odd_ten(ku, ten, s, out)?;
        } else {
            return Err(invalid_encoding(EUC_JIS_2004, s));
        }
        Ok(())
    })
}

/// `get_ten`: (ten, ku odd) of an SJIS second byte, ten -1 when invalid.
fn get_ten(b: i32) -> (i32, i32) {
    match b {
        0x40..=0x7e => (b - 0x3f, 1),
        0x80..=0x9e => (b - 0x40, 1),
        0x9f..=0xfc => (b - 0x9e, 0),
        _ => (-1, 0),
    }
}

fn sjis_2004_to_euc_jis_2004(src: &[u8]) -> Result<Vec<u8>> {
    each_mb(src, SHIFT_JIS_2004, |s, l, out| {
        let c1 = s[0] as i32;
        if (0xa1..=0xdf).contains(&c1) && l == 1 {
            out.extend_from_slice(&[SS2, c1 as u8]);
            return Ok(());
        }
        if l != 2 {
            return Ok(());
        }
        let (ten, kubun) = get_ten(s[1] as i32);
        let bad = || Err(invalid_encoding(SHIFT_JIS_2004, s));
        let (plane, ku) = match c1 {
            0x81..=0x9f => {
                if ten < 0 {
                    return bad();
                }
                (1, (c1 << 1) - 0x100 - kubun)
            }
            0xe0..=0xef => {
                if ten < 0 {
                    return bad();
                }
                (1, (c1 << 1) - 0x180 - kubun)
            }
            0xf0..=0xf3 => {
                if ten < 0 {
                    return bad();
                }
                let ku = match (c1, kubun == 0) {
                    (0xf0, true) => 8,
                    (0xf0, false) => 1,
                    (0xf1, true) => 4,
                    (0xf1, false) => 3,
                    (0xf2, true) => 12,
                    (0xf2, false) => 5,
                    (_, true) => 14,
                    (_, false) => 13,
                };
                (2, ku)
            }
            0xf4..=0xfc => {
                if ten < 0 {
                    return bad();
                }
                if c1 == 0xf4 && kubun == 1 {
                    (2, 15)
                } else {
                    (2, (c1 << 1) - 0x19a - kubun)
                }
            }
            _ => return bad(),
        };
        if plane == 2 {
            out.push(SS3);
        }
        out.extend_from_slice(&[(ku + 0xa0) as u8, (ten + 0xa0) as u8]);
        Ok(())
    })
}

