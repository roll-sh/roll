//! Postgres's direct conversions between encodings other than UTF-8
//! (conversion_procs/{cyrillic_and_mic,latin_and_mic,latin2_and_win1250,euc_cn_and_mic,
//! euc_kr_and_mic,euc_jp_and_sjis,euc_tw_and_big5,euc2004_sjis2004}), MULE_INTERNAL's
//! only conversions. Like the originals they recheck their input as they go.

use super::{
    BIG5, EUC_CN, EUC_JIS_2004, EUC_JP, EUC_KR, EUC_TW, ISO_8859_5, KOI8R, LATIN1, LATIN2,
    LATIN3, LATIN4, MULE_INTERNAL as MULE, SHIFT_JIS_2004, SJIS, SS2, SS3, WIN866, WIN1250,
    WIN1251, invalid_encoding, mule_mblen, untranslatable, verifychar,
};
use crate::error::Result;

const LC_ISO8859_1: u8 = 0x81;
const LC_ISO8859_2: u8 = 0x82;
const LC_ISO8859_3: u8 = 0x83;
const LC_ISO8859_4: u8 = 0x84;
const LC_JISX0201K: u8 = 0x89;
const LC_KOI8_R: u8 = 0x8b;
const LC_GB2312_80: u8 = 0x91;
const LC_JISX0208: u8 = 0x92;
const LC_KS5601: u8 = 0x93;
const LC_JISX0212: u8 = 0x94;
const LC_CNS11643_1: u8 = 0x95;
const LC_CNS11643_2: u8 = 0x96;
const LC_CNS11643_3: u8 = 0xf6;
const LC_CNS11643_4: u8 = 0xf7;
const LC_CNS11643_7: u8 = 0xfa;
const LCPRV2_B: u8 = 0x9d;
const PGSJISALTCODE: u16 = 0x81ac;
const PGEUCALTCODE: u16 = 0xa2ae;

/// Whether pg_conversion has a default conversion between the two (neither UTF-8 nor
/// SQL_ASCII).
pub fn exists(from: i32, to: i32) -> bool {
    matches!(
        (from, to),
        (BIG5, EUC_TW | MULE)
            | (EUC_CN | EUC_KR | LATIN1 | LATIN3 | LATIN4, MULE)
            | (EUC_JIS_2004, SHIFT_JIS_2004)
            | (SHIFT_JIS_2004, EUC_JIS_2004)
            | (EUC_JP, MULE | SJIS)
            | (SJIS, MULE | EUC_JP)
            | (EUC_TW, BIG5 | MULE)
            | (LATIN2, MULE | WIN1250)
            | (WIN1250, MULE | LATIN2)
            | (ISO_8859_5, KOI8R | MULE | WIN1251 | WIN866)
            | (KOI8R, ISO_8859_5 | MULE | WIN1251 | WIN866)
            | (WIN1251, ISO_8859_5 | KOI8R | MULE | WIN866)
            | (WIN866, ISO_8859_5 | KOI8R | MULE | WIN1251)
            | (
                MULE,
                BIG5 | EUC_CN
                    | EUC_JP
                    | EUC_KR
                    | EUC_TW
                    | LATIN1
                    | LATIN2
                    | LATIN3
                    | LATIN4
                    | ISO_8859_5
                    | KOI8R
                    | SJIS
                    | WIN1250
                    | WIN1251
                    | WIN866
            )
    )
}

/// The conversion from `from` to `to` (`exists` must hold).
pub fn convert(src: &[u8], from: i32, to: i32) -> Result<Vec<u8>> {
    match (from, to) {
        (LATIN1, MULE) => latin2mic(src, LC_ISO8859_1, LATIN1),
        (MULE, LATIN1) => mic2latin(src, LC_ISO8859_1, LATIN1),
        (LATIN2, MULE) => latin2mic(src, LC_ISO8859_2, LATIN2),
        (MULE, LATIN2) => mic2latin(src, LC_ISO8859_2, LATIN2),
        (LATIN3, MULE) => latin2mic(src, LC_ISO8859_3, LATIN3),
        (MULE, LATIN3) => mic2latin(src, LC_ISO8859_3, LATIN3),
        (LATIN4, MULE) => latin2mic(src, LC_ISO8859_4, LATIN4),
        (MULE, LATIN4) => mic2latin(src, LC_ISO8859_4, LATIN4),
        (WIN1250, MULE) => latin2mic_tab(src, LC_ISO8859_2, WIN1250, &WIN1250_2_ISO88592),
        (MULE, WIN1250) => mic2latin_tab(src, LC_ISO8859_2, WIN1250, &ISO88592_2_WIN1250),
        (LATIN2, WIN1250) => local2local(src, LATIN2, WIN1250, &ISO88592_2_WIN1250),
        (WIN1250, LATIN2) => local2local(src, WIN1250, LATIN2, &WIN1250_2_ISO88592),
        (KOI8R, MULE) => latin2mic(src, LC_KOI8_R, KOI8R),
        (MULE, KOI8R) => mic2latin(src, LC_KOI8_R, KOI8R),
        (ISO_8859_5, MULE) => latin2mic_tab(src, LC_KOI8_R, ISO_8859_5, &ISO2KOI),
        (MULE, ISO_8859_5) => mic2latin_tab(src, LC_KOI8_R, ISO_8859_5, &KOI2ISO),
        (WIN1251, MULE) => latin2mic_tab(src, LC_KOI8_R, WIN1251, &WIN12512KOI),
        (MULE, WIN1251) => mic2latin_tab(src, LC_KOI8_R, WIN1251, &KOI2WIN1251),
        (WIN866, MULE) => latin2mic_tab(src, LC_KOI8_R, WIN866, &WIN8662KOI),
        (MULE, WIN866) => mic2latin_tab(src, LC_KOI8_R, WIN866, &KOI2WIN866),
        (KOI8R, WIN1251) => local2local(src, KOI8R, WIN1251, &KOI2WIN1251),
        (WIN1251, KOI8R) => local2local(src, WIN1251, KOI8R, &WIN12512KOI),
        (KOI8R, WIN866) => local2local(src, KOI8R, WIN866, &KOI2WIN866),
        (WIN866, KOI8R) => local2local(src, WIN866, KOI8R, &WIN8662KOI),
        (WIN866, WIN1251) => local2local(src, WIN866, WIN1251, &WIN8662WIN1251),
        (WIN1251, WIN866) => local2local(src, WIN1251, WIN866, &WIN12512WIN866),
        (ISO_8859_5, KOI8R) => local2local(src, ISO_8859_5, KOI8R, &ISO2KOI),
        (KOI8R, ISO_8859_5) => local2local(src, KOI8R, ISO_8859_5, &KOI2ISO),
        (ISO_8859_5, WIN1251) => local2local(src, ISO_8859_5, WIN1251, &ISO2WIN1251),
        (WIN1251, ISO_8859_5) => local2local(src, WIN1251, ISO_8859_5, &WIN12512ISO),
        (ISO_8859_5, WIN866) => local2local(src, ISO_8859_5, WIN866, &ISO2WIN866),
        (WIN866, ISO_8859_5) => local2local(src, WIN866, ISO_8859_5, &WIN8662ISO),
        (EUC_CN, MULE) => euc_cn2mic(src),
        (MULE, EUC_CN) => mic2euc_cn(src),
        (EUC_KR, MULE) => euc_kr2mic(src),
        (MULE, EUC_KR) => mic2euc_kr(src),
        (EUC_JP, MULE) => euc_jp2mic(src),
        (MULE, EUC_JP) => mic2euc_jp(src),
        (SJIS, MULE) => sjis2mic(src),
        (MULE, SJIS) => mic2sjis(src),
        (EUC_JP, SJIS) => euc_jp2sjis(src),
        (SJIS, EUC_JP) => sjis2euc_jp(src),
        (EUC_TW, BIG5) => euc_tw2big5(src),
        (BIG5, EUC_TW) => big52euc_tw(src),
        (EUC_TW, MULE) => euc_tw2mic(src),
        (MULE, EUC_TW) => mic2euc_tw(src),
        (BIG5, MULE) => big52mic(src),
        (MULE, BIG5) => mic2big5(src),
        (EUC_JIS_2004, SHIFT_JIS_2004) => euc_jis_2004_to_sjis_2004(src),
        (SHIFT_JIS_2004, EUC_JIS_2004) => sjis_2004_to_euc_jis_2004(src),
        _ => unreachable!("no direct conversion"),
    }
}

/// `local2local`: single-byte to single-byte through a table of the high half.
fn local2local(src: &[u8], from: i32, to: i32, tab: &[u8; 128]) -> Result<Vec<u8>> {
    let mut out = Vec::with_capacity(src.len());
    for (i, &c) in src.iter().enumerate() {
        if c == 0 {
            return Err(invalid_encoding(from, &src[i..]));
        }
        if c < 0x80 {
            out.push(c);
        } else {
            match tab[(c - 0x80) as usize] {
                0 => return Err(untranslatable(from, to, &src[i..])),
                c2 => out.push(c2),
            }
        }
    }
    Ok(out)
}

/// `latin2mic`: a single-byte charset whose codes are MULE's under charset `lc`.
fn latin2mic(src: &[u8], lc: u8, enc: i32) -> Result<Vec<u8>> {
    let mut out = Vec::with_capacity(src.len() * 2);
    for (i, &c) in src.iter().enumerate() {
        if c == 0 {
            return Err(invalid_encoding(enc, &src[i..]));
        }
        if c >= 0x80 {
            out.push(lc);
        }
        out.push(c);
    }
    Ok(out)
}

/// `latin2mic_with_table`.
fn latin2mic_tab(src: &[u8], lc: u8, enc: i32, tab: &[u8; 128]) -> Result<Vec<u8>> {
    let mut out = Vec::with_capacity(src.len() * 2);
    for (i, &c) in src.iter().enumerate() {
        if c == 0 {
            return Err(invalid_encoding(enc, &src[i..]));
        }
        if c < 0x80 {
            out.push(c);
        } else {
            match tab[(c - 0x80) as usize] {
                0 => return Err(untranslatable(enc, MULE, &src[i..])),
                c2 => out.extend_from_slice(&[lc, c2]),
            }
        }
    }
    Ok(out)
}

/// `mic2latin` and `mic2latin_with_table`.
fn mic2latin_impl(src: &[u8], lc: u8, enc: i32, tab: Option<&[u8; 128]>) -> Result<Vec<u8>> {
    let mut out = Vec::with_capacity(src.len());
    let mut i = 0;
    while i < src.len() {
        let s = &src[i..];
        let c = s[0];
        if c == 0 {
            return Err(invalid_encoding(MULE, s));
        }
        if c < 0x80 {
            out.push(c);
            i += 1;
            continue;
        }
        let l = mule_mblen(c);
        if s.len() < l {
            return Err(invalid_encoding(MULE, s));
        }
        let mapped = if l != 2 || c != lc || s[1] < 0x80 {
            0
        } else {
            match tab {
                Some(t) => t[(s[1] - 0x80) as usize],
                None => s[1],
            }
        };
        if mapped == 0 {
            return Err(untranslatable(MULE, enc, s));
        }
        out.push(mapped);
        i += 2;
    }
    Ok(out)
}

fn mic2latin(src: &[u8], lc: u8, enc: i32) -> Result<Vec<u8>> {
    mic2latin_impl(src, lc, enc, None)
}

fn mic2latin_tab(src: &[u8], lc: u8, enc: i32, tab: &[u8; 128]) -> Result<Vec<u8>> {
    mic2latin_impl(src, lc, enc, Some(tab))
}

/// Walks `src` the way the multibyte conversion procs do: ASCII (NUL rejected) is
/// copied, every other character is checked with `verifychar(enc)` and handed to `f`
/// with its length; `f` appends its output or returns an error.
fn each_mb(
    src: &[u8],
    enc: i32,
    mut f: impl FnMut(&[u8], usize, &mut Vec<u8>) -> Result<()>,
) -> Result<Vec<u8>> {
    let mut out = Vec::with_capacity(src.len() * 2);
    let mut i = 0;
    while i < src.len() {
        let s = &src[i..];
        let c = s[0];
        if c < 0x80 {
            if c == 0 {
                return Err(invalid_encoding(enc, s));
            }
            out.push(c);
            i += 1;
            continue;
        }
        let Some(l) = verifychar(enc, s) else {
            return Err(invalid_encoding(enc, s));
        };
        f(s, l, &mut out)?;
        i += l;
    }
    Ok(out)
}

fn euc_cn2mic(src: &[u8]) -> Result<Vec<u8>> {
    let mut out = Vec::with_capacity(src.len() * 2);
    let mut i = 0;
    while i < src.len() {
        let s = &src[i..];
        let c = s[0];
        if c >= 0x80 {
            if s.len() < 2 || s[1] < 0x80 {
                return Err(invalid_encoding(EUC_CN, s));
            }
            out.extend_from_slice(&[LC_GB2312_80, c, s[1]]);
            i += 2;
        } else {
            if c == 0 {
                return Err(invalid_encoding(EUC_CN, s));
            }
            out.push(c);
            i += 1;
        }
    }
    Ok(out)
}

fn mic2euc_cn(src: &[u8]) -> Result<Vec<u8>> {
    let mut out = Vec::with_capacity(src.len());
    let mut i = 0;
    while i < src.len() {
        let s = &src[i..];
        let c = s[0];
        if c >= 0x80 {
            if c != LC_GB2312_80 {
                return Err(untranslatable(MULE, EUC_CN, s));
            }
            if s.len() < 3 || s[1] < 0x80 || s[2] < 0x80 {
                return Err(invalid_encoding(MULE, s));
            }
            out.extend_from_slice(&s[1..3]);
            i += 3;
        } else {
            if c == 0 {
                return Err(invalid_encoding(MULE, s));
            }
            out.push(c);
            i += 1;
        }
    }
    Ok(out)
}

fn euc_kr2mic(src: &[u8]) -> Result<Vec<u8>> {
    each_mb(src, EUC_KR, |s, l, out| {
        if l != 2 {
            return Err(invalid_encoding(EUC_KR, s));
        }
        out.extend_from_slice(&[LC_KS5601, s[0], s[1]]);
        Ok(())
    })
}

fn mic2euc_kr(src: &[u8]) -> Result<Vec<u8>> {
    each_mb(src, MULE, |s, _, out| {
        if s[0] != LC_KS5601 {
            return Err(untranslatable(MULE, EUC_KR, s));
        }
        out.extend_from_slice(&s[1..3]);
        Ok(())
    })
}

fn euc_jp2mic(src: &[u8]) -> Result<Vec<u8>> {
    each_mb(src, EUC_JP, |s, _, out| {
        match s[0] {
            SS2 => out.extend_from_slice(&[LC_JISX0201K, s[1]]),
            SS3 => out.extend_from_slice(&[LC_JISX0212, s[1], s[2]]),
            c => out.extend_from_slice(&[LC_JISX0208, c, s[1]]),
        }
        Ok(())
    })
}

fn mic2euc_jp(src: &[u8]) -> Result<Vec<u8>> {
    each_mb(src, MULE, |s, _, out| {
        match s[0] {
            LC_JISX0201K => out.extend_from_slice(&[SS2, s[1]]),
            LC_JISX0212 => out.extend_from_slice(&[SS3, s[1], s[2]]),
            LC_JISX0208 => out.extend_from_slice(&s[1..3]),
            _ => return Err(untranslatable(MULE, EUC_JP, s)),
        }
        Ok(())
    })
}

/// The SJIS bytes of a JIS X 0208 EUC code (UDC1 included), as euc_jp2sjis computes them.
fn jisx0208_to_sjis(c1: i32, c2: i32, out: &mut Vec<u8>) {
    let k = (c1 << 8) | (c2 & 0xff);
    let mut c1 = c1;
    if k >= 0xf5a1 {
        c1 -= 0x54;
        out.push((((c1 - 0xa1) >> 1) + if c1 < 0xdf { 0x81 } else { 0xc1 } + 0x6f) as u8);
    } else {
        out.push((((c1 - 0xa1) >> 1) + if c1 < 0xdf { 0x81 } else { 0xc1 }) as u8);
    }
    out.push((c2 - if c1 & 1 != 0 { if c2 < 0xe0 { 0x61 } else { 0x60 } } else { 2 }) as u8);
}

/// The SJIS bytes of a JIS X 0212 EUC code: UDC2 or an IBM kanji (else the
/// alternative code).
fn jisx0212_to_sjis(c1: i32, c2: i32, out: &mut Vec<u8>) {
    let k = (c1 << 8) | c2;
    if k >= 0xf5a1 {
        let c1 = c1 - 0x54;
        out.push((((c1 - 0xa1) >> 1) + if c1 < 0xdf { 0x81 } else { 0xc1 } + 0x74) as u8);
        out.push((c2 - if c1 & 1 != 0 { if c2 < 0xe0 { 0x61 } else { 0x60 } } else { 2 }) as u8);
        return;
    }
    for &(_, sjis, euc) in IBMKANJI.iter() {
        let k2 = (euc & 0xffff) as i32;
        if k2 == 0xffff {
            out.extend_from_slice(&PGSJISALTCODE.to_be_bytes());
            return;
        }
        if k2 == k {
            out.extend_from_slice(&sjis.to_be_bytes());
            return;
        }
    }
}

/// What an SJIS double-byte character becomes in EUC_JP/MULE terms: (charset, bytes),
/// charset 0x0208 or 0x0212, None when nothing is written (sjis2euc_jp/sjis2mic).
fn sjis_double(c1: i32, c2: i32, out: &mut Vec<(u16, u8, u8)>) {
    let (mut c1, mut c2) = (c1, c2);
    let mut k = (c1 << 8) + c2;
    if (0xed40..0xf040).contains(&k) {
        // NEC selection IBM kanji
        for &(nec, sjis, _) in IBMKANJI.iter() {
            if nec == 0xffff {
                break;
            }
            if nec as i32 == k {
                k = sjis as i32;
                c1 = (k >> 8) & 0xff;
                c2 = k & 0xff;
            }
        }
    }
    let b = |c: i32| c as u8;
    if k < 0xeb3f {
        out.push((
            0x0208,
            b(((c1 & 0x3f) << 1) + 0x9f + (c2 > 0x9e) as i32),
            b(c2 + if c2 > 0x9e { 2 } else { 0x60 } + (c2 < 0x80) as i32),
        ));
    } else if (0xeb40..0xf040).contains(&k) || (0xfc4c..=0xfcfc).contains(&k) {
        let [h, l] = PGEUCALTCODE.to_be_bytes();
        out.push((0x0208, h, l));
    } else if (0xf040..0xf540).contains(&k) {
        let c1 = c1 - 0x6f;
        out.push((
            0x0208,
            b(((c1 & 0x3f) << 1) + 0xf3 + (c2 > 0x9e) as i32),
            b(c2 + if c2 > 0x9e { 2 } else { 0x60 } + (c2 < 0x80) as i32),
        ));
    } else if (0xf540..0xfa40).contains(&k) {
        let c1 = c1 - 0x74;
        out.push((
            0x0212,
            b(((c1 & 0x3f) << 1) + 0xf3 + (c2 > 0x9e) as i32),
            b(c2 + if c2 > 0x9e { 2 } else { 0x60 } + (c2 < 0x80) as i32),
        ));
    } else if k >= 0xfa40 {
        // Like the original, a match replaces k, so later rows compare to the EUC code.
        let mut k = k as u32;
        for &(_, sjis, euc) in IBMKANJI.iter() {
            if sjis == 0xffff {
                break;
            }
            if sjis as u32 == k {
                k = euc;
                let set = if k >= 0x8f0000 { 0x0212 } else { 0x0208 };
                out.push((set, 0x80 | ((k & 0xff00) >> 8) as u8, 0x80 | (k & 0xff) as u8));
            }
        }
    }
}

fn euc_jp2sjis(src: &[u8]) -> Result<Vec<u8>> {
    each_mb(src, EUC_JP, |s, _, out| {
        match s[0] {
            SS2 => out.push(s[1]),
            SS3 => jisx0212_to_sjis(s[1] as i32, s[2] as i32, out),
            c => jisx0208_to_sjis(c as i32, s[1] as i32, out),
        }
        Ok(())
    })
}

fn sjis2euc_jp(src: &[u8]) -> Result<Vec<u8>> {
    each_mb(src, SJIS, |s, _, out| {
        let c1 = s[0];
        if (0xa1..=0xdf).contains(&c1) {
            out.extend_from_slice(&[SS2, c1]);
            return Ok(());
        }
        let mut chars = Vec::new();
        sjis_double(c1 as i32, s[1] as i32, &mut chars);
        for (set, a, b) in chars {
            if set == 0x0212 {
                out.push(SS3);
            }
            out.extend_from_slice(&[a, b]);
        }
        Ok(())
    })
}

fn sjis2mic(src: &[u8]) -> Result<Vec<u8>> {
    let mut out = Vec::with_capacity(src.len() * 2);
    let mut i = 0;
    while i < src.len() {
        let s = &src[i..];
        let c1 = s[0];
        if (0xa1..=0xdf).contains(&c1) {
            out.extend_from_slice(&[LC_JISX0201K, c1]);
            i += 1;
        } else if c1 >= 0x80 {
            let head = matches!(c1, 0x81..=0x9f | 0xe0..=0xfc);
            if s.len() < 2 || !head || !matches!(s[1], 0x40..=0x7e | 0x80..=0xfc) {
                return Err(invalid_encoding(SJIS, s));
            }
            let mut chars = Vec::new();
            sjis_double(c1 as i32, s[1] as i32, &mut chars);
            for (set, a, b) in chars {
                let lc = if set == 0x0212 { LC_JISX0212 } else { LC_JISX0208 };
                out.extend_from_slice(&[lc, a, b]);
            }
            i += 2;
        } else {
            if c1 == 0 {
                return Err(invalid_encoding(SJIS, s));
            }
            out.push(c1);
            i += 1;
        }
    }
    Ok(out)
}

fn mic2sjis(src: &[u8]) -> Result<Vec<u8>> {
    each_mb(src, MULE, |s, _, out| {
        match s[0] {
            LC_JISX0201K => out.push(s[1]),
            LC_JISX0208 => jisx0208_to_sjis(s[1] as i32, s[2] as i32, out),
            LC_JISX0212 => jisx0212_to_sjis(s[1] as i32, s[2] as i32, out),
            _ => return Err(untranslatable(MULE, SJIS, s)),
        }
        Ok(())
    })
}

/// big5.c's `BinarySearchRange` over a range table ending in a sentinel row.
fn binary_search_range(array: &[(u16, u16)], high: i32, code: u16) -> u16 {
    let (mut low, mut high) = (0i32, high);
    let mut mid = high >> 1;
    while low <= high {
        let (mc, mp) = (array[mid as usize].0 as i32, array[mid as usize].1 as i32);
        let code = code as i32;
        if mc <= code && array[mid as usize + 1].0 as i32 > code {
            if mp == 0 {
                return 0;
            }
            if code >= 0xa140 {
                // big5 to cns
                let tmp = ((code & 0xff00) - (mc & 0xff00)) >> 8;
                let hi = code & 0xff;
                let lo = mc & 0xff;
                let distance = tmp * 0x9d + hi - lo
                    + if hi >= 0xa1 {
                        if lo >= 0xa1 { 0 } else { -0x22 }
                    } else if lo >= 0xa1 {
                        0x22
                    } else {
                        0
                    };
                let tmp = (mp & 0xff) + distance - 0x21;
                let tmp = (mp & 0xff00) + ((tmp / 0x5e) << 8) + 0x21 + tmp % 0x5e;
                return tmp as u16;
            } else {
                // cns to big5
                let tmp = ((code & 0xff00) - (mc & 0xff00)) >> 8;
                let distance = tmp * 0x5e + ((code & 0xff) - (mc & 0xff));
                let lo = mp & 0xff;
                let tmp = lo + distance - if lo >= 0xa1 { 0x62 } else { 0x40 };
                let lo = tmp % 0x9d;
                let tmp = (mp & 0xff00) + ((tmp / 0x9d) << 8) + if lo > 0x3e { 0x62 } else { 0x40 } + lo;
                return tmp as u16;
            }
        } else if mc > code {
            high = mid - 1;
        } else {
            low = mid + 1;
        }
        mid = (low + high) >> 1;
    }
    0
}

/// `BIG5toCNS`: (CNS code with the high bits set, charset), charset 0 when unmapped.
fn big5_to_cns(big5: u16) -> (u16, u8) {
    let (cns, lc);
    if big5 < 0xc940 {
        if let Some(&(_, c)) = B1C4.iter().find(|r| r.0 == big5) {
            return (c | 0x8080, LC_CNS11643_4);
        }
        cns = binary_search_range(&BIG5_LEVEL1_TO_CNS_PLANE1, 23, big5);
        lc = LC_CNS11643_1;
    } else if big5 == 0xc94a {
        cns = 0x4442;
        lc = LC_CNS11643_1;
    } else {
        if let Some(&(_, c)) = B2C3.iter().find(|r| r.0 == big5) {
            return (c | 0x8080, LC_CNS11643_3);
        }
        cns = binary_search_range(&BIG5_LEVEL2_TO_CNS_PLANE2, 46, big5);
        lc = LC_CNS11643_2;
    }
    if cns == 0 {
        return (b'?' as u16, 0);
    }
    (cns | 0x8080, lc)
}

/// `CNStoBIG5` (0 when unmapped).
fn cns_to_big5(cns: u16, lc: u8) -> u16 {
    let cns = cns & 0x7f7f;
    match lc {
        LC_CNS11643_1 => binary_search_range(&CNS_PLANE1_TO_BIG5_LEVEL1, 24, cns),
        LC_CNS11643_2 => binary_search_range(&CNS_PLANE2_TO_BIG5_LEVEL2, 47, cns),
        LC_CNS11643_3 => B2C3.iter().find(|r| r.1 == cns).map_or(0, |r| r.0),
        LC_CNS11643_4 => B1C4.iter().find(|r| r.1 == cns).map_or(0, |r| r.0),
        _ => 0,
    }
}

fn euc_tw2big5(src: &[u8]) -> Result<Vec<u8>> {
    each_mb(src, EUC_TW, |s, _, out| {
        let (lc, cns) = if s[0] == SS2 {
            let lc = match s[1] {
                0xa1 => LC_CNS11643_1,
                0xa2 => LC_CNS11643_2,
                p => p.wrapping_sub(0xa3).wrapping_add(LC_CNS11643_3),
            };
            (lc, u16::from_be_bytes([s[2], s[3]]))
        } else {
            (LC_CNS11643_1, u16::from_be_bytes([s[0], s[1]]))
        };
        match cns_to_big5(cns, lc) {
            0 => Err(untranslatable(EUC_TW, BIG5, s)),
            b => {
                out.extend_from_slice(&b.to_be_bytes());
                Ok(())
            }
        }
    })
}

