#!/usr/bin/env python3
"""Generate tables.rs: the character data the collation providers need.

1. Postgres 18's Unicode case tables (src/include/common/unicode_case_table.h, Unicode 16.0)
   and the Case_Ignorable ranges of src/include/common/unicode_category_table.h, for the
   builtin provider:

       B=https://raw.githubusercontent.com/postgres/postgres/REL_18_STABLE
       curl -O $B/src/include/common/unicode_case_table.h
       curl -O $B/src/include/common/unicode_category_table.h

2. What the reference server (Postgres 18.6 on Alpine: ICU 78.1, musl) answers for the ICU
   provider's and the libc provider's character classes, and musl's towupper/towlower, dumped
   per class into <dumps>/<coll>_<class>.txt ("first last" ranges) with

       with c as (select i from generate_series(1,1114111) i
                  where i not between 55296 and 57343
                    and chr(i) ~ '[[:<class>:]]' collate <coll>)
       select min(i)||' '||max(i)
       from (select i, i - row_number() over (order by i) g from c) s group by g order by 1;

   for <coll> "und-x-icu" and a libc collation of any non-C locale (musl treats them all
   alike), and into <dumps>/musl_upper.txt / musl_lower.txt ("cp mapped") with

       select i||' '||ascii(upper(chr(i) collate <libc coll>)) from generate_series(1,1114111) i
       where i not between 55296 and 57343 and upper(chr(i) collate <libc coll>) <> chr(i);

Usage: gen_tables.py <dir with the two headers> <dumps dir> > tables.rs
"""

import re
import sys

hdr_dir, dump_dir = sys.argv[1], sys.argv[2]
case_h = open(f"{hdr_dir}/unicode_case_table.h").read()
cat_h = open(f"{hdr_dir}/unicode_category_table.h").read()


def array_body(src, name):
    m = re.search(r"static const [a-z_0-9]+ " + name + r"\[(\d+)\]\s*=\s*\{(.*?)\n\};", src, re.S)
    return int(m.group(1)), m.group(2)


# special_case[]: {conditions, {[CaseLower] = {..}, [CaseTitle] = {..}, [CaseUpper] = {..}, [CaseFold] = {..}}}
n_special, body = array_body(case_h, "special_case")
specials = []
for line in body.strip().split("\n"):
    line = line.strip().rstrip(",")
    if not line.startswith("{"):
        continue
    cond = 1 if line.startswith("{PG_U_FINAL_SIGMA") else 0
    groups = re.findall(r"\{(0x[0-9a-f]+), (0x[0-9a-f]+), (0x[0-9a-f]+)\}", line)
    if not groups:
        groups = [("0", "0", "0")] * 4
    assert len(groups) == 4, line
    specials.append((cond, [[int(x, 16) for x in g] for g in groups]))
assert len(specials) == n_special

maps = {}
for kind in ("lower", "title", "upper", "fold"):
    n, body = array_body(case_h, "case_map_" + kind)
    vals = [int(v, 16) for v in re.findall(r"^\s*(0x[0-9a-f]+),", body, re.M)]
    assert len(vals) == n, kind
    maps[kind] = vals
n, body = array_body(case_h, "case_map_special")
special_idx = [int(v) for v in re.findall(r"^\s*(\d+),", body, re.M)]
assert len(special_idx) == n

# case_map[]: the comments name each entry's code point.
n, body = array_body(case_h, "case_map")
index = [(int(cp, 16), int(i)) for i, cp in re.findall(r"^\s*(\d+),\s*/\* U\+([0-9A-F]+) \*/", body, re.M)]
assert len(index) == n
entries = sorted({cp: i for cp, i in index if i != 0}.items())

n, body = array_body(cat_h, "unicode_case_ignorable")
case_ignorable = [(int(a, 16), int(b, 16)) for a, b in re.findall(r"\{(0x[0-9a-f]+), (0x[0-9a-f]+)\}", body)]
assert len(case_ignorable) == n


def ranges(path):
    out = []
    for line in open(path):
        line = line.strip()
        if line:
            a, b = line.split()
            out.append((int(a), int(b)))
    return out


def pairs(path):
    out = []
    for line in open(path):
        line = line.strip()
        if line:
            a, b = line.split()
            out.append((int(a), int(b)))
    return out


def emit_ranges(name, rs, doc):
    print(f"/// {doc}")
    print("#[rustfmt::skip]")
    print(f"pub static {name}: [(u32, u32); {len(rs)}] = [")
    for i in range(0, len(rs), 6):
        print("    " + " ".join(f"(0x{a:06x}, 0x{b:06x})," for a, b in rs[i:i + 6]))
    print("];\n")


print("//! Generated by gen_tables.py; do not edit.\n")
print("/// Postgres's special case mappings (`special_case`): (Final_Sigma condition, the lower,")
print("/// title, upper and fold expansions, NUL-padded).")
print("#[rustfmt::skip]")
print(f"pub static SPECIAL_CASE: [(bool, [[u32; 3]; 4]); {len(specials)}] = [")
for cond, g in specials:
    gs = ", ".join("[" + ", ".join(f"0x{x:x}" for x in m) + "]" for m in g)
    print(f"    ({'true' if cond else 'false'}, [{gs}]),")
print("];\n")
print("/// Code points with case data, sorted: (code point, simple lower, title, upper, fold,")
print("/// index into SPECIAL_CASE or 0).")
print("#[rustfmt::skip]")
print(f"pub static CASE_MAP: [(u32, u32, u32, u32, u32, u8); {len(entries)}] = [")
for cp, i in entries:
    print(f"    (0x{cp:x}, 0x{maps['lower'][i]:x}, 0x{maps['title'][i]:x}, 0x{maps['upper'][i]:x}, "
          f"0x{maps['fold'][i]:x}, {special_idx[i]}),")
print("];\n")
emit_ranges("CASE_IGNORABLE", case_ignorable, "Case_Ignorable (unicode_case_ignorable).")

classes = ["alpha", "digit", "alnum", "upper", "lower", "graph", "print", "punct", "space"]
for prefix, coll, who in (("ICU", "und-x-icu", "ICU 78's u_is*"), ("MUSL", "gxl_bad", "musl's isw*")):
    for cls in classes:
        emit_ranges(f"{prefix}_{cls.upper()}", ranges(f"{dump_dir}/{coll}_{cls}.txt"),
                    f"{who} [[:{cls}:]] members.")
for kind in ("upper", "lower"):
    ps = pairs(f"{dump_dir}/musl_{kind}.txt")
    print(f"/// musl's tow{kind}: the code points it changes, sorted.")
    print("#[rustfmt::skip]")
    print(f"pub static MUSL_TO{kind.upper()}: [(u32, u32); {len(ps)}] = [")
    for i in range(0, len(ps), 6):
        print("    " + " ".join(f"(0x{a:06x}, 0x{b:06x})," for a, b in ps[i:i + 6]))
    print("];\n")

