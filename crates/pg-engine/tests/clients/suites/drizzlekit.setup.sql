CREATE SCHEMA other;
CREATE TYPE mood AS ENUM ('sad', 'ok', 'happy');
CREATE TYPE other.level AS ENUM ('low', 'high');
CREATE SEQUENCE ticket_seq START 100 INCREMENT 5 MAXVALUE 100000 CYCLE;
CREATE TABLE account (
  id bigserial PRIMARY KEY,
  email varchar(120) NOT NULL UNIQUE,
  name varchar(80) NOT NULL DEFAULT 'anon',
  mood mood NOT NULL DEFAULT 'ok',
  score numeric(10, 2) CHECK (score >= 0),
  ratio double precision,
  small smallint DEFAULT 1,
  flag boolean NOT NULL DEFAULT false,
  born date,
  wake time(3) with time zone,
  created timestamptz(6) NOT NULL DEFAULT now(),
  updated timestamp(3),
  tags text[] NOT NULL DEFAULT '{}',
  grid integer[][],
  meta jsonb DEFAULT '{"a": 1}',
  raw json,
  blob bytea,
  uid uuid NOT NULL DEFAULT gen_random_uuid(),
  ip inet,
  net cidr,
  mac macaddr,
  bits bit(4),
  vbits varbit(8),
  ch char(3),
  iv interval day to second,
  pt point,
  ln line,
  ticket integer NOT NULL DEFAULT nextval('ticket_seq'),
  gen integer GENERATED ALWAYS AS (small * 2) STORED,
  ident integer GENERATED BY DEFAULT AS IDENTITY (START WITH 7 INCREMENT BY 3)
);
COMMENT ON TABLE account IS 'people';
CREATE INDEX account_name_idx ON account (name DESC NULLS LAST);
CREATE INDEX account_lower_idx ON account (lower(name));
CREATE INDEX account_meta_gin ON account USING gin (meta jsonb_path_ops);
CREATE INDEX account_partial ON account (born) WHERE flag AND score > 10;
CREATE UNIQUE INDEX account_name_born ON account (name, born) NULLS NOT DISTINCT;
CREATE INDEX account_hash ON account USING hash (uid);
CREATE INDEX account_brin ON account USING brin (created) WITH (pages_per_range = 32);
CREATE TABLE post (
  id serial PRIMARY KEY,
  author_id bigint NOT NULL REFERENCES account (id) ON DELETE CASCADE ON UPDATE RESTRICT,
  editor_id bigint REFERENCES account (id) ON DELETE SET NULL,
  title text NOT NULL,
  body text,
  published boolean DEFAULT false,
  CONSTRAINT post_title_len CHECK (length(title) > 0),
  CONSTRAINT post_author_title UNIQUE (author_id, title)
);
CREATE TABLE pair (a integer, b integer, v text, PRIMARY KEY (a, b));
CREATE TABLE pair_ref (
  id integer PRIMARY KEY,
  pa integer,
  pb integer,
  FOREIGN KEY (pa, pb) REFERENCES pair (a, b) DEFERRABLE INITIALLY DEFERRED
);
CREATE TABLE other.thing (
  id integer PRIMARY KEY,
  lvl other.level NOT NULL,
  account_id bigint REFERENCES public.account (id)
);
CREATE TABLE parted (id integer NOT NULL, k date NOT NULL, v text) PARTITION BY RANGE (k);
CREATE TABLE parted_2024 PARTITION OF parted FOR VALUES FROM ('2024-01-01') TO ('2025-01-01');
CREATE TABLE parted_rest PARTITION OF parted DEFAULT;
CREATE INDEX parted_v ON parted (v);
CREATE TABLE listed (region text NOT NULL, n integer) PARTITION BY LIST (region);
CREATE TABLE listed_eu PARTITION OF listed FOR VALUES IN ('de', 'fr');
CREATE TABLE hashed (id integer PRIMARY KEY) PARTITION BY HASH (id);
CREATE TABLE hashed_0 PARTITION OF hashed FOR VALUES WITH (MODULUS 2, REMAINDER 0);
CREATE TABLE hashed_1 PARTITION OF hashed FOR VALUES WITH (MODULUS 2, REMAINDER 1);
CREATE TABLE base_log (id serial PRIMARY KEY, msg text);
CREATE TABLE child_log (extra text) INHERITS (base_log);
