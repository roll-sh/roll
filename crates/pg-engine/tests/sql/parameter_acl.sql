-- GRANT SET / ALTER SYSTEM ON PARAMETER and pg_parameter_acl
create role param_acl_r1;
create role param_acl_r2;
select count(*) from pg_parameter_acl;
grant set on parameter work_mem, "Log_Min_Duration_Statement" to param_acl_r1;
grant alter system on parameter work_mem to param_acl_r2 with grant option;
grant set, alter system on parameter param_acl.custom to public;
select parname, paracl from pg_parameter_acl order by oid;
select oid::int8 - (select min(oid)::int8 from pg_parameter_acl) from pg_parameter_acl order by oid;
select has_parameter_privilege('param_acl_r1', 'work_mem', 'SET'), has_parameter_privilege('param_acl_r1', 'work_mem', 'ALTER SYSTEM'), has_parameter_privilege('param_acl_r2', 'WORK_MEM', 'alter system with grant option'), has_parameter_privilege('param_acl_r2', 'work_mem', 'SET');
select has_parameter_privilege('param_acl_r1', 'param_acl.custom', 'SET'), has_parameter_privilege('work_mem', 'SET');
select pg_describe_object(classid, objid, objsubid), deptype, refobjid::regrole from pg_shdepend where classid = 'pg_parameter_acl'::regclass order by 1, 3;
select (pg_identify_object('pg_parameter_acl'::regclass, oid, 0)).* from pg_parameter_acl order by oid;
select (pg_identify_object_as_address('pg_parameter_acl'::regclass, oid, 0)).* from pg_parameter_acl order by oid;
drop role param_acl_r1;
revoke set on parameter work_mem from param_acl_r1;
revoke alter system on parameter work_mem from param_acl_r2 cascade;
select parname, paracl from pg_parameter_acl order by oid;
grant set on parameter nosuch_param to param_acl_r1;
grant select on parameter work_mem to param_acl_r1;
grant set on parameter work_mem to param_acl_r1;
select parname, paracl from pg_parameter_acl order by oid;
set role param_acl_r1;
set work_mem = '8MB';
show work_mem;
set log_min_duration_statement = 10;
show log_min_duration_statement;
set lc_messages = 'C';
set session_replication_role = replica;
reset role;
reset work_mem;
reset log_min_duration_statement;
revoke all on parameter work_mem, log_min_duration_statement, param_acl.custom from param_acl_r1, param_acl_r2, public;
select parname, paracl from pg_parameter_acl order by oid;
select count(*) from pg_parameter_acl;
drop role param_acl_r1;
drop role param_acl_r2;
