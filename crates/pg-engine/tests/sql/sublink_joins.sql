-- EXISTS / NOT EXISTS / IN pulled up into semi and anti joins (pull_up_sublinks), and
-- how the planner runs them: semi / anti joins either way round, the right side made
-- unique, or an inner join when it is unique already.
create table a (id int primary key, x int, t text);
create table b (id int primary key, y int, z int);
create table c (k int, w int);
create table d (k int, v text);
create table big (id int primary key, g int, pad text);
create table small (s int, t int);
create table mid (m int, n int);
insert into a select g, g % 50, 'a' || g from generate_series(1, 1000) g;
insert into b select g, g % 30, g % 7 from generate_series(1, 500) g;
insert into c select g % 10, g from generate_series(1, 100) g;
insert into d select g % 2000, 'd' || g from generate_series(1, 20000) g;
create index on d (k);
insert into big select i, i % 100, repeat('x', 50) from generate_series(1, 20000) i;
insert into small select i % 20, i from generate_series(1, 40) i;
insert into mid select i % 3000, i from generate_series(1, 6000) i;
analyze a; analyze b; analyze c; analyze d; analyze big; analyze small; analyze mid;
