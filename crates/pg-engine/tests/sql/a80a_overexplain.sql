CREATE FUNCTION oe_filter(text) RETURNS SETOF text LANGUAGE plpgsql AS $$
DECLARE ln text;
BEGIN
  FOR ln IN EXECUTE $1 LOOP
    RETURN NEXT regexp_replace(ln, 'Relation OIDs:( \m\d+\M)+', 'Relation OIDs: NNN...', 'g');
  END LOOP;
END;
$$;
CREATE TABLE oe (id int, name text);
CREATE TABLE oep (id int, genus text) PARTITION BY LIST (genus);
CREATE TABLE oep_a PARTITION OF oep FOR VALUES IN ('a');
CREATE TABLE oep_b PARTITION OF oep FOR VALUES IN ('b');
SELECT oe_filter($q$EXPLAIN (DEBUG, RANGE_TABLE, COSTS OFF) SELECT * FROM oe WHERE id > 1$q$);
EXPLAIN (RANGE_TABLE, COSTS OFF) SELECT * FROM oe x WHERE id > 1;
EXPLAIN (RANGE_TABLE, COSTS OFF) SELECT * FROM oep WHERE genus = 'b';
SELECT oe_filter($q$EXPLAIN (DEBUG, RANGE_TABLE, COSTS OFF) SELECT genus, count(*) FROM oep GROUP BY genus$q$);
SELECT oe_filter($q$EXPLAIN (DEBUG, RANGE_TABLE, COSTS OFF) INSERT INTO oe VALUES (1, 'x')$q$);
EXPLAIN (RANGE_TABLE, COSTS OFF) INSERT INTO oep VALUES (1, 'a');
DROP TABLE oe, oep;
DROP FUNCTION oe_filter(text);
