-- Foreign-data wrappers, servers and user mappings: DDL, generic options, the libpq option
-- check of postgresql_fdw_validator, privileges, catalog rows and identities.
create role fdwd_user;
create foreign data wrapper fdwd_dummy;
comment on foreign data wrapper fdwd_dummy is 'useless';
create foreign data wrapper fdwd_pg validator postgresql_fdw_validator;
create foreign data wrapper fdwd_bad validator nope;
create foreign data wrapper fdwd_dummy;
create foreign data wrapper fdwd_o options (testing '1', testing '2');
create foreign data wrapper fdwd_o options (testing '1', another '2');
select fdwname, fdwhandler::regproc, fdwvalidator::regproc, fdwoptions from pg_foreign_data_wrapper where fdwname like 'fdwd%' order by 1;
alter foreign data wrapper fdwd_o options (set c '4');
alter foreign data wrapper fdwd_o options (drop c);
alter foreign data wrapper fdwd_o options (add x '1', drop x);
alter foreign data wrapper fdwd_o options (drop testing, set another '3', add c '4');
alter foreign data wrapper fdwd_o options (c '5');
alter foreign data wrapper fdwd_o no validator;
alter foreign data wrapper fdwd_o validator postgresql_fdw_validator;
select fdwname, fdwvalidator::regproc, fdwoptions from pg_foreign_data_wrapper where fdwname = 'fdwd_o';
alter foreign data wrapper fdwd_o rename to fdwd_dummy;
alter foreign data wrapper fdwd_o rename to fdwd_o2;
alter foreign data wrapper fdwd_o2 owner to fdwd_user;
create server fdwd_s1 foreign data wrapper fdwd_dummy;
create server fdwd_s1 foreign data wrapper fdwd_dummy;
create server if not exists fdwd_s1 foreign data wrapper fdwd_dummy;
create server fdwd_s2 type 'oracle' version '1.0' foreign data wrapper fdwd_pg options (host 'a', dbname 'b');
create server fdwd_s3 foreign data wrapper fdwd_pg options (foo '1');
create server fdwd_s3 foreign data wrapper fdwd_pg options (hostx 'a');
create server fdwd_s3 foreign data wrapper fdwd_pg options (user 'a');
create server fdwd_s3 foreign data wrapper nope;
select srvname, srvtype, srvversion, srvoptions from pg_foreign_server where srvname like 'fdwd%' order by 1;
alter server fdwd_s2 version '2.0' options (set host 'c', add port '5432');
alter server fdwd_s2 version null;
select srvname, srvtype, srvversion, srvoptions from pg_foreign_server where srvname = 'fdwd_s2';
create user mapping for current_user server fdwd_s2 options (user 'u', password 'p');
create user mapping for current_user server fdwd_s2;
create user mapping if not exists for current_user server fdwd_s2;
create user mapping for public server fdwd_s2 options (dbname 'x');
create user mapping for fdwd_user server fdwd_s1;
create user mapping for nope server fdwd_s1;
alter user mapping for public server fdwd_s2 options (drop dbname);
alter user mapping for fdwd_user server fdwd_s2 options (add user 'a');
select srvname, usename, umoptions from pg_user_mappings where srvname like 'fdwd%' order by 1, 2;
select pg_describe_object(classid, objid, objsubid) as obj, pg_describe_object(refclassid, refobjid, refobjsubid) as ref, deptype from pg_depend where refclassid in ('pg_foreign_data_wrapper'::regclass, 'pg_foreign_server'::regclass) order by 1, 2;
select (pg_identify_object(classid, objid, objsubid)).*, (pg_identify_object_as_address(classid, objid, objsubid)).* from pg_depend where classid in ('pg_foreign_server'::regclass, 'pg_user_mapping'::regclass) order by 4;
grant usage on foreign data wrapper fdwd_dummy to fdwd_user;
grant usage on foreign server fdwd_s1 to fdwd_user with grant option;
select fdwname, fdwacl from pg_foreign_data_wrapper where fdwname = 'fdwd_dummy';
select srvname, srvacl from pg_foreign_server where srvname = 'fdwd_s1';
select has_foreign_data_wrapper_privilege('fdwd_user', 'fdwd_dummy', 'usage'), has_server_privilege('fdwd_user', 'fdwd_s1', 'usage'), has_server_privilege('fdwd_user', 'fdwd_s2', 'usage');
select has_server_privilege('nope', 'usage');
drop role fdwd_user;
alter server fdwd_s1 rename to fdwd_s2;
alter server fdwd_s1 rename to fdwd_s9;
drop server fdwd_s9;
drop server if exists fdwd_nope;
drop server fdwd_nope;
drop foreign data wrapper if exists fdwd_nope;
drop foreign data wrapper fdwd_pg;
drop user mapping if exists for nope server fdwd_s2;
drop user mapping if exists for current_user server fdwd_nope;
drop user mapping for public server fdwd_s9;
drop user mapping if exists for public server fdwd_s9;
drop foreign data wrapper fdwd_pg cascade;
drop foreign data wrapper fdwd_dummy cascade;
drop foreign data wrapper fdwd_o2;
drop role fdwd_user;
