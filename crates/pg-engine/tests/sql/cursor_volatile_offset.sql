-- A cursor over a scan with a volatile WHERE qual under LIMIT ... OFFSET: the Limit node
-- passes the OFFSET's rows first (the qual evaluated for them), and stepping off the
-- window's start or end and back re-returns the row it was on.
create sequence cvo_s;
create table cvo_t (a int);
insert into cvo_t values (1),(2),(3),(4),(5),(6);
create function cvo_q(int) returns bool language plpgsql volatile as $$ begin raise notice 'qual %', $1; return true; end $$;
create function cvo_odd(int) returns bool language plpgsql volatile as $$ declare n int := nextval('cvo_s'); begin raise notice 'odd % %', $1, n; return n % 2 = 1; end $$;
begin;
declare c scroll cursor for select a from cvo_t where cvo_q(a) limit 2 offset 2;
fetch next from c;
fetch next from c;
fetch next from c;
fetch prior from c;
fetch prior from c;
fetch prior from c;
fetch prior from c;
fetch next from c;
fetch all from c;
fetch backward all from c;
commit;
begin;
declare c scroll cursor for select a from cvo_t where cvo_q(a) offset 4;
fetch all from c;
fetch backward all from c;
fetch next from c;
commit;
begin;
declare c scroll cursor for select a from cvo_t where cvo_q(a) limit 3 offset 10;
fetch next from c;
fetch prior from c;
fetch next from c;
commit;
begin;
declare c scroll cursor for select a from cvo_t where cvo_q(a) limit 0 offset 1;
fetch next from c;
commit;
begin;
declare c scroll cursor for select a from cvo_t where cvo_q(a) limit 5 offset 3;
fetch prior from c;
fetch absolute 2 from c;
fetch absolute -1 from c;
fetch first from c;
fetch relative 2 from c;
commit;
begin;
declare c scroll cursor for select a from cvo_t where cvo_odd(a) limit 2 offset 1;
fetch all from c;
fetch backward all from c;
fetch all from c;
commit;
drop table cvo_t; drop function cvo_q, cvo_odd; drop sequence cvo_s;
