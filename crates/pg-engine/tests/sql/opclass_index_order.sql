CREATE FUNCTION oio_rcmp(int4, int4) RETURNS int LANGUAGE sql IMMUTABLE AS $$ SELECT CASE WHEN $1 = $2 THEN 0 WHEN $1 > $2 THEN -1 ELSE 1 END $$;
CREATE FUNCTION oio_rlt(int4, int4) RETURNS bool LANGUAGE sql IMMUTABLE AS $$ SELECT $1 > $2 $$;
CREATE FUNCTION oio_rle(int4, int4) RETURNS bool LANGUAGE sql IMMUTABLE AS $$ SELECT $1 >= $2 $$;
CREATE FUNCTION oio_rgt(int4, int4) RETURNS bool LANGUAGE sql IMMUTABLE AS $$ SELECT $1 < $2 $$;
CREATE FUNCTION oio_rge(int4, int4) RETURNS bool LANGUAGE sql IMMUTABLE AS $$ SELECT $1 <= $2 $$;
CREATE OPERATOR <<< (leftarg = int4, rightarg = int4, function = oio_rlt);
CREATE OPERATOR <<<= (leftarg = int4, rightarg = int4, function = oio_rle);
CREATE OPERATOR >>> (leftarg = int4, rightarg = int4, function = oio_rgt);
CREATE OPERATOR >>>= (leftarg = int4, rightarg = int4, function = oio_rge);
CREATE OPERATOR === (leftarg = int4, rightarg = int4, function = int4eq);
CREATE OPERATOR CLASS oio_rev_ops FOR TYPE int4 USING btree AS OPERATOR 1 <<<, OPERATOR 2 <<<=, OPERATOR 3 ===, OPERATOR 4 >>>=, OPERATOR 5 >>>, FUNCTION 1 oio_rcmp(int4, int4);
