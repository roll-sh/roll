CREATE TABLE docs (id int PRIMARY KEY, body text, tsv tsvector);
INSERT INTO docs SELECT g, 'doc ' || g || CASE WHEN g % 3 = 0 THEN ' fat cats' WHEN g % 3 = 1 THEN ' rats ate' ELSE ' sat on mats' END, NULL FROM generate_series(1, 300) g;
UPDATE docs SET tsv = to_tsvector('english', body);
CREATE INDEX docs_gin ON docs USING gin (tsv);
CREATE INDEX docs_gist ON docs USING gist (to_tsvector('english', body));
CREATE INDEX docs_gin2 ON docs USING gin (to_tsvector('simple', body)) WITH (fastupdate = off);
SELECT indexrelid::regclass, indisvalid, pg_get_indexdef(indexrelid) FROM pg_index WHERE indrelid = 'docs'::regclass ORDER BY 1;
SELECT opcname, opcmethod::regclass IS NULL FROM pg_opclass WHERE opcintype IN ('tsvector'::regtype, 'tsquery'::regtype) ORDER BY 1;
SELECT amname FROM pg_am a JOIN pg_opclass o ON o.opcmethod = a.oid WHERE o.opcname IN ('tsvector_ops', 'gist_tsvector_ops', 'gist_tsquery_ops') ORDER BY 1;
SELECT count(*) FROM docs WHERE tsv @@ to_tsquery('english', 'cat');
SELECT count(*) FROM docs WHERE to_tsvector('english', body) @@ to_tsquery('english', 'rat & ate');
SELECT id FROM docs WHERE tsv @@ 'mat & 10'::tsquery ORDER BY id;
SET enable_seqscan = off;
SELECT count(*) FROM docs WHERE tsv @@ to_tsquery('english', 'cat | rat');
SELECT count(*) FROM docs WHERE to_tsvector('simple', body) @@ to_tsquery('simple', 'fat <-> cats');
SELECT count(*) FROM docs WHERE tsv @@ to_tsquery('english', '!cat');
SELECT count(*) FROM docs WHERE tsv @@ to_tsquery('english', 'ca:*');
RESET enable_seqscan;
CREATE INDEX docs_bad ON docs USING gin (body);
CREATE INDEX docs_bad ON docs USING gist (body);
CREATE INDEX docs_q ON docs USING gist (to_tsquery('english', body));
CREATE INDEX docs_btree ON docs (tsv);
SELECT tsv FROM docs ORDER BY tsv LIMIT 3;
SELECT DISTINCT tsv FROM docs ORDER BY 1 DESC LIMIT 2;
DROP TABLE docs;
