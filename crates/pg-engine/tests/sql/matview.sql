-- materialized views: populated state, indexes, REFRESH (CONCURRENTLY), ALTER
CREATE TABLE mb (a int, b text);
INSERT INTO mb VALUES (1, 'one'), (2, 'two'), (3, 'three');
CREATE MATERIALIZED VIEW mvp AS SELECT a, b FROM mb WITH NO DATA;
SELECT relispopulated FROM pg_class WHERE relname = 'mvp';
SELECT ispopulated, hasindexes FROM pg_matviews WHERE matviewname = 'mvp';
SELECT * FROM mvp;
SELECT count(*) FROM (SELECT * FROM mvp) s;
REFRESH MATERIALIZED VIEW CONCURRENTLY mvp;
REFRESH MATERIALIZED VIEW mvp;
SELECT * FROM mvp ORDER BY a;
SELECT relispopulated FROM pg_class WHERE relname = 'mvp';
