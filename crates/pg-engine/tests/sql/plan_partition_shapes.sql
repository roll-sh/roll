-- Partition pruning (partprune.c steps over list / range / hash bounds, default
-- partitions, multi-level trees, IN lists, boolean keys) and partitionwise joins.
create table pp_l (a int, b text) partition by list (a);
create table pp_l1 partition of pp_l for values in (1, 2);
create table pp_l2 partition of pp_l for values in (3, 4);
create table pp_ld partition of pp_l default;
create table pp_r (a int, b int) partition by range (a, b);
create table pp_r1 partition of pp_r for values from (minvalue, minvalue) to (10, 0);
create table pp_r2 partition of pp_r for values from (10, 0) to (20, 0) partition by list (b);
create table pp_r2a partition of pp_r2 for values in (1, 2, 3);
create table pp_r2b partition of pp_r2 default;
create table pp_r3 partition of pp_r for values from (20, 0) to (maxvalue, maxvalue);
create table pp_h (a int, b text) partition by hash (a);
create table pp_h0 partition of pp_h for values with (modulus 2, remainder 0);
create table pp_h1 partition of pp_h for values with (modulus 2, remainder 1);
create table pp_bool (a bool) partition by list (a);
create table pp_bt partition of pp_bool for values in (true);
create table pp_bf partition of pp_bool for values in (false);
explain (costs off) select * from pp_l where a = 1;
explain (costs off) select * from pp_l where a in (1, 3);
explain (costs off) select * from pp_l where a = 5;
explain (costs off) select * from pp_l where a is null;
explain (costs off) select * from pp_l where a <> 1;
explain (costs off) select * from pp_l where a = 1 and a = 3;
explain (costs off) select * from pp_r where a = 15 and b = 2;
explain (costs off) select * from pp_r where a = 15;
explain (costs off) select * from pp_r where a < 10;
explain (costs off) select * from pp_r where a >= 20 or a < 5;
explain (costs off) select * from pp_r where (a, b) = (10, 7);
explain (costs off) select * from pp_h where a = 1;
explain (costs off) select * from pp_h where a in (1, 2);
explain (costs off) select * from pp_bool where a;
explain (costs off) select * from pp_bool where not a;
explain (costs off) select * from pp_bool where a is not true;
create table pw1 (k int, v int) partition by range (k);
create table pw1a partition of pw1 for values from (0) to (100);
create table pw1b partition of pw1 for values from (100) to (200);
create table pw2 (k int, w int) partition by range (k);
create table pw2a partition of pw2 for values from (0) to (100);
create table pw2b partition of pw2 for values from (100) to (200);
insert into pw1 select g, g % 7 from generate_series(0, 199) g;
insert into pw2 select g, g % 5 from generate_series(0, 199, 2) g;
analyze pw1; analyze pw2;
set enable_partitionwise_join = on;
explain (costs off) select * from pw1 join pw2 on pw1.k = pw2.k where pw1.v = 1;
explain (costs off) select * from pw1 left join pw2 on pw1.k = pw2.k where pw1.v = 1;
explain (costs off) select * from pw1 where exists (select 1 from pw2 where pw2.k = pw1.k and pw2.w = 2);
explain (costs off) select * from pw1 where not exists (select 1 from pw2 where pw2.k = pw1.k);
select count(*), sum(pw2.w) from pw1 join pw2 on pw1.k = pw2.k where pw1.v = 1;
select count(*) from pw1 left join pw2 on pw1.k = pw2.k where pw1.v = 1;
select count(*) from pw1 where not exists (select 1 from pw2 where pw2.k = pw1.k);
reset enable_partitionwise_join;
