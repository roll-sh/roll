-- SELECT ... FOR UPDATE / SHARE over joins: one LockRows at the query level's top (under its
-- LIMIT, over its sort), its row marks' ctids carried up the plan.
CREATE TABLE a9a (id int PRIMARY KEY, x int, note text);
CREATE TABLE a9b (id int PRIMARY KEY, y int);
INSERT INTO a9a SELECT g, g, 'n' || g FROM generate_series(1, 10) g;
INSERT INTO a9b SELECT g, g FROM generate_series(1, 5) g;
ANALYZE a9a;
ANALYZE a9b;
EXPLAIN (COSTS OFF) SELECT * FROM a9a JOIN a9b ON a9a.x = a9b.y FOR UPDATE;
EXPLAIN (COSTS OFF, VERBOSE) SELECT * FROM a9a JOIN a9b ON a9a.x = a9b.y FOR UPDATE;
EXPLAIN (COSTS OFF, VERBOSE) SELECT a9a.x FROM a9a JOIN a9b ON a9a.x = a9b.y FOR UPDATE OF a9a;
EXPLAIN (COSTS OFF, VERBOSE) SELECT a9a.x FROM a9a, a9b WHERE a9a.x = a9b.y AND a9b.y < 3 FOR SHARE OF a9b NOWAIT;
EXPLAIN (COSTS OFF) SELECT * FROM a9a LEFT JOIN a9b ON a9a.x = a9b.y FOR UPDATE OF a9a;
EXPLAIN (COSTS OFF) SELECT * FROM a9a JOIN a9b ON a9a.x = a9b.y ORDER BY a9a.id LIMIT 2 FOR UPDATE;
EXPLAIN (COSTS OFF) SELECT * FROM a9a ORDER BY x FOR UPDATE;
EXPLAIN (COSTS OFF) SELECT * FROM a9a WHERE id < 3 ORDER BY x LIMIT 1 FOR UPDATE SKIP LOCKED;
EXPLAIN (COSTS OFF, VERBOSE) SELECT x + 1 FROM a9a ORDER BY x FOR SHARE;
EXPLAIN (COSTS OFF, VERBOSE) SELECT * FROM a9a WHERE x = 3 FOR UPDATE;
EXPLAIN (COSTS OFF, VERBOSE) SELECT 1 FROM a9a a, a9a b WHERE a.id = b.id FOR UPDATE OF b;
-- The rows themselves.
SELECT * FROM a9a JOIN a9b ON a9a.x = a9b.y ORDER BY a9a.id FOR UPDATE;
SELECT a9a.id, a9b.id FROM a9a LEFT JOIN a9b ON a9a.x = a9b.y WHERE a9a.id > 3 ORDER BY 1 FOR UPDATE OF a9a;
SELECT id FROM a9a ORDER BY id DESC LIMIT 3 FOR UPDATE SKIP LOCKED;
SELECT a.id, b.note FROM a9a a JOIN a9a b ON a.id = b.x + 1 WHERE a.id < 4 ORDER BY 1 FOR NO KEY UPDATE OF a FOR SHARE OF b;
SELECT x, count(*) FROM (SELECT x FROM a9a JOIN a9b ON x = y FOR UPDATE) s GROUP BY x ORDER BY x;
WITH l AS (SELECT a9a.id FROM a9a JOIN a9b ON a9a.x = a9b.y WHERE a9b.id > 3 FOR UPDATE) SELECT * FROM l ORDER BY 1;
SELECT a9a.id, g FROM a9a, generate_series(1, 2) g WHERE g = a9a.x FOR UPDATE OF a9a;
-- WHERE CURRENT OF through a cursor over a join locking rows.
BEGIN;
DECLARE c CURSOR FOR SELECT a9a.id, a9b.y FROM a9a JOIN a9b ON a9a.x = a9b.y ORDER BY a9a.id FOR UPDATE OF a9a;
FETCH 2 FROM c;
UPDATE a9a SET note = 'via cursor' WHERE CURRENT OF c RETURNING *;
UPDATE a9b SET y = y WHERE CURRENT OF c;
ROLLBACK;
BEGIN;
DECLARE c CURSOR FOR SELECT a9a.id, a9b.y FROM a9a JOIN a9b ON a9a.x = a9b.y ORDER BY a9a.id FOR UPDATE;
FETCH 3 FROM c;
DELETE FROM a9b WHERE CURRENT OF c RETURNING *;
UPDATE a9a SET note = 'both' WHERE CURRENT OF c RETURNING id, note;
ROLLBACK;
DROP TABLE a9a, a9b;
