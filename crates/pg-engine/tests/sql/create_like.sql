-- CREATE TABLE (LIKE ...): indexes, comments, constraint names, column order
create table lk (a int primary key, b text, c int check (c > 0), d int);
create index lk_b on lk (b);
create index lk_e on lk (lower(b)) where d > 0;
create unique index lk_cd on lk (c, d) include (b);
create index lk_h on lk using hash (d);
alter table lk add constraint lk_x exclude using btree (d with =);
comment on column lk.b is 'bee';
comment on constraint lk_c_check on lk is 'positive';
comment on index lk_b is 'b index';
comment on table lk is 'the table';
create table lk2 (like lk including all);
select indexname, indexdef from pg_indexes where tablename = 'lk2' order by 1;
select conname, contype from pg_constraint where conrelid = 'lk2'::regclass order by 1;
select col_description('lk2'::regclass, 2), obj_description('lk2'::regclass, 'pg_class');
select c.relname, obj_description(c.oid, 'pg_class') from pg_index i join pg_class c on c.oid = i.indexrelid where i.indrelid = 'lk2'::regclass order by 1;
select conname, obj_description(oid, 'pg_constraint') from pg_constraint where conrelid = 'lk2'::regclass order by 1;
create table lk3 (like lk including indexes);
select indexname from pg_indexes where tablename = 'lk3' order by 1;
select conname, contype from pg_constraint where conrelid = 'lk3'::regclass order by 1;
create table lk4 (like lk including comments);
select col_description('lk4'::regclass, 2);
select conname, obj_description(oid, 'pg_constraint') from pg_constraint where conrelid = 'lk4'::regclass order by 1;
create table lk5 (like lk including constraints including comments);
select conname, obj_description(oid, 'pg_constraint') from pg_constraint where conrelid = 'lk5'::regclass order by 1;
create table lk6 (x int, like lk including all excluding indexes, y int);
select attname from pg_attribute where attrelid = 'lk6'::regclass and attnum > 0 order by attnum;
select indexname from pg_indexes where tablename = 'lk6' order by 1;
create table lk7 (like lk including all, b text);
create table lk8 (b text, like lk);
drop table lk, lk2, lk3, lk4, lk5, lk6;
