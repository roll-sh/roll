-- GIN index sizes: the build's entry tree (sorted keys, posting lists in the entry tuples
-- or posting trees), the fast-update pending list later rows go to, VACUUM moving them
-- into the tree, and inserts straight into the tree with fastupdate off.
create table gis1 (id int, a int[]);
insert into gis1 select g, array[g % 10, g % 7, g % 100] from generate_series(1, 2000) g;
create index gis1_a on gis1 using gin (a);
select pg_relation_size('gis1_a');
insert into gis1 select g, array[g % 11] from generate_series(1, 50) g;
select pg_relation_size('gis1_a');
create table gis2 (id int, t tsvector);
insert into gis2 select g, to_tsvector('simple', 'word' || (g % 50) || ' common other' || (g % 7) || ' x' || g) from generate_series(1, 3000) g;
create index gis2_t on gis2 using gin (t);
select pg_relation_size('gis2_t');
create table gis3 (id int, j jsonb);
insert into gis3 select g, jsonb_build_object('k', g % 10, 'name', 'n' || g, 'tags', jsonb_build_array('a', 'b' || (g % 3))) from generate_series(1, 2000) g;
create index gis3_j on gis3 using gin (j);
select pg_relation_size('gis3_j');
create table gis4 (id int, a int[]);
insert into gis4 select g, array[g % 3] from generate_series(1, 30000) g;
create index gis4_a on gis4 using gin (a);
select pg_relation_size('gis4_a');
create table gis5 (a int[]);
create index gis5_a on gis5 using gin (a);
select pg_relation_size('gis5_a');
insert into gis5 select array[g, g + 1] from generate_series(1, 1000) g;
select pg_relation_size('gis5_a');
create table gis6 (id int, a text[]);
insert into gis6 select g, array['tag' || (g % 37), 'x' || g, null] from generate_series(1, 5000) g;
insert into gis6 values (0, '{}'), (-1, null);
create index gis6_a on gis6 using gin (a);
select pg_relation_size('gis6_a');
insert into gis6 select g, array['tag' || (g % 5), repeat('long', 40) || g] from generate_series(1, 400) g;
select pg_relation_size('gis6_a');
create table gis7 (a int[]);
create index gis7_a on gis7 using gin (a) with (fastupdate = off);
insert into gis7 select array[(g * 7919) % 5000, g] from generate_series(1, 5000) g;
select pg_relation_size('gis7_a');
create table gis8 (a int[]);
insert into gis8 select array[g % 100] from generate_series(1, 1000) g;
create index gis8_a on gis8 using gin (a);
insert into gis8 select array[g] from generate_series(1, 3000) g;
select pg_relation_size('gis8_a');
vacuum gis8;
select pg_relation_size('gis8_a');
insert into gis8 select array[g] from generate_series(1, 300) g;
select pg_relation_size('gis8_a');
truncate gis8;
select pg_relation_size('gis8_a');
create table gis9 (j jsonb);
insert into gis9 select jsonb_build_object('a', g, 'b', jsonb_build_object('c', g % 5, 'd', array[g, g % 3]), 'e', null, 'f', true, 'g', 1.50) from generate_series(1, 4000) g;
create index gis9_j on gis9 using gin (j);
select pg_relation_size('gis9_j');
