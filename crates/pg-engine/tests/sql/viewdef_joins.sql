-- pg_get_viewdef of joins (USING, NATURAL, FULL), functions in FROM, set-returning calls,
-- GROUPING and SEARCH / CYCLE; dropping several relations with dependents together.
CREATE TABLE vq_a (id int, name text, v numeric);
CREATE TABLE vq_b (id int, a_id int, w int);
CREATE VIEW vq_srf AS SELECT generate_series(1, 3) AS g, unnest(ARRAY[1, 2]) AS u;
CREATE VIEW vq_natural AS SELECT * FROM vq_a NATURAL JOIN vq_b;
CREATE VIEW vq_join_alias AS SELECT j.id, j.w FROM (vq_a a JOIN vq_b b ON b.a_id = a.id) j;
CREATE VIEW vq_full_using AS SELECT id, name FROM vq_a FULL JOIN vq_b USING (id);
CREATE VIEW vq_using_alias AS SELECT x.id, w FROM vq_a JOIN vq_b USING (id) AS x;
CREATE VIEW vq_rows_from AS SELECT * FROM ROWS FROM (generate_series(1, 2), generate_series(1, 3)) r(a, b);
CREATE VIEW vq_implicit_lateral AS SELECT a.id, g FROM vq_a a, generate_series(1, a.id) g;
CREATE VIEW vq_cte_sublink AS WITH c AS (SELECT a_id FROM vq_b) SELECT id FROM vq_a WHERE id IN (SELECT a_id FROM c);
CREATE VIEW vq_qualified_fn AS SELECT * FROM pg_catalog.generate_series(1, 2) s;
CREATE VIEW vq_partial_alias AS SELECT * FROM (SELECT id, name, v FROM vq_a) s(x);
CREATE VIEW vq_order_expr AS SELECT name FROM vq_a ORDER BY v * 2, id;
CREATE VIEW vq_view_of_view AS SELECT g FROM vq_srf WHERE g > 1;
CREATE VIEW vq_grouping AS SELECT a_id, grouping(a_id), sum(w) FROM vq_b GROUP BY ROLLUP (a_id);
CREATE VIEW vq_union_from AS SELECT * FROM (SELECT id FROM vq_a UNION SELECT w FROM vq_b) u WHERE id > 1;
CREATE VIEW vq_values_in AS SELECT id FROM vq_a WHERE id IN (VALUES (1), (2));
CREATE VIEW vq_groups AS SELECT id, sum(v) OVER (ORDER BY id GROUPS BETWEEN 1 PRECEDING AND 1 FOLLOWING), count(*) FILTER (WHERE v > 0) OVER () FROM vq_a;
CREATE VIEW vq_join_lateral AS SELECT a.id, s.n FROM vq_a a JOIN LATERAL (SELECT count(*) AS n FROM vq_b b WHERE b.a_id = a.id) s ON true;
CREATE VIEW vq_two_up AS SELECT id, (SELECT (SELECT max(c.w) FROM vq_b c WHERE c.w = a.id) FROM vq_b b LIMIT 1) AS x FROM vq_a a;
CREATE VIEW vq_search AS WITH RECURSIVE t(n) AS (SELECT 1 UNION ALL SELECT n + 1 FROM t WHERE n < 3) SEARCH DEPTH FIRST BY n SET ord SELECT * FROM t;
CREATE VIEW vq_cycle AS WITH RECURSIVE t(n) AS (SELECT 1 UNION ALL SELECT n + 1 FROM t WHERE n < 3) CYCLE n SET is_cycle USING path SELECT n FROM t;
CREATE VIEW vq_right_nested AS SELECT a.id FROM vq_a a LEFT JOIN (vq_b b JOIN vq_b c ON c.id = b.id) ON b.a_id = a.id;
CREATE VIEW vq_distinct_order AS SELECT DISTINCT name, v FROM vq_a ORDER BY v DESC;
CREATE VIEW vq_case_sub AS SELECT CASE WHEN EXISTS (SELECT 1 FROM vq_b) THEN 1 ELSE 0 END AS flag;
CREATE VIEW vq_no_from AS SELECT 1 AS one, 'x' AS two;
CREATE VIEW vq_star_qual AS SELECT a.*, b.w FROM vq_a a, vq_b b;
CREATE VIEW vq_func_alias AS SELECT t.x FROM unnest(ARRAY[1, 2]) WITH ORDINALITY AS t(x, n);
SELECT s.x FROM (SELECT 1 AS x, 2 AS x) s;
CREATE TABLE vq_ctas AS SELECT row(1, 2) AS r;
CREATE TABLE vq_ctas AS SELECT ARRAY[row(1, 2)] AS r;
SELECT c.relname, pg_get_viewdef(c.oid) FROM pg_class c WHERE c.relkind = 'v' AND c.relname LIKE 'vq\_%' ORDER BY 1;
SELECT c.relname, pg_get_viewdef(c.oid, true) FROM pg_class c WHERE c.relkind = 'v' AND c.relname IN ('vq_join_alias', 'vq_right_nested', 'vq_natural') ORDER BY 1;
DROP TABLE vq_a, vq_b;
DROP TABLE vq_b, vq_a CASCADE;
DROP VIEW vq_srf CASCADE;
DROP VIEW vq_rows_from, vq_qualified_fn, vq_cycle, vq_no_from, vq_func_alias;
