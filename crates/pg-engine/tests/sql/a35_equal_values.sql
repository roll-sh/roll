SELECT max(x), min(x) FROM (VALUES (ARRAY[1.0::numeric]), (ARRAY[1.00::numeric])) v(x);
SELECT max(x), min(x) FROM (VALUES (ROW(1.0::numeric)), (ROW(1.00::numeric))) v(x);
