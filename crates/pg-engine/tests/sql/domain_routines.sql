-- Domains through routines and CREATE TABLE AS: column types kept, checks on parameters,
-- set-returning results, PL/pgSQL returns and OUT parameters; PG_ROUTINE_OID.
CREATE DOMAIN dr_pos AS int CHECK (VALUE > 0);
CREATE TABLE dr_c AS SELECT 1::dr_pos AS a, 'x'::text AS b;
SELECT format_type(atttypid, atttypmod) FROM pg_attribute WHERE attrelid = 'dr_c'::regclass AND attnum > 0 ORDER BY attnum;
INSERT INTO dr_c VALUES (0, 'y');
CREATE PROCEDURE dr_p(x dr_pos) LANGUAGE plpgsql AS $$ BEGIN RAISE NOTICE 'x=%', x; END $$;
CALL dr_p(1);
CALL dr_p(0);
CREATE FUNCTION dr_s() RETURNS SETOF dr_pos LANGUAGE sql AS $$ VALUES (1), (0) $$;
SELECT * FROM dr_s();
SELECT dr_s();
CREATE FUNCTION dr_s2() RETURNS SETOF dr_pos LANGUAGE plpgsql AS $$ BEGIN RETURN NEXT 1; RETURN NEXT 0; END $$;
SELECT * FROM dr_s2();
CREATE FUNCTION dr_o() RETURNS oid LANGUAGE plpgsql AS $$ DECLARE r oid; BEGIN GET DIAGNOSTICS r = PG_ROUTINE_OID; RETURN r; END $$;
SELECT dr_o() = 'dr_o'::regproc::oid;
CREATE FUNCTION dr_r() RETURNS dr_pos LANGUAGE plpgsql AS $$ BEGIN RETURN 0; END $$;
SELECT dr_r();
CREATE FUNCTION dr_q(OUT a dr_pos) LANGUAGE plpgsql AS $$ BEGIN a := 0; END $$;
SELECT dr_q();
CREATE FUNCTION dr_o2(INOUT x dr_pos, OUT a dr_pos, OUT b text) LANGUAGE plpgsql AS $$ BEGIN a := x; b := 'k'; END $$;
CREATE FUNCTION dr_t2() RETURNS TABLE (p dr_pos, q int) LANGUAGE sql AS $$ VALUES (1, 2), (0, 3) $$;
SELECT proallargtypes::regtype[], prorettype::regtype FROM pg_proc WHERE proname IN ('dr_o2', 'dr_t2') ORDER BY proname;
SELECT * FROM dr_o2(1);
SELECT * FROM dr_t2();
CREATE FUNCTION dr_o3(OUT a dr_pos, OUT b int) LANGUAGE plpgsql AS $$ BEGIN b := 1; a := 0; END $$;
SELECT * FROM dr_o3();
CREATE FUNCTION dr_o4(x dr_pos) RETURNS int LANGUAGE plpgsql AS $$ BEGIN x := 0; RETURN x; END $$;
SELECT dr_o4(5);
CREATE VIEW dr_vd AS SELECT 1::dr_pos AS a;
SELECT format_type(atttypid, atttypmod) FROM pg_attribute WHERE attrelid = 'dr_vd'::regclass AND attnum > 0;
DROP VIEW dr_vd;
-- RETURN QUERY: the query's columns must be the result's
CREATE FUNCTION dr_rq() RETURNS SETOF dr_pos LANGUAGE plpgsql AS $$ BEGIN RETURN QUERY SELECT 0; END $$;
SELECT * FROM dr_rq();
CREATE FUNCTION dr_rq2() RETURNS SETOF dr_pos LANGUAGE plpgsql AS $$ BEGIN RETURN QUERY SELECT 0::dr_pos; END $$;
SELECT * FROM dr_rq2();
CREATE FUNCTION dr_rq3() RETURNS TABLE (a int, bb text) LANGUAGE plpgsql AS $$ BEGIN RETURN QUERY SELECT 1, 2; END $$;
SELECT * FROM dr_rq3();
CREATE FUNCTION dr_rq4() RETURNS SETOF varchar LANGUAGE plpgsql AS $$ BEGIN RETURN QUERY SELECT 'x'::text; END $$;
SELECT * FROM dr_rq4();
CREATE FUNCTION dr_rq5() RETURNS TABLE (a int) LANGUAGE plpgsql AS $$ BEGIN RETURN QUERY EXECUTE 'SELECT 1, 2'; END $$;
SELECT * FROM dr_rq5();
CREATE FUNCTION dr_rq6() RETURNS SETOF text LANGUAGE plpgsql AS $$ BEGIN RETURN QUERY SELECT 'x'; RETURN QUERY SELECT 'y'::varchar; END $$;
SELECT * FROM dr_rq6();
CREATE FUNCTION dr_rq7() RETURNS SETOF dr_pos LANGUAGE plpgsql AS $$ BEGIN RETURN 0; END $$;
CREATE FUNCTION dr_rq8() RETURNS dr_pos LANGUAGE plpgsql AS $$ BEGIN RETURN 0; END $$;
SELECT dr_rq8();
DROP FUNCTION dr_rq, dr_rq2, dr_rq3, dr_rq4, dr_rq5, dr_rq6, dr_rq8;
DROP TABLE dr_c; DROP PROCEDURE dr_p; DROP FUNCTION dr_s, dr_s2, dr_o, dr_r, dr_q, dr_o2, dr_t2, dr_o3, dr_o4; DROP DOMAIN dr_pos;
