-- gincostestimate: a GIN scan's cost from the metapage's statistics (the build's counts,
-- the pending list after it, a VACUUM's count) and each operator class's search entries;
-- brincostestimate's revmap pages (brinGetStats: none past the first).
create table a273_g (a int[], v tsvector) with (autovacuum_enabled = off);
insert into a273_g select array[g % 50, g % 7, g], to_tsvector('simple', 'w' || (g % 20) || ' z' || (g % 5)) from generate_series(1, 2000) g;
create index a273_ga on a273_g using gin (a);
create index a273_gv on a273_g using gin (v);
analyze a273_g;
set enable_seqscan = off;
explain select * from a273_g where a @> '{3}';
explain select * from a273_g where a && '{3,4,5}';
explain select * from a273_g where v @@ 'w3 & z3';
explain select * from a273_g where v @@ 'w1:*';
explain select * from a273_g where v @@ '!w3';
explain select * from a273_g where v @@ to_tsquery('simple', 'w3 | z4');
insert into a273_g select array[g % 50, g], to_tsvector('simple', 'w' || (g % 20)) from generate_series(2001, 2300) g;
explain select * from a273_g where a @> '{3}';
explain select * from a273_g where v @@ 'w3';
vacuum a273_g;
explain select * from a273_g where a @> '{3}';
explain select * from a273_g where v @@ 'w3';
create table a273_j (j jsonb) with (autovacuum_enabled = off);
insert into a273_j select jsonb_build_object('k', g % 10, 'w', 'x' || (g % 3), 'l', jsonb_build_array(g % 4, 'e')) from generate_series(1, 1500) g;
create index a273_jo on a273_j using gin (j);
analyze a273_j;
explain select * from a273_j where j @> '{"k": 3}';
explain select * from a273_j where j @> '{"k": 3, "w": "x1"}';
explain select * from a273_j where j ? 'w';
explain select * from a273_j where j ?| array['k', 'q'];
explain select * from a273_j where j @@ '$.k == 3';
explain select * from a273_j where j @? '$.l[*] ? (@ == "e")';
explain select * from a273_j where j @? '$.k';
drop index a273_jo;
create index a273_jp on a273_j using gin (j jsonb_path_ops);
explain select * from a273_j where j @> '{"k": 3, "w": "x1"}';
explain select * from a273_j where j @@ '$.k == 3';
explain select * from a273_j where j @> '{}';
create table a273_b (x int) with (autovacuum_enabled = off);
insert into a273_b select generate_series(1, 20000);
create index a273_bx on a273_b using brin (x) with (pages_per_range = 4);
analyze a273_b;
explain select * from a273_b where x < 100;
reset enable_seqscan;
drop table a273_g, a273_j, a273_b;
