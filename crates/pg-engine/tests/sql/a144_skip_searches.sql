-- Btree skip scans' "Index Searches" in EXPLAIN ANALYZE (agent 144): PostgreSQL 18's
-- _bt_first calls, replayed over the index's size model. Leading int columns (skip support)
-- with and without a lower bound, a text leading column (none), equalities, ranges, IN
-- lists, matches crossing leaf pages, many small groups (the NSKIPADVANCES heuristic), and
-- a bitmap index scan.
CREATE TABLE sk1 (a int, b int);
INSERT INTO sk1 SELECT g % 7, g FROM generate_series(1, 10000) g;
CREATE INDEX sk1_ab ON sk1 (a, b);
CREATE TABLE sk2 (a int, b int);
INSERT INTO sk2 SELECT g % 10, g / 10 FROM generate_series(1, 20000) g;
CREATE INDEX sk2_ab ON sk2 (a, b);
CREATE TABLE sk3 (a int, b int);
INSERT INTO sk3 SELECT g / 7, g % 7 FROM generate_series(1, 21000) g;
CREATE INDEX sk3_ab ON sk3 (a, b);
CREATE TABLE sk4 (a int, b int);
INSERT INTO sk4 SELECT g % 10, g / 10 FROM generate_series(0, 19999) g;
CREATE INDEX sk4_ab ON sk4 (a, b);
CREATE TABLE sk5 (a text, b int);
INSERT INTO sk5 SELECT 'k' || (g % 10), g / 10 FROM generate_series(0, 19999) g;
CREATE INDEX sk5_ab ON sk5 (a, b);
CREATE TABLE sk6 (a int, b int);
INSERT INTO sk6 SELECT g / 100, g % 100 FROM generate_series(0, 29999) g;
CREATE INDEX sk6_ab ON sk6 (a, b);
VACUUM ANALYZE sk1;
VACUUM ANALYZE sk2;
VACUUM ANALYZE sk3;
VACUUM ANALYZE sk4;
VACUUM ANALYZE sk5;
VACUUM ANALYZE sk6;
SET enable_seqscan = off;
SET enable_bitmapscan = off;
EXPLAIN (ANALYZE, COSTS OFF, TIMING OFF, SUMMARY OFF, BUFFERS OFF) SELECT a, b FROM sk1 WHERE b = 7;
EXPLAIN (ANALYZE, COSTS OFF, TIMING OFF, SUMMARY OFF, BUFFERS OFF) SELECT a, b FROM sk1 WHERE b = 5000;
EXPLAIN (ANALYZE, COSTS OFF, TIMING OFF, SUMMARY OFF, BUFFERS OFF) SELECT a, b FROM sk1 WHERE b > 9990;
EXPLAIN (ANALYZE, COSTS OFF, TIMING OFF, SUMMARY OFF, BUFFERS OFF) SELECT a, b FROM sk1 WHERE b IN (3, 5000, 9999);
EXPLAIN (ANALYZE, COSTS OFF, TIMING OFF, SUMMARY OFF, BUFFERS OFF) SELECT a, b FROM sk2 WHERE b = 500;
EXPLAIN (ANALYZE, COSTS OFF, TIMING OFF, SUMMARY OFF, BUFFERS OFF) SELECT a, b FROM sk2 WHERE b BETWEEN 500 AND 510;
EXPLAIN (ANALYZE, COSTS OFF, TIMING OFF, SUMMARY OFF, BUFFERS OFF) SELECT a, b FROM sk2 WHERE b < 3;
EXPLAIN (ANALYZE, COSTS OFF, TIMING OFF, SUMMARY OFF, BUFFERS OFF) SELECT a, b FROM sk2 WHERE b >= 1990;
EXPLAIN (ANALYZE, COSTS OFF, TIMING OFF, SUMMARY OFF, BUFFERS OFF) SELECT a, b FROM sk2 WHERE a > 4 AND b = 500;
EXPLAIN (ANALYZE, COSTS OFF, TIMING OFF, SUMMARY OFF, BUFFERS OFF) SELECT a, b FROM sk3 WHERE b = 3;
EXPLAIN (ANALYZE, COSTS OFF, TIMING OFF, SUMMARY OFF, BUFFERS OFF) SELECT a, b FROM sk3 WHERE b = 3 AND a < 50;
EXPLAIN (ANALYZE, COSTS OFF, TIMING OFF, SUMMARY OFF, BUFFERS OFF) SELECT a, b FROM sk4 WHERE b BETWEEN 300 AND 700;
EXPLAIN (ANALYZE, COSTS OFF, TIMING OFF, SUMMARY OFF, BUFFERS OFF) SELECT a, b FROM sk4 WHERE b BETWEEN 300 AND 310;
EXPLAIN (ANALYZE, COSTS OFF, TIMING OFF, SUMMARY OFF, BUFFERS OFF) SELECT a, b FROM sk4 WHERE b BETWEEN 0 AND 1500;
EXPLAIN (ANALYZE, COSTS OFF, TIMING OFF, SUMMARY OFF, BUFFERS OFF) SELECT a, b FROM sk5 WHERE b = 500;
EXPLAIN (ANALYZE, COSTS OFF, TIMING OFF, SUMMARY OFF, BUFFERS OFF) SELECT a, b FROM sk5 WHERE b BETWEEN 300 AND 700;
EXPLAIN (ANALYZE, COSTS OFF, TIMING OFF, SUMMARY OFF, BUFFERS OFF) SELECT a, b FROM sk6 WHERE b = 50;
EXPLAIN (ANALYZE, COSTS OFF, TIMING OFF, SUMMARY OFF, BUFFERS OFF) SELECT a, b FROM sk6 WHERE b = 0;
EXPLAIN (ANALYZE, COSTS OFF, TIMING OFF, SUMMARY OFF, BUFFERS OFF) SELECT a, b FROM sk6 WHERE b BETWEEN 10 AND 20;
EXPLAIN (ANALYZE, COSTS OFF, TIMING OFF, SUMMARY OFF, BUFFERS OFF) SELECT a, b FROM sk6 WHERE a BETWEEN 100 AND 120 AND b = 50;
SET enable_indexonlyscan = off;
EXPLAIN (ANALYZE, COSTS OFF, TIMING OFF, SUMMARY OFF, BUFFERS OFF) SELECT * FROM sk2 WHERE b = 500;
RESET enable_indexonlyscan;
RESET enable_bitmapscan;
SET enable_indexscan = off;
EXPLAIN (ANALYZE, COSTS OFF, TIMING OFF, SUMMARY OFF, BUFFERS OFF) SELECT count(*) FROM sk2 WHERE b = 500;
RESET enable_indexscan;
-- The rows themselves.
SELECT a, b FROM sk1 WHERE b IN (3, 5000, 9999) ORDER BY a, b;
SELECT count(*) FROM sk6 WHERE b BETWEEN 10 AND 20;
SELECT a, b FROM sk5 WHERE b = 500 ORDER BY a;
RESET enable_seqscan;
DROP TABLE sk1, sk2, sk3, sk4, sk5, sk6;
