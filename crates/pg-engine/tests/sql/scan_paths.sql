-- Access paths chosen by cost as Postgres's planner does: sequential, index, index-only
-- and bitmap heap scans (BitmapAnd / BitmapOr, OR arms as = ANY), indexes read in ORDER BY
-- order (backward too) under a LIMIT, partial / expression / boolean / hash indexes, the
-- enable_* settings, and the EXPLAIN ANALYZE details of each (Heap Fetches, Heap Blocks,
-- Index Searches). Also ModifyTable costs and the widths of the rows scans return.
set jit = off;
create table sp_k (a int primary key, c text);
insert into sp_k select g, 'c' || g from generate_series(1, 1000) g;
analyze sp_k;
explain select c from sp_k where a < 900;
explain select c from sp_k where a < 4;
explain select c from sp_k where a < 100;
explain select a from sp_k where a < 300;
explain select a from sp_k where a < 30;
explain select * from sp_k order by a;
explain select * from sp_k order by a limit 5;
explain select * from sp_k order by a desc limit 1;
create table sp_b (a int, b int, c int, d text);
insert into sp_b select g, g % 100, g % 7, 'x' || (g % 1000) from generate_series(1, 20000) g;
create index sp_b_b on sp_b (b);
create index sp_b_c on sp_b (c);
create index sp_b_ab on sp_b (a, b);
create index sp_b_d on sp_b (d);
analyze sp_b;
explain select * from sp_b where b = 5;
explain select * from sp_b where b = 5 and c = 3;
explain select * from sp_b where b = 5 or c = 3;
explain select count(*) from sp_b where b = 5;
explain select * from sp_b where b = 5 or b = 7;
explain select * from sp_b where b = 5 or b = 7 or c = 1;
explain select * from sp_b where b in (1, 5, 9) and c = 2;
explain select * from sp_b where a < 100;
explain select * from sp_b where a = 100;
explain select * from sp_b where a = 100 and b = 0;
explain select * from sp_b where a between 100 and 200 and b = 5;
explain select * from sp_b where b = 7 and a > 10;
explain select a, b from sp_b where b = 7 and a > 10;
explain select * from sp_b where d = 'x5';
explain select * from sp_b where d < 'x2';
explain select * from sp_b where d > 'x995';
explain select * from sp_b where b is null;
explain select * from sp_b order by a;
explain select * from sp_b order by a limit 10;
explain select * from sp_b order by a desc limit 10;
explain select * from sp_b order by a, b limit 10;
explain select * from sp_b order by a, c limit 10;
explain select * from sp_b where b = 4 order by a limit 10;
explain select * from sp_b order by d limit 3;
explain select * from sp_b order by d offset 10 limit 3;
explain select * from sp_b order by d offset 19990;
explain select a from sp_b order by a;
explain select * from sp_b where a < 1000 order by a;
explain select * from sp_b where a > 100 limit 5;
explain select b from sp_b where c = 4 order by b;
explain (format json) select * from sp_b where b = 5 or c = 3;
-- settings
set enable_bitmapscan = off;
explain select * from sp_b where b = 5;
reset enable_bitmapscan;
set enable_indexscan = off;
explain select * from sp_b order by a limit 10;
reset enable_indexscan;
set enable_seqscan = off;
explain select * from sp_b where c + 1 = 5;
explain (format yaml) select * from sp_b where c + 1 = 5;
reset enable_seqscan;
set random_page_cost = 1.1;
explain select * from sp_b where b < 30;
reset random_page_cost;
-- the rows come back in the order the plan reads them
select * from sp_b order by a desc limit 3;
select * from sp_b where b = 5 and c = 3 order by a limit 5;
select count(*) from sp_b where b = 5 or c = 3;
select a, b from sp_b where b = 7 and a > 10 limit 5;
select a from sp_b where a < 8;
select a, b, c from sp_b where b = 5 and c = 3 limit 4;
-- EXPLAIN ANALYZE
explain (analyze, costs off, timing off, summary off, buffers off) select a from sp_b where a < 50;
explain (analyze, costs off, timing off, summary off, buffers off) select * from sp_b where b = 5 or c = 3;
explain (analyze, costs off, timing off, summary off, buffers off) select * from sp_b where b = 5 and c = 3 and a > 100;
explain (analyze, costs off, timing off, summary off, buffers off) select * from sp_b order by a desc limit 3;
vacuum sp_b;
explain (analyze, costs off, timing off, summary off, buffers off) select a from sp_b where a < 50;
explain select a from sp_b where a < 50;
explain select b from sp_b where b < 10;
explain select count(*) from sp_b;
-- DML
explain update sp_b set c = 1 where a = 5;
explain delete from sp_b where b = 5;
create table sp_m (a int, b int);
insert into sp_m select g, g from generate_series(1, 1000) g;
analyze sp_m;
explain delete from sp_m where b < 10;
explain update sp_m set b = b + 1 where b < 10;
explain update sp_m set b = 5;
explain insert into sp_m select * from sp_m;
explain insert into sp_m values (1, 2);
explain delete from sp_m where b < 10 returning *;
explain update sp_m set b = b + 1, a = 7 where b < 10 returning *;
explain delete from sp_m using sp_m m2 where m2.a = sp_m.b;
-- partial, expression, boolean and hash indexes
create table sp_p (a int, b int, c int, f bool, t text, n numeric);
insert into sp_p select g, g % 100, g % 7, g % 3 = 0, 't' || g, g / 10.0 from generate_series(1, 20000) g;
create index sp_p_part on sp_p (b) where c = 1;
create index sp_p_expr on sp_p ((a % 50));
create index sp_p_cb on sp_p (c, b);
create index sp_p_f on sp_p (f);
create index sp_p_h on sp_p using hash (a);
create index sp_p_n on sp_p (n);
analyze sp_p;
explain select * from sp_p where b = 5 and c = 1;
explain select * from sp_p where b = 5;
explain select * from sp_p where a % 50 = 3;
explain select * from sp_p where b = 7;
explain select * from sp_p where c = 2 and b = 7;
explain select * from sp_p where f;
explain select * from sp_p where not f;
explain select * from sp_p where a = 77;
explain select * from sp_p where n = 5.5;
explain select * from sp_p where n < 10;
explain select * from sp_p where c is not null and b = 3;
explain select * from sp_p where a = 5 or a = 9;
explain select * from sp_p where (c = 1 and b = 2) or (c = 2 and b = 3);
explain select * from sp_p where c in (1, 2) and b = 50;
select a, b, c from sp_p where (c = 1 and b = 2) or (c = 2 and b = 3) order by a limit 5;
select count(*) from sp_p where f;
