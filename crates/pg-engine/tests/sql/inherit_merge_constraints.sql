-- multiple parents: the same check merges silently, a different one conflicts
create table mp1 (a int, constraint mck check (a > 0));
create table mp2 (a int, constraint mck check (a > 0));
create table mp3 (a int, constraint mck check (a < 0));
create table mc1 () inherits (mp1, mp2);
create table mc2 () inherits (mp1, mp3);
create table mc3 (constraint mck check (a > 0)) inherits (mp1, mp2);
select conrelid::regclass, conname, conislocal, coninhcount from pg_constraint where conrelid::regclass::text ~ '^mc' order by conrelid::regclass::text, conname;
-- ALTER TABLE ... INHERIT: oids of what merges stay, the column's inhcount goes up
create table q (a int not null, constraint qck check (a > 0));
create table qc (a int not null, constraint qck check (a > 0));
create table mk0 ();
alter table qc inherit q;
create table mk1 ();
select conname, conislocal, coninhcount, oid < 'mk0'::regclass::oid from pg_constraint where conrelid = 'qc'::regclass order by conname;
select 'mk1'::regclass::int8 - 'mk0'::regclass::int8;
alter table qc no inherit q;
select conname, conislocal, coninhcount from pg_constraint where conrelid = 'qc'::regclass order by conname;
drop table mp1, mp2, mp3, q, qc, mk0, mk1 cascade;
-- ALTER TABLE ... ADD CONSTRAINT on a child with the inherited one
create table ap (a int, constraint ack check (a > 0), constraint ack2 check (a > 0), constraint ack3 check (a > 0));
create table ac () inherits (ap);
alter table ac add constraint ack check (a > 0);
alter table ac add constraint ack2 check (a > 0) no inherit;
alter table ac add constraint ack3 check (a > 0) not enforced;
alter table ac add constraint ack3 check (a > 1);
select conname, conislocal, coninhcount, connoinherit from pg_constraint where conrelid = 'ac'::regclass order by conname;
-- CREATE TABLE ignores NOT VALID; a NOT VALID child constraint can't merge with a valid one
create table nv1 (a int, constraint v check (a > 0) not valid);
select convalidated from pg_constraint where conname = 'v';
create table nvp (a int, constraint w check (a > 0));
create table nvc (a int);
alter table nvc add constraint w check (a > 0) not valid;
alter table nvc inherit nvp;
-- ATTACH PARTITION: the partition's matching constraints are no longer its own
create table pp (k int, a int not null, constraint pck check (a > 0)) partition by range (k);
create table pp1 (a int not null, k int, constraint pck check (a > 0));
alter table pp attach partition pp1 for values from (0) to (10);
create table pp2 partition of pp for values from (10) to (20);
select conrelid::regclass, conname, conislocal, coninhcount from pg_constraint where conrelid in ('pp1'::regclass, 'pp2'::regclass) order by conrelid::regclass::text, conname;
alter table pp detach partition pp1;
select conname, conislocal, coninhcount from pg_constraint where conrelid = 'pp1'::regclass order by conname;
drop table ap, nv1, nvp, nvc, pp, pp1 cascade;
