-- EXPLAIN's estimates: relation sizes from the current page count (a never-analyzed table
-- assumes a tuple density from its row width), default and statistics-based
-- selectivities, and the cost formulas of costsize.c.
set jit = off;
create table ee_a(id int, t text, v varchar(20), n numeric, b bool, ts timestamptz);
explain select * from ee_a;
explain select id from ee_a where id = 5;
explain select id from ee_a where id < 5;
explain select id from ee_a where id <> 5;
explain select id from ee_a where t like 'a%';
explain select id from ee_a where t is null;
explain select id from ee_a where b;
explain select id from ee_a where id = 5 and t = 'x';
explain select id from ee_a where id = 5 or id = 6;
explain select id from ee_a where id > 1 and id < 10;
explain select id from ee_a where id in (1,2,3);
explain select * from ee_a a, ee_a b;
insert into ee_a select g, 'text'||g, 'v'||g, g, g%2=0, '2024-01-01' from generate_series(1,5000) g;
explain select * from ee_a;
insert into ee_a values (1);
explain select * from ee_a;
explain select * from generate_series(1,10) g;
explain select * from generate_series(1,10) g where g > 3;
explain select * from unnest(array[1,2,3]) u;
explain select * from ee_a a cross join lateral generate_series(1, a.id) g;
create table ee_b(x int, y int);
explain select * from ee_b b1 join ee_b b2 on b1.x < b2.x;
explain select count(*) from ee_b;
explain select x, count(*) from ee_b group by x;
explain select * from ee_b order by x;
explain select * from ee_b order by x limit 10;
explain select * from ee_b order by x offset 5 limit 10;
explain select distinct x from ee_b;
explain select x + 1, y * 2 from ee_b;
explain select * from ee_b union all select * from ee_b;
explain select x, sum(y) over (order by x) from ee_b;
explain with c as materialized (select * from ee_b) select * from c;
explain select * from ee_b where x = (select max(y) from ee_b);
explain select * from (values (1,'a'),(2,'b')) v(a,b);
-- Analyzed: most common values, histograms, distinct counts.
create table ee_s(id int, k int, t text, v varchar(20), n numeric(10,2), b bool);
insert into ee_s select g, g % 10, 'text'||g, 'v'||(g%100), g, g%2=0 from generate_series(1,5000) g;
analyze ee_s;
explain select * from ee_s;
explain select id from ee_s where id = 5;
explain select id from ee_s where k = 5;
explain select id from ee_s where k = 50;
explain select id from ee_s where id < 100;
explain select id from ee_s where id > 4900;
explain select id from ee_s where id between 100 and 200;
explain select id from ee_s where t = 'text7';
explain select id from ee_s where t < 'text2';
explain select id from ee_s where v = 'v7';
explain select id from ee_s where b;
explain select id from ee_s where not b;
explain select id from ee_s where k in (1,2,3);
explain select id from ee_s where t is null;
explain select k, count(*) from ee_s group by k;
explain select v, count(*) from ee_s group by v;
explain select k, v, count(*) from ee_s group by k, v;
explain select k, count(*) from ee_s where id < 1000 group by k;
explain select distinct k from ee_s;
explain select * from ee_s a join ee_s b on a.id = b.id;
explain select * from ee_s a join ee_s b on a.k = b.k where a.id < 10;
explain select * from ee_s order by t limit 5;
explain select * from ee_s order by t offset 10 limit 5;
explain select count(*), sum(id), avg(n) from ee_s;
explain select * from ee_s where id + 1 = 7;
explain select id * 2, upper(t) from ee_s;
create table ee_c(x int);
insert into ee_c select g from generate_series(1,100) g;
analyze ee_c;
explain select * from ee_s, ee_c where ee_s.id = ee_c.x;
explain select * from ee_c c1, ee_c c2;
explain select * from ee_c c1, ee_c c2 where c1.x < c2.x;
explain select * from (values (1),(2),(3)) v(a), ee_c where ee_c.x = v.a;
