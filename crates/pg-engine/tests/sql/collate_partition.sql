-- Partition keys compare under their collation (partcollation): bound checks, overlap, routing,
-- pruning (only by clauses under the key's collation), hashing under nondeterministic ones.
create table p (x text collate "de-x-icu") partition by range (x);
create table p1 partition of p for values from ('a') to ('B');
create table p2 partition of p for values from ('B') to ('c');
create table pbad partition of p for values from ('b') to ('A');
create table pov partition of p for values from ('A') to ('b');
create table pd partition of p default;
insert into p values ('a'), ('A'), ('ab'), ('B'), ('b'), ('bz'), ('C'), ('c'), ('Ä'), ('z');
select tableoid::regclass, x from p order by x collate "C";
select x from p where x < 'B' order by x;
explain (costs off) select x from p where x < 'B';
explain (costs off) select x from p where x = 'bz';
explain (costs off) select x from p where x collate "C" < 'B';
create table q (x text) partition by range (x collate "sv-x-icu");
create table q1 partition of q for values from ('a') to ('z');
create table q2 partition of q for values from ('z') to (maxvalue);
insert into q values ('ä'), ('z'), ('zz'), ('y');
select tableoid::regclass, x from q order by x collate "C";
explain (costs off) select * from q where x > 'zz';
create table l (x text collate "de-x-icu") partition by list (x);
create table l1 partition of l for values in ('a', 'B');
create table l2 partition of l for values in ('b', 'A');
insert into l values ('a'), ('A'), ('b'), ('B');
select tableoid::regclass, x from l order by x collate "C";
select pg_get_partkeydef('q'::regclass), pg_get_partkeydef('p'::regclass);
create collation ci (provider = icu, locale = 'und-u-ks-level2', deterministic = false);
create table n (x text collate ci) partition by range (x);
create table n1 partition of n for values from ('a') to ('m');
insert into n values ('A'), ('L'), ('M');
create table h (x text collate ci) partition by hash (x);
create table h1 partition of h for values with (modulus 2, remainder 0);
create table h2 partition of h for values with (modulus 2, remainder 1);
insert into h values ('abc'), ('ABC'), ('x'), ('X');
select tableoid::regclass, x from h order by x collate "C";
create table nl (x text collate ci) partition by list (x);
create table nl1 partition of nl for values in ('a', 'B');
create table nl2 partition of nl for values in ('A');
create table nl3 partition of nl for values in ('c', 'C');
insert into nl values ('a'), ('A'), ('b'), ('c');
select tableoid::regclass, x from nl order by x collate "C";
select pg_get_expr(relpartbound, oid) from pg_class where relname like 'nl_' order by 1;
explain (costs off) select * from nl where x = 'C';
create table m (a text collate "sv-x-icu", b text collate "C") partition by range (a, b);
create table m1 partition of m for values from ('a', 'B') to ('z', 'a');
create table m2 partition of m for values from ('z', 'a') to ('ö', 'a');
insert into m values ('y', 'x'), ('z', 'A'), ('z', 'b'), ('ä', 'a');
select tableoid::regclass, a, b from m order by 2, 3;
explain (costs off) select * from m where a = 'z' and b < 'a';
explain (costs off) select * from m where a > 'z';
update m set a = 'ä' where a = 'y';
select tableoid::regclass, a, b from m order by 2, 3;
