-- Volatile select-list entries the ORDER BY does not use are evaluated after the sort
-- (and only for the rows a LIMIT lets through); an ORDER BY repeating a select-list
-- expression uses it rather than evaluating it again.
create table vse_v(a int, b text);
insert into vse_v values (3,'c'),(1,'a'),(2,'b'),(5,'e'),(4,'d');
create table vse_log(id serial, x int);
create function vse_f(x int) returns int language plpgsql volatile as $$ begin insert into vse_log(x) values (x); return x * 10; end $$;
create view vse_l as select string_agg(x::text, ',' order by id) as calls from vse_log;
select a, vse_f(a) from vse_v order by a;
select * from vse_l; delete from vse_log;
select a, vse_f(a) from vse_v order by a limit 2;
select * from vse_l; delete from vse_log;
select a, vse_f(a) from vse_v order by b desc limit 2;
select * from vse_l; delete from vse_log;
select vse_f(a) from vse_v order by vse_f(a);
select * from vse_l; delete from vse_log;
select vse_f(a) as x from vse_v order by x limit 2;
select * from vse_l; delete from vse_log;
select a, vse_f(a) from vse_v order by vse_f(a) desc limit 1;
select * from vse_l; delete from vse_log;
select a, vse_f(a) from vse_v order by vse_f(a) desc;
select * from vse_l; delete from vse_log;
select a, vse_f(a) from vse_v where a > 1 order by a offset 1 limit 2;
select * from vse_l; delete from vse_log;
select distinct a, vse_f(a) from vse_v order by a;
select * from vse_l; delete from vse_log;
select a, vse_f(a) from vse_v group by a order by a limit 2;
select * from vse_l; delete from vse_log;
select a, vse_f(a), row_number() over (order by a) from vse_v order by a desc limit 2;
select * from vse_l; delete from vse_log;
select a, vse_f(a) from vse_v order by a fetch first 1 rows with ties;
select * from vse_l; delete from vse_log;
select a, vse_f(a) from vse_v union all select 9, 9 order by 1 limit 2;
select * from vse_l; delete from vse_log;
select * from (select a, vse_f(a) from vse_v order by a limit 2) s;
select * from vse_l; delete from vse_log;
select a, vse_f(a) + 1 from vse_v order by a limit 3;
select * from vse_l; delete from vse_log;
select a, vse_f(a) from vse_v order by a, vse_f(a) limit 2;
select * from vse_l; delete from vse_log;
select a, vse_f(a), vse_f(a) from vse_v order by 3 limit 2;
select * from vse_l; delete from vse_log;
select a, vse_f(a) from vse_v order by a desc offset 3;
select * from vse_l; delete from vse_log;
select a, vse_f(a) from vse_v order by b || 'x' limit 2;
select * from vse_l; delete from vse_log;
select vse_f(a) from vse_v order by a limit 2;
select * from vse_l; delete from vse_log;
select * from vse_l; delete from vse_log;
create sequence vse_s;
select a, nextval('vse_s') from vse_v order by a desc;
select a, nextval('vse_s') from vse_v order by a limit 3;
select a, nextval('vse_s') n from vse_v order by nextval('vse_s') limit 2;
