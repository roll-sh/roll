-- tables, indexes and constraints
CREATE TABLE ft (id int, r floatrange, t textrange, m floatmultirange);
INSERT INTO ft VALUES (1, '[1,2)', '[a,b)', '{[1,2),[5,6)}'), (2, '(2,3]', 'empty', '{}'), (3, NULL, '[c,)', NULL);
SELECT * FROM ft ORDER BY r;
SELECT id FROM ft WHERE r && floatrange(1.5, 2.5) ORDER BY id;
SELECT id FROM ft WHERE m @> 5.5::float8;
CREATE INDEX ft_r ON ft USING gist (r);
CREATE INDEX ft_r2 ON ft (r);
SELECT id, r FROM ft WHERE r = '[1,2)';
CREATE TABLE fe (r floatrange, EXCLUDE USING gist (r WITH &&));
