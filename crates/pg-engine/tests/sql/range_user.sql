-- CREATE TYPE ... AS RANGE: user-defined range and multirange types.
CREATE TYPE floatrange AS RANGE (subtype = float8, subtype_diff = float8mi);
SELECT '[1.5,2.5)'::floatrange, floatrange(1, 2.5), floatrange(1, 2, '[]'), '{[1,2), [3,4)}'::floatmultirange, floatmultirange(floatrange(1,2));
SELECT pg_typeof(floatrange(1,2)), lower(floatrange(1.5,2)), floatrange(1,3) && floatrange(2,4), floatrange(1,3) -|- floatrange(3,4);
SELECT floatrange(1,3) * floatrange(2,4), floatrange(1,3) + floatrange(2,4), floatrange(1,5) - floatrange(2,3) AS err;
SELECT floatmultirange(floatrange(1,2), floatrange(3,4), floatrange(2,3)), floatmultirange(), floatrange(NULL, 3), floatrange(3, 1);
SELECT range_merge(floatrange(1,2), floatrange(5,6)), upper_inf(floatrange(1, NULL)), 2.5::float8 <@ floatrange(1,3);
SELECT typname, typtype, typarray::regtype FROM pg_type WHERE typname IN ('floatrange', 'floatmultirange', '_floatrange', '_floatmultirange') ORDER BY 1;
SELECT rngtypid::regtype, rngsubtype::regtype, rngmultitypid::regtype, rngsubdiff, rngcollation FROM pg_range WHERE rngtypid = 'floatrange'::regtype;
SELECT '{[1,2)}'::floatrange[], ARRAY[floatrange(1,2)], pg_typeof(ARRAY[floatmultirange()]);
CREATE TYPE textrange AS RANGE (subtype = text, multirange_type_name = textranges, collation = "C");
SELECT textrange('a', 'c'), textranges(textrange('a','b')), 'b'::text <@ textrange('a', 'c');
SELECT rngcollation, rngmultitypid::regtype FROM pg_range WHERE rngtypid = 'textrange'::regtype;
CREATE TYPE vrange AS RANGE (subtype = varchar);
SELECT rngcollation, rngmultitypid::regtype FROM pg_range WHERE rngtypid = 'vrange'::regtype;
CREATE TYPE int4span AS RANGE (subtype = int4);
SELECT int4span(1, 5), int4span(1, 5, '[]'), pg_typeof(int4span(1,2)), '{[1,3)}'::int4span_multirange;
