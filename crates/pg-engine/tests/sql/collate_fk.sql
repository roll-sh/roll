-- Foreign keys under collations: lookups and actions compare keys under the key's collation;
-- a nondeterministic primary key changing only its bytes still counts as changed (PG 18).
create collation ci (provider = icu, locale = 'und-u-ks-level2', deterministic = false);
create table pk (k text collate ci primary key);
create table fk (id int, k text collate ci references pk on update cascade on delete cascade);
insert into pk values ('abc'), ('xyz');
insert into fk values (1, 'ABC'), (2, 'abc'), (3, 'Xyz');
insert into fk values (4, 'q');
update pk set k = 'ABC' where k = 'abc';
select * from fk order by id;
update pk set k = 'Abc' where k = 'ABC';
select * from fk order by id;
delete from pk where k = 'XYZ';
select * from fk order by id;
create table pk2 (k text collate ci primary key);
create table fk2 (k text collate "C" references pk2 on update cascade);
create table fk3 (k text collate ci references pk2 on update restrict on delete restrict);
insert into pk2 values ('abc');
insert into fk3 values ('ABC');
update pk2 set k = 'ABC';
update pk2 set k = 'abd';
delete from pk2;
create table pk3 (k text collate ci primary key);
create table fk4 (k text collate ci references pk3 on update set null);
insert into pk3 values ('abc'); insert into fk4 values ('abc');
update pk3 set k = 'ABC';
select * from fk4;
create table pk4 (k text collate "de-x-icu" primary key);
create table fk5 (k text collate "de-x-icu" references pk4 on update cascade);
insert into pk4 values ('a'); insert into fk5 values ('a');
insert into fk5 values ('A');
update pk4 set k = 'A';
select * from fk5;
create table pk5 (k text collate ci primary key);
create table fk6 (k text collate ci references pk5 on update no action);
insert into pk5 values ('abc'); insert into fk6 values ('abc');
update pk5 set k = 'ABC';
select * from pk5, fk6;
create table a (k text collate ci primary key);
create table b (k text collate ci);
insert into a values ('abc');
insert into b values ('ABC'), ('Abc');
alter table b add constraint b_fk foreign key (k) references a;
insert into b values ('zzz');
create table c (k text collate ci);
insert into c values ('zzz');
alter table c add constraint c_fk foreign key (k) references a;
create table pp (k text collate ci primary key) partition by list (k);
create table pp1 partition of pp for values in ('a');
create table pp2 partition of pp for values in ('b');
insert into pp values ('A'), ('b');
create table pf (k text collate ci references pp on delete cascade);
insert into pf values ('a'), ('B');
insert into pf values ('c');
delete from pp where k = 'a';
select * from pf;
select * from pp order by k;
