ALTER TYPE ac_pt ADD ATTRIBUTE w int;
SELECT ps, ps[2].bee FROM ac_arr;
DROP TABLE ac_arr;
-- nested in another composite type, and function signatures
CREATE TYPE ac_inner AS (a int);
CREATE TYPE ac_outer AS (i ac_inner, n int);
CREATE FUNCTION ac_make(v int) RETURNS ac_inner LANGUAGE sql AS 'SELECT ROW(v)::ac_inner';
ALTER TYPE ac_inner ADD ATTRIBUTE b text;
SELECT ROW(ROW(1, 'x'), 2)::ac_outer;
SELECT ac_make(5);
ALTER TYPE ac_inner RENAME ATTRIBUTE a TO aa;
SELECT ((ROW(ROW(1, 'x'), 2)::ac_outer).i).aa;
CREATE TABLE ac_t2 (o ac_outer);
ALTER TYPE ac_inner ADD ATTRIBUTE c int;
SELECT * FROM ac_t2;
INSERT INTO ac_t2 VALUES (ROW(ROW(1, 'x', 2), 3));
ALTER TYPE ac_inner DROP ATTRIBUTE b;
SELECT o, (o).i, ((o).i).c FROM ac_t2;
DROP TABLE ac_t2;
DROP FUNCTION ac_make(int);
DROP TABLE ac_t, ac_plain;
DROP TYPE ac_outer, ac_inner, ac_pt, ac_mood;
