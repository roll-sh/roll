ALTER TYPE ac_pt DROP ATTRIBUTE y;
SELECT attname, atttypid::regtype FROM pg_attribute WHERE attrelid = 'ac_pt'::regclass AND attnum > 0 AND NOT attisdropped ORDER BY attnum;
SELECT ROW(1, 3)::ac_pt;
