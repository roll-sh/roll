-- used by a table column
CREATE TABLE ac_t (id int, p ac_pt);
INSERT INTO ac_t VALUES (1, ROW(1, 2.5)), (2, NULL);
INSERT INTO ac_t VALUES (3, ROW(7, 8.25)::ac_pt);
ALTER TYPE ac_pt ADD ATTRIBUTE c int, ADD ATTRIBUTE b text;
SELECT * FROM ac_t ORDER BY id;
UPDATE ac_t SET p.b = 'bee' WHERE id = 1;
ALTER TYPE ac_pt DROP ATTRIBUTE c;
ALTER TYPE ac_pt ALTER ATTRIBUTE zz TYPE int;
ALTER TYPE ac_pt RENAME ATTRIBUTE b TO bee;
SELECT (p).bee, (p).x, p FROM ac_t ORDER BY id;
ALTER TYPE ac_pt DROP ATTRIBUTE x;
SELECT * FROM ac_t ORDER BY id;
CREATE TABLE ac_arr (ps ac_pt[]);
