CREATE FUNCTION tt() RETURNS trigger LANGUAGE plpgsql AS $$ DECLARE r record; BEGIN
  IF TG_OP IN ('INSERT', 'UPDATE') THEN FOR r IN SELECT * FROM n ORDER BY k, v LOOP RAISE NOTICE '% new %', TG_TABLE_NAME, r; END LOOP; END IF;
  IF TG_OP IN ('DELETE', 'UPDATE') THEN FOR r IN SELECT * FROM o ORDER BY k, v LOOP RAISE NOTICE '% old %', TG_TABLE_NAME, r; END LOOP; END IF;
  RETURN NULL; END $$;
