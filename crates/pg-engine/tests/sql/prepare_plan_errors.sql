-- PREPARE (and a Parse message) only analyzes: what fails when the query is planned (folding a
-- constant call, inlining a SQL function) or when it starts (a merge join or sort without a
-- collation) fails at EXECUTE. EXPLAIN plans, so planning errors show there.
create table gxw_t1 (a text collate "C", b text collate "POSIX");
insert into gxw_t1 values ('a','a'),('b','b');
set enable_hashjoin = off; set enable_nestloop = off;
prepare gxw_q1 as select * from gxw_t1 x join gxw_t1 y on x.a = y.b;
explain (costs off) select * from gxw_t1 x join gxw_t1 y on x.a = y.b;
execute gxw_q1;
prepare gxw_q2 as select x.a from gxw_t1 x, gxw_t1 y where x.a || y.b > 'a';
execute gxw_q2;
prepare gxw_q3 as select * from gxw_t1 x where x.a = x.b;
execute gxw_q3;
explain (costs off) select * from gxw_t1 x where x.a = x.b;
prepare gxw_q4 as select x.a < x.b from gxw_t1 x;
explain (costs off) select x.a < x.b from gxw_t1 x;
execute gxw_q4;
prepare gxw_q6 as select * from gxw_t1 x order by x.a || x.b;
execute gxw_q6;
explain (costs off) select * from gxw_t1 x order by x.a || x.b;
prepare gxw_q7 as select distinct x.a || x.b from gxw_t1 x;
execute gxw_q7;
prepare gxw_q8 as select x.a || x.b from gxw_t1 x group by 1;
explain (costs off) select x.a || x.b from gxw_t1 x group by 1;
execute gxw_q8;
prepare gxw_q9 as select * from gxw_t1 x where x.a || x.b like 'a%';
execute gxw_q9;
prepare gxw_q10 as select x.a || x.b in ('aa') from gxw_t1 x;
execute gxw_q10;
drop table gxw_t1;
create table gxw_t1 (a text collate "C", b text collate "POSIX", n int);
insert into gxw_t1 values ('a','a',1),('b','b',0);
prepare gxw_d1 as select 1/0;
execute gxw_d1;
explain (costs off) select 1/0;
prepare gxw_d2 as select sqrt(-1);
execute gxw_d2;
prepare gxw_d3 as select 'abc'::int;
prepare gxw_d4 as select n from gxw_t1 where n = 1/0;
explain (costs off) select n from gxw_t1 where n = 1/0;
execute gxw_d4;
prepare gxw_d5 as select n / 0 from gxw_t1;
execute gxw_d5;
explain (costs off) select n / 0 from gxw_t1;
set check_function_bodies = off;
create function gxw_sf2(int) returns int language sql as 'select $1 + n from gxw_missing';
reset check_function_bodies;
prepare gxw_d6 as select gxw_sf2(1);
execute gxw_d6;
explain (costs off) select gxw_sf2(1);
prepare gxw_d8 as select upper(a || b) from gxw_t1;
execute gxw_d8;
explain (costs off) select upper(a || b) from gxw_t1;
prepare gxw_d9(int) as select $1 / 0;
execute gxw_d9(1);
prepare gxw_d10 as select x.a || x.b from gxw_t1 x where x.a || x.b < 'z';
explain (costs off) select x.a || x.b from gxw_t1 x where x.a || x.b < 'z';
execute gxw_d10;
prepare gxw_d11 as select array[1,2][3/0];
execute gxw_d11;
prepare gxw_d12 as select '2020-13-01'::date;
prepare gxw_d13 as select date '2020-01-01' + interval '1 day' / 0;
execute gxw_d13;
prepare gxw_d14 as select * from gxw_t1 where a = (select b from gxw_t1 limit 1 offset -1);
execute gxw_d14;
prepare gxw_d15 as select * from gxw_t1 limit -1;
execute gxw_d15;
prepare gxw_d16 as select * from generate_series(1, 3) g limit 1 offset 1/0;
execute gxw_d16;
deallocate all;
drop table gxw_t1;
drop function gxw_sf2;
