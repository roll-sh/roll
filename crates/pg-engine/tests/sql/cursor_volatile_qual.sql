-- Cursors scanning back and forth over a scan evaluate its volatile WHERE qual again for
-- each row passed (rows failing it now are skipped), and its target list
create sequence s;
create table t (a int);
insert into t values (1),(2),(3),(4);
create function q(int) returns bool language plpgsql volatile as $$ begin raise notice 'qual %', $1; return true; end $$;
create function odd(int) returns bool language plpgsql volatile as $$ declare n int := nextval('s'); begin raise notice 'odd % %', $1, n; return n % 2 = 1; end $$;
create function n(int) returns int language plpgsql volatile as $$ begin raise notice 'tl %', $1; return $1; end $$;
begin;
declare c scroll cursor for select a from t where q(a);
fetch 2 from c;
fetch prior from c;
fetch next from c;
fetch absolute 4 from c;
fetch backward all from c;
commit;
begin;
declare c scroll cursor for select a, n(a) from t where q(a);
fetch 2 from c;
fetch prior from c;
commit;
begin;
declare c scroll cursor for select a from t where odd(a);
fetch all from c;
fetch backward all from c;
fetch all from c;
commit;
begin;
declare c scroll cursor for select a from t where a > 1 and q(a);
fetch 2 from c;
fetch prior from c;
commit;
begin;
declare c scroll cursor for select a from t where q(a) order by a;
fetch 2 from c;
fetch prior from c;
commit;
begin;
declare c scroll cursor for select g from generate_series(1,3) g where q(g);
fetch 2 from c;
fetch prior from c;
commit;
begin;
declare c scroll cursor for select x from (values (1),(2),(3)) v(x) where q(x);
fetch 2 from c;
fetch prior from c;
commit;
begin;
declare c scroll cursor for select a from t where q(a) limit 3;
fetch 3 from c;
fetch prior from c;
fetch next from c;
fetch next from c;
fetch prior from c;
commit;
begin;
declare c scroll cursor for select a from t where q(a) limit 2;
fetch 2 from c;
fetch backward 3 from c;
fetch next from c;
fetch next from c;
fetch absolute 2 from c;
commit;
begin;
declare c scroll cursor for select a from t where q(a) limit 10;
fetch all from c;
fetch prior from c;
fetch prior from c;
fetch first from c;
fetch last from c;
move absolute 2 in c;
fetch relative 0 from c;
commit;
begin;
declare c scroll cursor for select a from t where odd(a) for read only;
fetch next from c;
fetch next from c;
fetch prior from c;
fetch absolute -1 from c;
commit;
-- updatable: WHERE CURRENT OF the row the qual landed on
begin;
declare c scroll cursor for select a from t where odd(a);
fetch next from c;
fetch next from c;
update t set a = a * 10 where current of c;
fetch prior from c;
delete from t where current of c;
commit;
select * from t order by a;
-- a holdable cursor runs into a store at commit (the qual evaluated once more per row)
begin;
declare c scroll cursor with hold for select a from t where q(a);
fetch next from c;
commit;
fetch next from c;
fetch prior from c;
fetch prior from c;
close c;
-- an index scan re-evaluates its residual qual too
create index t_a on t (a);
set enable_seqscan = off;
begin;
declare c scroll cursor for select a from t where a > 0 and q(a);
fetch 2 from c;
fetch prior from c;
commit;
reset enable_seqscan;
drop table t; drop function q, odd, n; drop sequence s;
