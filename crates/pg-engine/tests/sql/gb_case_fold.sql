-- CASE folding reaches only the arms eval_const_expressions keeps
SELECT CASE WHEN 1=0 THEN 1/0 WHEN 1=1 THEN 1 ELSE 2/0 END;
SELECT CASE 1 WHEN 0 THEN 1/0 WHEN 1 THEN 1 ELSE 2/0 END;
SELECT CASE WHEN true THEN 1 WHEN 1/0 = 1 THEN 2 END;
SELECT CASE WHEN false THEN 1/0 END;
SELECT CASE WHEN 1=1 THEN 1/0 END;
CREATE TABLE gb_cf (a int);
INSERT INTO gb_cf VALUES (1), (0), (NULL);
SELECT a, CASE WHEN a = 0 THEN 'zero' WHEN true THEN 'other' ELSE (1/0)::text END FROM gb_cf ORDER BY a;
SELECT a, CASE WHEN a > 0 THEN 1/0 ELSE 0 END FROM gb_cf ORDER BY a;
SELECT a, CASE a WHEN 1 THEN 'one' WHEN 0 THEN 'zero' END FROM gb_cf ORDER BY a;
SELECT CASE 2 WHEN 1 THEN 'one' WHEN 2 THEN 'two' END;
SELECT CASE NULL::int WHEN 1 THEN 'one' ELSE 'none' END;
SELECT a, CASE WHEN a = 1 THEN (SELECT 1/0) ELSE 0 END FROM gb_cf ORDER BY a;
SELECT NULLIF(1, 2), NULLIF(1, 1), NULLIF(1, NULL);
EXPLAIN (COSTS OFF) SELECT * FROM gb_cf WHERE NULLIF(1, 2) = 2;
EXPLAIN (COSTS OFF) SELECT * FROM gb_cf WHERE NULLIF(1, 1) IS NOT NULL;
EXPLAIN (COSTS OFF) SELECT CASE WHEN a = 1 THEN 1 WHEN true THEN 2 ELSE 3 END FROM gb_cf;
EXPLAIN (VERBOSE, COSTS OFF) SELECT CASE WHEN a = 1 THEN 1 WHEN false THEN 2 ELSE 3 END FROM gb_cf;
EXPLAIN (VERBOSE, COSTS OFF) SELECT CASE 1 WHEN a THEN 'x' WHEN 2 THEN 'y' END FROM gb_cf;
CREATE VIEW gb_cf_v AS SELECT CASE WHEN false THEN 1/0 WHEN a = 1 THEN 1 END AS c FROM gb_cf;
SELECT pg_get_viewdef('gb_cf_v');
DROP VIEW gb_cf_v;
