-- Prepared statements take custom plans (parameter values as constants) for their first five
-- runs, then the generic one; plan_cache_mode forces either; EXPLAIN EXECUTE shows which.
create table gx_pp_pt (a int primary key, b text);
insert into gx_pp_pt select g, 'v' || g from generate_series(1, 20) g;
prepare gx_pp_q(int) as select b from gx_pp_pt where a = $1;
explain (costs off) execute gx_pp_q(1);
execute gx_pp_q(1);
execute gx_pp_q(2);
execute gx_pp_q(3);
execute gx_pp_q(4);
select generic_plans, custom_plans from pg_prepared_statements where name = 'gx_pp_q';
explain (costs off) execute gx_pp_q(5);
select generic_plans, custom_plans from pg_prepared_statements where name = 'gx_pp_q';
execute gx_pp_q(6);
select generic_plans, custom_plans from pg_prepared_statements where name = 'gx_pp_q';
set plan_cache_mode = force_custom_plan;
explain (costs off) execute gx_pp_q(7);
set plan_cache_mode = force_generic_plan;
prepare gx_pp_q2(int) as select b from gx_pp_pt where a = $1;
explain (costs off) execute gx_pp_q2(7);
execute gx_pp_q2(8);
select name, generic_plans, custom_plans from pg_prepared_statements where name like 'gxo%' order by 1;
reset plan_cache_mode;
prepare gx_pp_x(text) as select xpath($1, '<a><b>1</b></a>'::xml);
execute gx_pp_x('//b/text()');
execute gx_pp_x('bad[');
prepare gx_pp_x2(text, xml) as select xpath($1, $2);
execute gx_pp_x2('bad[', '<a/>');
prepare gx_pp_n0 as select 1;
execute gx_pp_n0;
execute gx_pp_n0;
select name, generic_plans, custom_plans from pg_prepared_statements where name = 'gx_pp_n0';
prepare gx_pp_r(int) as select $1 + 1;
explain (verbose, costs off) execute gx_pp_r(1);
execute gx_pp_r(1); execute gx_pp_r(1); execute gx_pp_r(1); execute gx_pp_r(1);
explain (verbose, costs off) execute gx_pp_r(1);
select name, generic_plans, custom_plans from pg_prepared_statements where name = 'gx_pp_r';
prepare gx_pp_i(int) as insert into gx_pp_pt values ($1, 'x');
execute gx_pp_i(100);
select name, generic_plans, custom_plans from pg_prepared_statements where name = 'gx_pp_i';
deallocate all;
drop table gx_pp_pt;
select xpath('bad[', '<a/>'::xml);
create table gx_pp_xt (p text, x xml);
insert into gx_pp_xt values ('bad[', '<a/>');
select xpath(p, x) from gx_pp_xt;
set plan_cache_mode = force_generic_plan;
prepare gx_pp_x2(text, xml) as select xpath($1, $2);
execute gx_pp_x2('bad[', '<a/>');
reset plan_cache_mode;
deallocate all;
drop table gx_pp_xt;
create table gx_pp_t (a int, b text);
insert into gx_pp_t values (1, 'x'), (2, 'y');
prepare gx_pp_s(int) as select b from gx_pp_t where a = $1;
execute gx_pp_s(1);
select name, result_types, generic_plans, custom_plans from pg_prepared_statements;
prepare gx_pp_e(int) as select 1 / $1;
execute gx_pp_e(0);
select name, generic_plans, custom_plans from pg_prepared_statements where name = 'gx_pp_e';
prepare gx_pp_v(int) as select a from gx_pp_t where a > $1 order by a;
explain (costs off) execute gx_pp_v(1);
execute gx_pp_v(0); execute gx_pp_v(0); execute gx_pp_v(0); execute gx_pp_v(0);
explain (costs off) execute gx_pp_v(1);
execute gx_pp_v(1);
select name, generic_plans, custom_plans from pg_prepared_statements where name = 'gx_pp_v';
deallocate all;
drop table gx_pp_t;
