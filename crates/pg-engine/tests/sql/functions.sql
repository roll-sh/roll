CREATE FUNCTION add(a int, b int) RETURNS int AS 'SELECT a + b' LANGUAGE sql IMMUTABLE;
SELECT add(1, 2);
CREATE FUNCTION add(a int, b int) RETURNS int AS 'SELECT a - b' LANGUAGE sql;
CREATE OR REPLACE FUNCTION add(a int, b int) RETURNS int AS 'SELECT $1 * $2' LANGUAGE sql;
SELECT add(3, 4);
CREATE OR REPLACE FUNCTION add(a int, b int) RETURNS text AS 'SELECT 1' LANGUAGE sql;
CREATE FUNCTION add(a text, b text) RETURNS text LANGUAGE sql RETURN a || b;
SELECT add('x', 'y'), add(1, 1);
CREATE FUNCTION nums(n int) RETURNS SETOF int LANGUAGE sql AS $$ SELECT generate_series(1, n) $$;
SELECT * FROM nums(3);
CREATE FUNCTION pairs() RETURNS TABLE (a int, b text) LANGUAGE sql AS $$ VALUES (1, 'x'), (2, 'y') $$;
SELECT * FROM pairs() ORDER BY a;
CREATE TABLE emp (name text, salary int);
INSERT INTO emp VALUES ('a', 10), ('b', 20);
CREATE FUNCTION total() RETURNS bigint LANGUAGE sql STABLE AS 'SELECT sum(salary) FROM emp';
SELECT total();
CREATE FUNCTION greet(who text DEFAULT 'world') RETURNS text LANGUAGE sql AS $$ SELECT 'hi ' || who $$;
CREATE FUNCTION f_strict(x int) RETURNS int LANGUAGE sql STRICT AS 'SELECT 1';
SELECT f_strict(NULL), f_strict(5);
CREATE FUNCTION plp() RETURNS int LANGUAGE plpgsql AS $$ BEGIN RETURN 1; END $$;
CREATE FUNCTION badlang() RETURNS int LANGUAGE nosuch AS 'x';
SELECT proname, prorettype::regtype, provolatile, proisstrict FROM pg_proc WHERE proname IN ('add', 'nums', 'total', 'f_strict') ORDER BY proname, prorettype::regtype::text;
