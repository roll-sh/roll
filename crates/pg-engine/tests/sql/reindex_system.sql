select relname, oid::int8 - lag(oid::int8) over (order by oid) from pg_class where relname like 'mk%' order by oid;
select relname, relfilenode = oid, relfilenode <> 0 from pg_class where relname in ('pg_am', 'pg_am_oid_index', 'pg_am_name_index', 'pg_class_oid_index', 'pg_proc_oid_index', 'pg_toast_1255_index') order by relname;
select pg_relation_filenode('pg_class_oid_index') = 2662, pg_relation_filenode('pg_database_oid_index') = 2672;
select count(*) from pg_class c join pg_namespace n on n.oid = relnamespace where relkind = 'i' and nspname in ('pg_catalog', 'pg_toast') and not relisshared;
select count(*) from pg_class c join pg_namespace n on n.oid = relnamespace where relkind = 'i' and nspname in ('pg_catalog', 'pg_toast') and relisshared;
select pg_relation_filenode('pg_class_oid_index') <> 2662, pg_relation_filenode('pg_am_oid_index') = relfilenode, pg_relation_filepath('pg_class_oid_index') ~ '^base/\d+/\d+$', pg_relation_filepath('pg_database_oid_index') ~ '^global/\d+$' from pg_class where relname = 'pg_am_oid_index';
select pg_filenode_relation(0, pg_relation_filenode('pg_class_oid_index')), pg_filenode_relation(1664, pg_relation_filenode('pg_database_oid_index')), pg_filenode_relation(0, 2662);
