-- Cursors are planned for cursor_tuple_fraction (CURSOR_OPT_FAST_PLAN): whether one declared
-- without SCROLL / NO SCROLL can fetch backward, and whether one without FOR UPDATE is simply
-- updatable, are read off that plan; EXPLAIN DECLARE shows it.
CREATE TABLE ca (id int PRIMARY KEY, a int, b text);
CREATE TABLE cb (k int PRIMARY KEY, w text);
INSERT INTO ca SELECT g, g % 7, 'x' || g FROM generate_series(1, 30) g;
INSERT INTO cb SELECT g, 'w' || g FROM generate_series(1, 10) g;
CREATE TABLE cp (k int, v text, PRIMARY KEY (k, v)) PARTITION BY RANGE (k);
CREATE TABLE cp1 PARTITION OF cp FOR VALUES FROM (MINVALUE) TO (10);
CREATE TABLE cp2 PARTITION OF cp FOR VALUES FROM (10) TO (20);
INSERT INTO cp SELECT g, 'v' || g FROM generate_series(1, 19) g;
BEGIN;
DECLARE c1 CURSOR FOR SELECT id, a FROM ca ORDER BY id;
DECLARE c2 CURSOR FOR SELECT id, a FROM ca WHERE a > 0 ORDER BY a DESC, id;
DECLARE c3 CURSOR FOR SELECT k, v FROM cp ORDER BY k, v;
DECLARE c4 CURSOR FOR SELECT x.id, y.w FROM ca x LEFT JOIN cb y ON y.k = x.a ORDER BY x.id;
DECLARE c5 CURSOR FOR SELECT id, a FROM ca WHERE id = 3;
DECLARE c7 CURSOR FOR SELECT a, count(*) FROM ca GROUP BY a;
DECLARE c8 CURSOR FOR SELECT DISTINCT a FROM ca;
DECLARE c9 CURSOR FOR SELECT id FROM ca UNION ALL SELECT k FROM cb;
DECLARE c10 CURSOR FOR SELECT x.id, y.w FROM ca x JOIN cb y ON y.k = x.id;
SELECT name, is_scrollable FROM pg_cursors ORDER BY name;
FETCH 2 FROM c1;
UPDATE ca SET b = 'u' WHERE CURRENT OF c1;
FETCH PRIOR FROM c1;
FETCH 2 FROM c4;
SAVEPOINT s;
FETCH PRIOR FROM c4;
ROLLBACK TO s;
FETCH 1 FROM c5;
UPDATE ca SET b = 'v' WHERE CURRENT OF c5 RETURNING *;
FETCH 2 FROM c2;
UPDATE ca SET b = 'u' WHERE CURRENT OF c2;
COMMIT;
BEGIN;
DECLARE c3 CURSOR FOR SELECT k, v FROM cp ORDER BY k, v;
FETCH 2 FROM c3;
DELETE FROM cp WHERE CURRENT OF c3 RETURNING *;
FETCH PRIOR FROM c3;
COMMIT;
ANALYZE ca;
ANALYZE cb;
ANALYZE cp;
BEGIN;
DECLARE c3 CURSOR FOR SELECT k, v FROM cp ORDER BY k, v;
DECLARE c4 CURSOR FOR SELECT x.id, y.w FROM ca x LEFT JOIN cb y ON y.k = x.a ORDER BY x.id;
SELECT name, is_scrollable FROM pg_cursors ORDER BY name;
FETCH 2 FROM c3;
DELETE FROM cp WHERE CURRENT OF c3;
COMMIT;
EXPLAIN (COSTS OFF) DECLARE c CURSOR FOR SELECT id, a FROM ca ORDER BY id;
EXPLAIN (COSTS OFF) DECLARE c CURSOR FOR SELECT x.id, y.w FROM ca x LEFT JOIN cb y ON y.k = x.a ORDER BY x.id;
EXPLAIN DECLARE c CURSOR FOR SELECT k, v FROM cp ORDER BY k, v;
EXPLAIN DECLARE c CURSOR FOR SELECT x.id, y.w FROM ca x JOIN cb y ON y.k = x.id;
EXPLAIN (COSTS OFF) DECLARE c SCROLL CURSOR FOR SELECT x.id, y.w FROM ca x JOIN cb y ON y.k = x.id;
EXPLAIN (COSTS OFF) DECLARE c CURSOR FOR SELECT x.id, y.w FROM ca x LEFT JOIN cb y ON y.k = x.a WHERE y.w IS NULL OR x.id > 3;
SET cursor_tuple_fraction = 1.0;
EXPLAIN DECLARE c CURSOR FOR SELECT x.id, y.w FROM ca x JOIN cb y ON y.k = x.id;
SET cursor_tuple_fraction = 0.0;
EXPLAIN DECLARE c CURSOR FOR SELECT x.id, y.w FROM ca x JOIN cb y ON y.k = x.id;
RESET cursor_tuple_fraction;
-- (No parallel plan for a cursor: CURSOR_OPT_PARALLEL_OK isn't set.)
SET max_parallel_workers_per_gather = 4;
SET parallel_setup_cost = 0;
SET parallel_tuple_cost = 0;
SET min_parallel_table_scan_size = 0;
EXPLAIN (COSTS OFF) DECLARE c CURSOR FOR SELECT count(*) FROM ca;
RESET max_parallel_workers_per_gather;
RESET parallel_setup_cost;
RESET parallel_tuple_cost;
RESET min_parallel_table_scan_size;
