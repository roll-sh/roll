SELECT
    a.attrelid::regclass::text AS table_name,
    a.attname AS column_name,
    CASE
        WHEN NOT a.attisdropped THEN
            CASE
                WHEN a.attnotnull THEN 'NO'
                ELSE 'YES'
            END
        ELSE NULL
    END AS is_nullable,
    a.attndims AS array_dimensions,
    CASE
        WHEN a.atttypid = ANY ('{int,int8,int2}'::regtype[])
        AND EXISTS (
            SELECT FROM pg_attrdef ad
            WHERE ad.adrelid = a.attrelid
            AND ad.adnum = a.attnum
            AND pg_get_expr(ad.adbin, ad.adrelid) = 'nextval('''
                || pg_get_serial_sequence(a.attrelid::regclass::text, a.attname)::regclass || '''::regclass)'
        )
        THEN CASE a.atttypid
            WHEN 'int'::regtype THEN 'serial'
            WHEN 'int8'::regtype THEN 'bigserial'
            WHEN 'int2'::regtype THEN 'smallserial'
        END
        ELSE format_type(a.atttypid, a.atttypmod)
    END AS data_type,
    pg_get_serial_sequence('"public"."users"', a.attname)::regclass AS seq_name,
    c.column_default,
    c.data_type AS additional_dt,
    c.udt_name AS enum_name,
    c.is_generated,
    c.generation_expression,
    c.is_identity,
    c.identity_generation,
    c.identity_start,
    c.identity_increment,
    c.identity_maximum,
    c.identity_minimum,
    c.identity_cycle,
    enum_ns.nspname AS type_schema
FROM
    pg_attribute a
JOIN
    pg_class cls ON cls.oid = a.attrelid
JOIN
    pg_namespace ns ON ns.oid = cls.relnamespace
LEFT JOIN
    information_schema.columns c ON c.column_name = a.attname
        AND c.table_schema = ns.nspname
        AND c.table_name = cls.relname
LEFT JOIN
    pg_type enum_t ON enum_t.oid = a.atttypid
LEFT JOIN
    pg_namespace enum_ns ON enum_ns.oid = enum_t.typnamespace
WHERE
    a.attnum > 0
    AND NOT a.attisdropped
    AND cls.relkind IN ('r', 'v', 'm')
    AND ns.nspname = 'public'
    AND cls.relname = 'users'
ORDER BY
    a.attnum;
