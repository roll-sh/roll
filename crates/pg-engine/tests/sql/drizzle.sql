-- drizzle-kit (pull) introspection queries over a typical drizzle schema
CREATE TYPE mood AS ENUM ('sad', 'ok', 'happy');
CREATE TABLE users (
  id serial PRIMARY KEY,
  big_id bigint GENERATED ALWAYS AS IDENTITY (START WITH 10 INCREMENT BY 2),
  email varchar(256) NOT NULL,
  name text DEFAULT 'anon',
  mood mood DEFAULT 'ok' NOT NULL,
  prefs jsonb DEFAULT '{}'::jsonb,
  scores integer[],
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  full_name text GENERATED ALWAYS AS (name || '!') STORED,
  CONSTRAINT users_email_unique UNIQUE (email),
  CONSTRAINT name_len CHECK (length(name) < 100)
);
CREATE TABLE posts (
  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  author_id integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  title text NOT NULL,
  rank numeric(10, 2) DEFAULT 0
);
CREATE TABLE likes (user_id integer NOT NULL, post_id integer NOT NULL, CONSTRAINT likes_pk PRIMARY KEY (user_id, post_id));
ALTER TABLE likes ADD CONSTRAINT likes_post_fk FOREIGN KEY (post_id) REFERENCES posts (id) ON UPDATE CASCADE;
CREATE INDEX posts_author_idx ON posts (author_id, id DESC);
CREATE UNIQUE INDEX users_name_idx ON users USING btree (name) WHERE name IS NOT NULL;
CREATE SEQUENCE counter START 5 INCREMENT 5 MAXVALUE 1000 CYCLE;
CREATE VIEW recent AS SELECT id, title FROM posts WHERE id > 10;
SELECT
    n.nspname AS table_schema,
    c.relname AS table_name,
    CASE
        WHEN c.relkind = 'r' THEN 'table'
        WHEN c.relkind = 'v' THEN 'view'
        WHEN c.relkind = 'm' THEN 'materialized_view'
    END AS type,
	c.relrowsecurity AS rls_enabled
FROM
    pg_catalog.pg_class c
JOIN
    pg_catalog.pg_namespace n ON n.oid = c.relnamespace
WHERE
	c.relkind IN ('r', 'v', 'm')
     AND n.nspname = 'public';
select s.nspname as table_schema
  from pg_catalog.pg_namespace s
  join pg_catalog.pg_user u on u.usesysid = s.nspowner
  where nspname not in ('information_schema', 'pg_catalog', 'public')
        and nspname not like 'pg_toast%'
        and nspname not like 'pg_temp_%'
  order by table_schema;
select schemaname, sequencename, start_value, min_value, max_value, increment_by, cycle, cache_size from pg_sequences as seq WHERE schemaname = 'public';
select n.nspname as enum_schema,
  t.typname as enum_name,
  e.enumlabel as enum_value,
  e.enumsortorder as sort_order
  from pg_type t
  join pg_enum e on t.oid = e.enumtypid
  join pg_catalog.pg_namespace n ON n.oid = t.typnamespace
   WHERE n.nspname = 'public'
  order by enum_schema, enum_name, sort_order;
