-- CREATE / ALTER / DROP OPERATOR FAMILY and OPERATOR CLASS, their catalog rows and
-- dependencies, and a hash partition key with a made support function.
create function opc_hash(value int4, seed int8) returns int8 as $$ select value + seed $$ language sql strict immutable;
create operator class opc_hash_ops for type int4 using hash as operator 1 =, function 2 opc_hash(int4, int8);
select opcname, opcintype::regtype, opcdefault, opckeytype from pg_opclass where opcname = 'opc_hash_ops';
select opfname, opfmethod from pg_opfamily where opfname = 'opc_hash_ops';
select amopstrategy, amoplefttype::regtype, amoprighttype::regtype, amopopr::regoperator, amoppurpose from pg_amop a join pg_opfamily f on f.oid = a.amopfamily where f.opfname = 'opc_hash_ops';
select amprocnum, amproclefttype::regtype, amprocrighttype::regtype, amproc::regprocedure from pg_amproc a join pg_opfamily f on f.oid = a.amprocfamily where f.opfname = 'opc_hash_ops';
select pg_describe_object(classid, objid, objsubid) as obj, pg_describe_object(refclassid, refobjid, refobjsubid) as ref, deptype from pg_depend where classid in ('pg_opclass'::regclass, 'pg_opfamily'::regclass, 'pg_amop'::regclass, 'pg_amproc'::regclass) and objid >= 16384 order by 1, 2;
create table opc_hp (a int) partition by hash (a opc_hash_ops);
create table opc_hp0 partition of opc_hp for values with (modulus 4, remainder 0);
create table opc_hp1 partition of opc_hp for values with (modulus 4, remainder 1);
create table opc_hp2 partition of opc_hp for values with (modulus 4, remainder 2);
create table opc_hp3 partition of opc_hp for values with (modulus 4, remainder 3);
insert into opc_hp select generate_series(1, 12);
select tableoid::regclass, a from opc_hp order by 2;
select satisfies_hash_partition('opc_hp'::regclass, 4, 0, 4), satisfies_hash_partition('opc_hp'::regclass, 4, 1, 4);
select satisfies_hash_partition('opc_hp'::regclass, 0, 0, 4);
select satisfies_hash_partition('opc_hp'::regclass, 4, 0, variadic array[4]);
drop operator class opc_hash_ops using hash;
drop operator family opc_hash_ops using hash;
drop operator class opc_hash_ops using btree;
drop operator class if exists opc_hash_ops using btree;
drop operator family if exists nope.opc_hash_ops using btree;
drop operator family if exists opc_hash_ops using nope;
drop table opc_hp;
