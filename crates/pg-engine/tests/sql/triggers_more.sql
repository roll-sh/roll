CREATE TABLE tm (a int PRIMARY KEY, b text, c int CHECK (c >= 0));
CREATE VIEW tmv AS SELECT a, b FROM tm;
CREATE FUNCTION tm_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE NOTICE '% % % % argv=%', TG_NAME, TG_WHEN, TG_LEVEL, TG_OP, TG_ARGV;
  IF TG_LEVEL = 'STATEMENT' THEN RETURN NULL; END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END $$;
