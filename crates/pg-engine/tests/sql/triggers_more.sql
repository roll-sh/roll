CREATE FUNCTION tmv_ins() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.a < 0 THEN RETURN NULL; END IF;
  INSERT INTO tm VALUES (NEW.a, NEW.b, 0);
  NEW.b := NEW.b || ' (via view)';
  RETURN NEW;
END $$;
