-- transition tables with ON CONFLICT and FK cascades
CREATE TABLE tc (k int PRIMARY KEY, v int);
CREATE FUNCTION tc_dump() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE n int; o int;
BEGIN
  IF TG_OP = 'INSERT' THEN
    SELECT count(*) INTO n FROM nt;
    RAISE NOTICE '% inserted %', TG_NAME, n;
  ELSE
    SELECT count(*) INTO o FROM ot;
    SELECT count(*) INTO n FROM nt;
    RAISE NOTICE '% updated old=% new=% sum=%', TG_NAME, o, n, (SELECT sum(v) FROM nt);
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER tc_i AFTER INSERT ON tc REFERENCING NEW TABLE AS nt FOR EACH STATEMENT EXECUTE FUNCTION tc_dump();
CREATE TRIGGER tc_u AFTER UPDATE ON tc REFERENCING OLD TABLE AS ot NEW TABLE AS nt FOR EACH STATEMENT EXECUTE FUNCTION tc_dump();
