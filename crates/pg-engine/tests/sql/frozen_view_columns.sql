-- A view's query is fixed when it is made, as Postgres's stored tree is: the columns `*`
-- stood for, the columns NATURAL joined on, the relations it named; columns added to or
-- dropped from its tables later, and search_path changes, don't change it.
create schema fvc;
set search_path = fvc, public;
create table tt2 (a int, b int, c int);
create table tt3 (ax int8, b int2, c numeric);
create table tt4 (ay int, b int, q int);
create view v1 as select * from tt2 natural join tt3;
create view v1a as select * from (tt2 natural join tt3) j;
create view v2 as select * from tt2 join tt3 using (b,c) join tt4 using (b);
create view v2a as select * from (tt2 join tt3 using (b,c) join tt4 using (b)) j;
create view v3 as select * from tt2 join tt3 using (b,c) full join tt4 using (b);
create view v5 as select * from (select * from tt2) s, (select ay, q from tt4) s4;
select pg_get_viewdef('v1', true);
select pg_get_viewdef('v2', true);
select pg_get_viewdef('v3', true);
select pg_get_viewdef('v5', true);
alter table tt2 add column d int;
alter table tt2 add column e int;
select pg_get_viewdef('v1', true);
select pg_get_viewdef('v1a', true);
select pg_get_viewdef('v2', true);
select pg_get_viewdef('v3', true);
select pg_get_viewdef('v5', true);
alter table tt3 rename c to d;
select pg_get_viewdef('v1', true);
select pg_get_viewdef('v1a', true);
select pg_get_viewdef('v2', true);
select pg_get_viewdef('v3', true);
alter table tt3 add column c int;
alter table tt3 add column e int;
select pg_get_viewdef('v1', true);
select pg_get_viewdef('v1a', true);
select pg_get_viewdef('v2', true);
select pg_get_viewdef('v3', true);
alter table tt2 drop column d;
select pg_get_viewdef('v1', true);
select pg_get_viewdef('v2', true);
insert into tt2 values (1, 2, 3, 4);
insert into tt3 values (10, 2, 3, 0, 5);
insert into tt4 values (100, 2, 7);
select * from v1;
select * from v2;
select * from v3;
select * from v5;
reset search_path;
select * from fvc.v1;
select pg_get_viewdef('fvc.v2', true);
drop schema fvc cascade;
