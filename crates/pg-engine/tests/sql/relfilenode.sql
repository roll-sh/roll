-- pg_class.relfilenode: new files on TRUNCATE, rewrites and REINDEX, relative to a marker
-- table made right after (each marker takes three oids)
create table t (a int primary key, b text);
create index t_b on t (b);
create table mk ();
create view files as select c.oid, regexp_replace(c.relname, '\d+', 'N') rel, c.relfilenode::int8 - (select max(oid::int8) from pg_class where relname like 'mk%') d, c.relfilenode = c.oid same from pg_class c where relname like 't%' or c.oid = (select reltoastrelid from pg_class where relname = 't') or c.oid = (select reltoastrelid from pg_class where relname = 't') + 1;
select rel, d, same from files order by oid;
truncate t;
create table mk1 ();
select rel, d, same from files order by oid;
vacuum full t;
create table mk2 ();
select rel, d, same from files order by oid;
cluster t using t_pkey;
create table mk3 ();
select rel, d, same from files order by oid;
-- binary-coercible type change: the rebuilt index keeps its file
alter table t alter b type varchar;
create table mk4 ();
select rel, d, same from files order by oid;
-- ... unless its collation changes
alter table t alter b type varchar collate "C";
create table mk4a ();
select rel, d, same from files order by oid;
reindex table t;
create table mk5 ();
select rel, d, same from files order by oid;
reindex index t_b;
create table mk6 ();
select rel, d, same from files order by oid;
