create table mk8 ();
select rel, d, same from files order by oid;
alter table t set unlogged;
create table mk9 ();
select rel, d, same from files order by oid;
reindex table concurrently t;
create table mk10 ();
select rel, d, same from files order by oid;
select relname, oid::int8 - lag(oid::int8) over (order by oid) from pg_class where relname ~ '^mk' order by oid;
