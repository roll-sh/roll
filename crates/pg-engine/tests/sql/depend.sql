-- pg_depend as Postgres records it, read through pg_describe_object
CREATE SCHEMA gd;
CREATE TYPE gd.mood AS ENUM ('a','b');
CREATE DOMAIN gd.pos AS int CHECK (VALUE > 0) DEFAULT 1;
CREATE DOMAIN gd.pos2 AS gd.pos NOT NULL;
CREATE TYPE gd.co AS (x int, m gd.mood);
CREATE TYPE gd.rng AS RANGE (subtype = float8);
CREATE SEQUENCE gd.s;
CREATE TABLE gd.p (id serial PRIMARY KEY, n int NOT NULL CHECK (n > 0), m gd.mood DEFAULT 'a', d gd.pos, u text UNIQUE, g int GENERATED ALWAYS AS (n * 2) STORED, s2 bigint DEFAULT nextval('gd.s'));
CREATE TABLE gd.c (id int GENERATED ALWAYS AS IDENTITY, pid int REFERENCES gd.p ON DELETE CASCADE, arr gd.mood[], cc gd.co, CHECK (pid <> id));
CREATE INDEX c_pid ON gd.c (pid);
CREATE INDEX c_expr ON gd.c ((pid + 1));
CREATE INDEX c_part ON gd.c (id) WHERE pid > 0;
CREATE TABLE gd.kid (extra int) INHERITS (gd.p);
CREATE VIEW gd.v AS SELECT id, n FROM gd.p WHERE n > 1;
CREATE VIEW gd.v2 AS SELECT count(*) AS c FROM gd.c;
CREATE MATERIALIZED VIEW gd.mv AS SELECT n FROM gd.p;
CREATE FUNCTION gd.f(gd.co) RETURNS gd.mood LANGUAGE sql AS 'SELECT $1.m';
CREATE FUNCTION gd.tf() RETURNS trigger LANGUAGE plpgsql AS 'BEGIN RETURN NEW; END';
CREATE FUNCTION gd.ba(int) RETURNS int LANGUAGE sql BEGIN ATOMIC SELECT count(*)::int FROM gd.p WHERE n = $1; END;
CREATE PROCEDURE gd.pr(a int) LANGUAGE sql AS 'SELECT 1';
CREATE TRIGGER gd_t BEFORE UPDATE OF n ON gd.p FOR EACH ROW EXECUTE FUNCTION gd.tf();
ALTER TABLE gd.p ENABLE ROW LEVEL SECURITY;
CREATE POLICY gd_pol ON gd.p USING (n > 0 AND u IS NOT NULL);
CREATE TABLE gd.pt (k int, v text) PARTITION BY RANGE (k);
CREATE TABLE gd.pt1 PARTITION OF gd.pt FOR VALUES FROM (0) TO (10);
CREATE TABLE gd.typed OF gd.co;
CREATE STATISTICS gd.st ON id, pid FROM gd.c;
CREATE TABLE public.gd_vis (a int PRIMARY KEY);
CREATE SCHEMA ge;
CREATE TYPE ge.en AS ENUM ('x','y');
CREATE FUNCTION ge.ok(int) RETURNS bool LANGUAGE sql IMMUTABLE AS 'SELECT $1 > 0';
CREATE DOMAIN ge.dm AS int CHECK (ge.ok(VALUE));
CREATE TABLE ge.pp (a int, b int, e ge.en DEFAULT 'x', PRIMARY KEY (a, b), CHECK (true)) PARTITION BY RANGE (a);
CREATE TABLE ge.pp1 PARTITION OF ge.pp FOR VALUES FROM (0) TO (10);
CREATE TABLE ge.ex (k int) PARTITION BY LIST ((k + 1));
CREATE INDEX pp_b ON ge.pp (b) INCLUDE (e);
CREATE TABLE ge.r (a int, b int, FOREIGN KEY (a, b) REFERENCES ge.pp);
CREATE TABLE ge.rp (a int, b int, FOREIGN KEY (a, b) REFERENCES ge.pp) PARTITION BY RANGE (a);
CREATE TABLE ge.rp1 PARTITION OF ge.rp FOR VALUES FROM (0) TO (5);
CREATE FUNCTION ge.tf() RETURNS trigger LANGUAGE plpgsql AS 'BEGIN RETURN NEW; END';
CREATE TRIGGER tw AFTER UPDATE ON ge.pp FOR EACH ROW WHEN (NEW.b > OLD.b) EXECUTE FUNCTION ge.tf();
CREATE STATISTICS ge.sx ON (a + b), a FROM ge.r;
CREATE SEQUENCE ge.sq OWNED BY ge.r.a;
CREATE VIEW ge.vv AS SELECT 'x'::ge.en AS e, ge.ok(a) AS ok, r.* FROM ge.r;
CREATE FUNCTION ge.df(a int DEFAULT ge.ok(1)::int) RETURNS ge.dm LANGUAGE sql AS 'SELECT 1';
CREATE FUNCTION ge.add(ge.en, ge.en) RETURNS ge.en LANGUAGE sql AS 'SELECT $1';
CREATE OPERATOR ge.### (LEFTARG = ge.en, RIGHTARG = ge.en, FUNCTION = ge.add);
CREATE AGGREGATE ge.agg(ge.en) (SFUNC = ge.add, STYPE = ge.en);
CREATE TABLE ge.dt (d ge.dm DEFAULT 3, i int GENERATED BY DEFAULT AS IDENTITY);
CREATE VIEW ge.vv2 AS SELECT e, ok FROM ge.vv WHERE e = 'y';
CREATE FUNCTION ge.rt(x ge.en) RETURNS int LANGUAGE sql RETURN (SELECT count(*) FROM ge.r WHERE b > 0)::int;
CREATE TABLE ge.ck (a int CHECK (b > 0), b int CHECK (a > b), c int CHECK (true), d int CHECK (d > 0 AND d < 9), CHECK (ck.c > 0));
SELECT pg_describe_object(classid, objid, objsubid) AS obj, pg_describe_object(refclassid, refobjid, refobjsubid) AS ref, deptype FROM pg_depend
  WHERE (objid >= 16384 OR refobjid >= 16384) AND pg_describe_object(classid, objid, objsubid) !~ 'toast|RI_ConstraintTrigger'
  ORDER BY 1, 2, 3;
SELECT pg_describe_object(classid, objid, objsubid) AS obj, pg_describe_object(refclassid, refobjid, refobjsubid) AS ref, deptype FROM pg_depend WHERE deptype = 'e' ORDER BY 1;
SELECT rulename, ev_class::regclass, ev_type, ev_enabled, is_instead FROM pg_rewrite WHERE ev_class >= 16384 ORDER BY 2;
SELECT conname FROM pg_constraint WHERE conrelid = 'ge.ck'::regclass AND contype = 'c' ORDER BY 1;
SELECT oid::regprocedure, prosrc, provariadic::regtype, proallargtypes::regtype[], proargmodes, proisstrict FROM pg_proc WHERE pronamespace = 'gd'::regnamespace ORDER BY oid;
SELECT castsource::regtype, casttarget::regtype, castfunc::regprocedure, castcontext, castmethod FROM pg_cast WHERE castsource = 'gd.rng'::regtype;
SELECT oid::regprocedure, prolang::regproc, probin FROM pg_proc WHERE oid IN (SELECT unnest(ARRAY[lanplcallfoid, laninline, lanvalidator]) FROM pg_language) ORDER BY oid;
SELECT format_type('gd.co'::regtype, NULL), format_type('gd.mood[]'::regtype, NULL), pg_get_function_arguments('gd.f'::regproc), pg_get_function_result('gd.f'::regproc);
SELECT pg_describe_object('pg_class'::regclass, 'pg_class'::regclass, 0), pg_describe_object('pg_type'::regclass, 'int4'::regtype, 0), pg_describe_object('pg_namespace'::regclass, 'public'::regnamespace, 0), pg_describe_object(0, 0, 0);
DROP SCHEMA gd, ge CASCADE;
DROP TABLE public.gd_vis;
-- EXECUTE on a user aggregate is checked like a function's
CREATE ROLE dep_r;
CREATE AGGREGATE dep_ag(int) (sfunc = int4pl, stype = int);
REVOKE EXECUTE ON FUNCTION dep_ag(int) FROM PUBLIC;
SET ROLE dep_r;
SELECT dep_ag(1);
RESET ROLE;
DROP AGGREGATE dep_ag(int);
DROP ROLE dep_r;
-- ALTER TABLE DROP COLUMN / CONSTRAINT go through the dependency graph
CREATE SCHEMA da;
SET search_path = da, public;
CREATE SEQUENCE zs;
CREATE FUNCTION zf(int) RETURNS int LANGUAGE sql IMMUTABLE AS 'SELECT $1';
CREATE TABLE zt (id int PRIMARY KEY DEFAULT nextval('zs'), v int DEFAULT zf(1) CHECK (zf(v) > 0), w serial);
CREATE INDEX zt_fi ON zt (zf(v));
CREATE TABLE zc (tid int REFERENCES zt);
CREATE VIEW zv AS SELECT id, zf(v) FROM zt;
CREATE VIEW zv2 AS SELECT * FROM zv;
CREATE FUNCTION ztf() RETURNS trigger LANGUAGE plpgsql AS 'BEGIN RETURN NEW; END';
CREATE TRIGGER ztt BEFORE INSERT ON zt FOR EACH ROW WHEN (zf(NEW.v) > 0) EXECUTE FUNCTION ztf();
CREATE POLICY zp ON zt USING (zf(v) > 0);
CREATE STATISTICS zst ON id, v FROM zt;
ALTER TABLE zt DROP COLUMN v;
ALTER TABLE zt DROP COLUMN id;
ALTER TABLE zt DROP CONSTRAINT zt_pkey;
BEGIN;
ALTER TABLE zt DROP COLUMN v CASCADE;
SELECT relname FROM pg_class WHERE relnamespace = 'da'::regnamespace ORDER BY 1;
ROLLBACK;
BEGIN;
ALTER TABLE zt DROP CONSTRAINT zt_pkey CASCADE;
SELECT conname FROM pg_constraint WHERE connamespace = 'da'::regnamespace ORDER BY 1;
ROLLBACK;
ALTER TABLE zt DROP COLUMN w;
SELECT relname FROM pg_class WHERE relnamespace = 'da'::regnamespace AND relkind = 'S' ORDER BY 1;
CREATE TABLE zpp (a int, b int) PARTITION BY RANGE (a);
CREATE TABLE zpp1 PARTITION OF zpp FOR VALUES FROM (0) TO (10);
CREATE VIEW zppv AS SELECT b FROM zpp;
CREATE VIEW zppv1 AS SELECT b FROM zpp1;
ALTER TABLE zpp DROP COLUMN b;
ALTER TABLE zpp1 DROP COLUMN b;
CREATE TABLE zg (a int, b int GENERATED ALWAYS AS (a*2) STORED, c int GENERATED ALWAYS AS (a*3) VIRTUAL);
ALTER TABLE zg DROP COLUMN a;
BEGIN;
ALTER TABLE zg DROP COLUMN a CASCADE;
SELECT attname FROM pg_attribute WHERE attrelid = 'zg'::regclass AND attnum > 0 ORDER BY attnum;
ROLLBACK;
CREATE TABLE zi (a int, b int);
CREATE TABLE zic () INHERITS (zi);
CREATE VIEW ziv AS SELECT b FROM zic;
ALTER TABLE zi DROP COLUMN b;
ALTER TABLE ONLY zi DROP COLUMN b;
SELECT attname, attislocal, attinhcount FROM pg_attribute WHERE attrelid = 'zic'::regclass AND attnum > 0 ORDER BY attnum;
DROP SCHEMA da CASCADE;
RESET search_path;
