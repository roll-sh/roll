-- Prisma's databases: a51_prisma for migrate / db push / the client (and its shadow database
-- a51_prisma_shadow), a51_prisma_intro for `db pull` of a hand-written schema.
DROP DATABASE IF EXISTS a51_prisma;
DROP DATABASE IF EXISTS a51_prisma_shadow;
DROP DATABASE IF EXISTS a51_prisma_intro;
CREATE DATABASE a51_prisma;
CREATE DATABASE a51_prisma_shadow;
CREATE DATABASE a51_prisma_intro;
\c a51_prisma_intro
CREATE EXTENSION citext;
CREATE SCHEMA other;
CREATE TYPE mood AS ENUM ('sad', 'ok', 'happy');
CREATE TYPE other.level AS ENUM ('low', 'high');
CREATE SEQUENCE ticket_seq START 100 INCREMENT 5;
CREATE TABLE account (
  id bigserial PRIMARY KEY,
  email citext NOT NULL UNIQUE,
  name varchar(80) NOT NULL DEFAULT 'anon',
  mood mood NOT NULL DEFAULT 'ok',
  score numeric(10, 2) CHECK (score >= 0),
  ratio double precision,
  small smallint DEFAULT 1,
  flag boolean NOT NULL DEFAULT false,
  born date,
  wake time(3),
  created timestamptz(6) NOT NULL DEFAULT now(),
  updated timestamp(3),
  tags text[] NOT NULL DEFAULT '{}',
  nums integer[],
  meta jsonb DEFAULT '{"a": 1}',
  raw json,
  blob bytea,
  uid uuid NOT NULL DEFAULT gen_random_uuid(),
  ip inet,
  bits bit(4),
  vbits varbit(8),
  ch char(3),
  x xml,
  money_col money,
  iv interval,
  ticket integer NOT NULL DEFAULT nextval('ticket_seq'),
  gen integer GENERATED ALWAYS AS (small * 2) STORED,
  ident integer GENERATED BY DEFAULT AS IDENTITY
);
COMMENT ON TABLE account IS 'people';
COMMENT ON COLUMN account.email IS 'login';
CREATE INDEX account_name_idx ON account (name DESC NULLS LAST);
CREATE INDEX account_lower_idx ON account (lower(name));
CREATE INDEX account_meta_gin ON account USING gin (meta jsonb_path_ops);
CREATE INDEX account_partial ON account (born) WHERE flag;
CREATE UNIQUE INDEX account_name_born ON account (name, born);
CREATE INDEX account_hash ON account USING hash (uid);
CREATE TABLE post (
  id serial PRIMARY KEY,
  author_id bigint NOT NULL REFERENCES account (id) ON DELETE CASCADE ON UPDATE RESTRICT,
  editor_id bigint REFERENCES account (id) ON DELETE SET NULL,
  title text NOT NULL,
  body text,
  published boolean DEFAULT false,
  CONSTRAINT post_title_len CHECK (length(title) > 0),
  CONSTRAINT post_author_title UNIQUE (author_id, title)
);
CREATE TABLE tag (name text PRIMARY KEY);
CREATE TABLE post_tag (
  post_id integer REFERENCES post (id),
  tag_name text REFERENCES tag (name),
  PRIMARY KEY (post_id, tag_name)
);
CREATE TABLE node (
  id integer PRIMARY KEY,
  parent_id integer REFERENCES node (id),
  label text
);
CREATE TABLE pair (
  a integer,
  b integer,
  v text,
  PRIMARY KEY (a, b)
);
CREATE TABLE pair_ref (
  id integer PRIMARY KEY,
  pa integer,
  pb integer,
  FOREIGN KEY (pa, pb) REFERENCES pair (a, b) DEFERRABLE INITIALLY DEFERRED
);
CREATE TABLE no_pk (a integer, b text);
CREATE TABLE other.thing (
  id integer PRIMARY KEY,
  lvl other.level NOT NULL,
  account_id bigint REFERENCES public.account (id)
);
CREATE TABLE excl (
  id integer PRIMARY KEY,
  c circle,
  EXCLUDE USING gist (c WITH &&)
);
CREATE TABLE parted (id integer, k date) PARTITION BY RANGE (k);
CREATE TABLE parted_2024 PARTITION OF parted FOR VALUES FROM ('2024-01-01') TO ('2025-01-01');
CREATE TABLE child_inh (extra text) INHERITS (no_pk);
CREATE VIEW published_posts AS SELECT id, title FROM post WHERE published;
CREATE MATERIALIZED VIEW post_counts AS SELECT author_id, count(*) AS n FROM post GROUP BY author_id;
CREATE FUNCTION touch() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN NEW.updated := now(); RETURN NEW; END $$;
CREATE TRIGGER account_touch BEFORE UPDATE ON account FOR EACH ROW EXECUTE FUNCTION touch();
ALTER TABLE post ENABLE ROW LEVEL SECURITY;
CREATE POLICY post_pol ON post USING (published);
