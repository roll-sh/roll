#!/usr/bin/env python3
"""Generate src/sql/nodewalk.rs: a visit of every `Node` of a parse tree, mutably.

    python3 tools/gen_nodewalk.py <pg_query.rs's src/protobuf.rs> > src/sql/nodewalk.rs

Run it again when the pg_query dependency changes. Every message type that can hold a node
(directly, or through another message type) gets a function visiting those fields, so no
node is ever left out (the statement templates in `sql/literals.rs` rely on finding every
A_Const of a tree).
"""
import re
import sys

src = open(sys.argv[1]).read()
# Join the fields prost-build wrapped over several lines.
src = re.sub(r"<\s*\n\s*", "<", src)
src = re.sub(r",\s*\n\s*>", ">", src)

structs = {}
for m in re.finditer(r"^pub struct (\w+) \{(\}|\n.*?^\})", src, re.S | re.M):
    fields = re.findall(r"^\s*pub (\w+): ([^\n]*),$", m.group(2), re.M)
    structs[m.group(1)] = fields

enum = re.search(r"pub mod node \{.*?pub enum Node \{(.*?)\n    \}", src, re.S).group(1)
variants = re.findall(r"^\s*(\w+)\(\s*(?:::prost::alloc::boxed::Box<)?super::(\w+)>?,?\s*\),", enum, re.M)
assert len(variants) == enum.count("#[prost("), "a Node variant wasn't read"

BOX = "::prost::alloc::boxed::Box<"


def inner(ty):
    """(kind, message type) of a field type: kind is 'opt', 'vec' or None."""
    for kind, pre in (("opt", "::core::option::Option<"), ("vec", "::prost::alloc::vec::Vec<")):
        if ty.startswith(pre):
            t = ty[len(pre):-1]
            if t.startswith(BOX):
                t = t[len(BOX):-1]
            return kind, t
    return None, ty


# Message types that can hold a node, to a fixed point.
holds = {"Node"}
changed = True
while changed:
    changed = False
    for name, fields in structs.items():
        if name in holds:
            continue
        if any(inner(t)[1] in holds for _, t in fields):
            holds.add(name)
            changed = True


def snake(name):
    return "m_" + re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


out = [
    "// @generated by tools/gen_nodewalk.py from pg_query's protobuf.rs; don't edit by hand.",
    "//! Every `Node` of a parse tree, mutably (pre-order: a node before what it holds).",
    "#![allow(clippy::all, dead_code)]",
    "use pg_query::NodeEnum as E;",
    "use pg_query::protobuf::*;",
    "",
    "type F<'a> = &'a mut dyn FnMut(&mut Node);",
    "",
    "/// `f` on `n` and on every node below it.",
    "pub fn node(n: &mut Node, f: F) {",
    "    f(n);",
    "    let Some(e) = &mut n.node else { return };",
    "    match e {",
]
for v, t in variants:
    if t in holds:
        out.append(f"        E::{v}(x) => {snake(t)}(x, f),")
out += ["        _ => {}", "    }", "}", ""]
for name in sorted(holds - {"Node"}):
    body = []
    for fname, ty in structs[name]:
        kind, t = inner(ty)
        if t not in holds:
            continue
        call = "node" if t == "Node" else snake(t)
        if kind == "vec":
            body.append(f"    for y in &mut x.{fname} {{ {call}(y, f); }}")
        elif kind == "opt":
            body.append(f"    if let Some(y) = &mut x.{fname} {{ {call}(y, f); }}")
    out.append(f"fn {snake(name)}(x: &mut {name}, f: F) {{")
    out += body
    out += ["}", ""]
out.append("/// `f` on every node of a statement.")
out.append("pub fn raw_stmt(x: &mut RawStmt, f: F) {")
out.append("    if let Some(y) = &mut x.stmt { node(y, f); }")
out.append("}")
print("\n".join(out))
