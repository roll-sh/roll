#!/usr/bin/env python3
"""Generates src/tokenizer/tlds.rs from Lucene's ASCIITLD.jflex (the IANA TLD list as of the
Lucene release Elasticsearch 9.5.5 bundles).

usage: python3 -I tools/gen_tlds.py <path to ASCIITLD.jflex> > src/tokenizer/tlds.rs
"""
import re, sys

text = open(sys.argv[1], encoding='utf-8').read()
out = {}
for name in ['ASCIITLD', 'ASCIITLDprefix_1CharSuffix', 'ASCIITLDprefix_2CharSuffix']:
    m = re.search(r'^' + name + r' = "\." \((.*?)\) "\."\?', text, re.S | re.M)
    tlds = []
    for line in m.group(1).splitlines():
        line = line.split('//')[0].strip()
        if not line:
            continue
        line = line.lstrip('|').strip()
        pairs = re.findall(r'\[(.)(.)\]|(\\u[0-9A-Fa-f]{4})|"([^"]*)"|(\S)', line)
        s = ''
        for a, b, u, q, o in pairs:
            if a:
                s += a.lower()
            elif u:
                s += chr(int(u[2:], 16))
            elif q:
                s += q
            else:
                s += o
        tlds.append(s)
    out[name] = tlds

print('//! Generated by `tools/gen_tlds.py` from Lucene\'s `ASCIITLD.jflex` (the IANA root zone TLDs).')
print('//! Do not edit.')
print()
for name, rust in [('ASCIITLD', 'TLDS'), ('ASCIITLDprefix_1CharSuffix', 'TLD_PREFIX_1'), ('ASCIITLDprefix_2CharSuffix', 'TLD_PREFIX_2')]:
    tlds = out[name]
    print(f'pub(crate) static {rust}: [&str; {len(tlds)}] = [')
    line = '   '
    for t in tlds:
        item = f' "{t}",'
        if len(line) + len(item) > 100:
            print(line)
            line = '   '
        line += item
    print(line)
    print('];')
    print()
