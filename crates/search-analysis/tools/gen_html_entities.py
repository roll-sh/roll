#!/usr/bin/env python3
"""Generates src/charfilter/html_entities.rs from Lucene's HTMLCharacterEntities.jflex (Apache-2.0):
the named character references HTMLStripCharFilter decodes.

usage: python3 -I tools/gen_html_entities.py <HTMLCharacterEntities.jflex> > src/charfilter/html_entities.rs
"""
import re, sys

src = open(sys.argv[1], encoding='utf-8').read()
macro = src[src.index('CharacterEntities = ('):src.index(')', src.index('CharacterEntities = ('))]
names = re.findall(r'"([A-Za-z0-9]+)"', macro)
arr = src[src.index('String[] entities = {'):src.index('};', src.index('String[] entities = {'))]
items = re.findall(r'"((?:\\u[0-9A-Fa-f]{4}|\\"|[^"])*)"', arr)
values = {}
for i in range(0, len(items), 2):
    v = items[i + 1]
    v = v.encode().decode('unicode_escape') if v.startswith('\\u') else v.replace('\\"', '"')
    values[items[i]] = v
upper = {'quot': 'QUOT', 'copy': 'COPY', 'gt': 'GT', 'lt': 'LT', 'reg': 'REG', 'amp': 'AMP'}
for k, u in upper.items():
    values[u] = values[k]
missing = [n for n in names if n not in values]
assert not missing, missing
print("//! Generated by `tools/gen_html_entities.py` from Lucene's `HTMLCharacterEntities.jflex` (Apache-2.0). Do not edit.")
print()
print('/// (name, character), sorted by name.')
pairs = sorted((n, values[n]) for n in set(names))
print(f'pub(crate) static ENTITIES: [(&str, char); {len(pairs)}] = [')
line = '   '
for n, v in pairs:
    item = f" (\"{n}\", '\\u{{{ord(v):04X}}}'),"
    if len(line) + len(item) > 100:
        print(line)
        line = '   '
    line += item
print(line)
print('];')
