#!/usr/bin/env python3
"""Generates src/filter/ascii_folding_table.rs from Lucene's ASCIIFoldingFilter.java (Apache-2.0):
the (character, ASCII replacement) pairs of its `foldToASCII` switch.

usage: python3 -I tools/gen_ascii_folding.py <ASCIIFoldingFilter.java> > src/filter/ascii_folding_table.rs
"""
import re, sys

src = open(sys.argv[1], encoding='utf-8').read()
body = src[src.index('switch (c) {'):]
pairs = []
pending = []
out = ''
for line in body.splitlines():
    line = line.strip()
    m = re.match(r"case '\\u([0-9A-Fa-f]{4})':", line)
    if m:
        if out and not pending:
            out = ''
        pending.append(int(m.group(1), 16))
        continue
    m = re.match(r"output\[outputPos\+\+\] = '(\\\\|\\'|.)';", line)
    if m:
        ch = m.group(1)
        ch = {'\\\\': '\\', "\\'": "'"}.get(ch, ch)
        out += ch
        continue
    if line.startswith('break;'):
        for cp in pending:
            pairs.append((cp, out))
        pending = []
        out = ''
        continue
    if line.startswith('default:'):
        break
pairs.sort()
print('//! Generated by `tools/gen_ascii_folding.py` from Lucene\'s `ASCIIFoldingFilter` (Apache-2.0). Do not edit.')
print()
print(f'/// (code point, ASCII folding), sorted by code point.')
print(f'pub(crate) static FOLDINGS: [(u16, &str); {len(pairs)}] = [')
line = '   '
for cp, s in pairs:
    lit = s.replace('\\', '\\\\').replace('"', '\\"')
    item = f' (0x{cp:04X}, "{lit}"),'
    if len(line) + len(item) > 100:
        print(line)
        line = '   '
    line += item
print(line)
print('];')
