"""Generates src/stopwords.rs: the default stop word sets of Lucene's language analyzers (the
`_lang_` lists Elasticsearch accepts), read the way each analyzer reads its resource file.

usage: python3 -I tools/gen_stopwords.py <lucene>/lucene/analysis/common/src/resources/org/apache/lucene/analysis > src/stopwords.rs
"""
import os, re, sys

