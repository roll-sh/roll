    print(f'/// `{res}`.')
    print(f'pub(crate) static {name}: &[&str] = &[')
    line = '   '
    for w in words:
        item = ' ' + rust_str(w) + ','
        if len(line) + len(item) > 100:
            print(line)
            line = '   '
        line += item
    if line.strip():
        print(line)
    print('];')
    print()
