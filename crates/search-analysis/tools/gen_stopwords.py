def load(path, fmt):
    words = []
    seen = set()
    def add(w):
        if w not in seen:
            seen.add(w)
            words.append(w)
    with open(path, encoding='utf-8') as f:
        for line in f.read().splitlines():
            if fmt == 'snowball':
                line = line.split('|', 1)[0]
                for w in re.split(r'\s+', line):
                    if w:
                        add(w)
            else:
                if fmt == 'hash' and line.startswith('#'):
                    continue
                # Java's String.trim(): code points <= U+0020.
                w = line.strip(''.join(chr(c) for c in range(0x21)))
                if w:
                    add(w)
    return words

def rust_str(w):
    return '"' + w.replace('\\', '\\\\').replace('"', '\\"') + '"'

