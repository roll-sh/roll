#!/usr/bin/env python3
"""Generates src/unicode/tables.rs from the Unicode Character Database.

usage: python3 -I tools/gen_unicode.py <ucd dir> > src/unicode/tables.rs

<ucd dir> holds three versions of the UCD, each matching what Elasticsearch 9.5.5 uses:
  17/   UnicodeData.txt PropList.txt DerivedCoreProperties.txt   (the JDK's java.lang.Character)
  12.1/ UnicodeData.txt WordBreakProperty.txt Scripts.txt LineBreak.txt emoji-data.txt
        DerivedCoreProperties.txt
        (JFlex's `%unicode 12.1`: StandardTokenizer and UAX29URLEmailTokenizer)
  3.0/  UnicodeData.txt                                          (JFlex's `%unicode 3.0`: ClassicTokenizer)
from https://www.unicode.org/Public/.
"""
import sys, os

D = sys.argv[1]
MAXCP = 0x110000
JAVA_GC = {
    'Cn': 0, 'Lu': 1, 'Ll': 2, 'Lt': 3, 'Lm': 4, 'Lo': 5, 'Mn': 6, 'Me': 7, 'Mc': 8, 'Nd': 9, 'Nl': 10,
    'No': 11, 'Zs': 12, 'Zl': 13, 'Zp': 14, 'Cc': 15, 'Cf': 16, 'Co': 18, 'Cs': 19, 'Pd': 20, 'Ps': 21,
    'Pe': 22, 'Pc': 23, 'Po': 24, 'Sm': 25, 'Sc': 26, 'Sk': 27, 'So': 28, 'Pi': 29, 'Pf': 30,
}

def unicode_data(path):
    """Yields (cp, fields) for every code point, expanding First/Last ranges."""
    first = None
    with open(path, encoding='utf-8') as f:
        for line in f:
            p = line.rstrip('\n').split(';')
            cp = int(p[0], 16)
            if p[1].endswith(', First>'):
                first = cp
                continue
            if p[1].endswith(', Last>'):
                for c in range(first, cp + 1):
                    yield c, p
                first = None
                continue
            yield cp, p

def prop_file(path):
    """{value: [(lo, hi)]} from a `lo..hi ; Value # comment` file."""
    out = {}
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.split('#', 1)[0].strip()
            if not line:
                continue
            rng, val = [x.strip() for x in line.split(';')[:2]]
            if '..' in rng:
                lo, hi = [int(x, 16) for x in rng.split('..')]
            else:
                lo = hi = int(rng, 16)
            out.setdefault(val, []).append((lo, hi))
    return {k: merge(v) for k, v in out.items()}

def merge(ranges):
    ranges = sorted(ranges)
    out = []
    for lo, hi in ranges:
        if out and lo <= out[-1][1] + 1:
            out[-1] = (out[-1][0], max(out[-1][1], hi))
        else:
            out.append((lo, hi))
    return out

def ranges_of(pred_values):
    """Ranges where the per-code-point list is true."""
    out = []
    start = None
    for cp in range(MAXCP):
        if pred_values[cp]:
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAXCP - 1))
    return out

def emit_ranges(name, ranges, doc):
    print(f'/// {doc}')
    print(f'pub(crate) static {name}: &[(u32, u32)] = &[')
    line = '   '
    for lo, hi in ranges:
        item = f' (0x{lo:X}, 0x{hi:X}),'
        if len(line) + len(item) > 100:
            print(line)
            line = '   '
        line += item
    if line.strip():
        print(line)
    print('];')
    print()

def emit_two_level(name, values, ty, doc):
    """A two-level table: INDEX[cp >> 8] selects a 256-entry block of BLOCKS."""
    blocks = []
    index = []
    seen = {}
    for b in range(MAXCP >> 8):
        blk = tuple(values[b << 8:(b + 1) << 8])
        if blk not in seen:
            seen[blk] = len(blocks)
            blocks.append(blk)
        index.append(seen[blk])
    print(f'/// {doc}')
    print(f'pub(crate) static {name}_INDEX: [u16; {len(index)}] = [')
    for i in range(0, len(index), 24):
        print('    ' + ', '.join(str(x) for x in index[i:i + 24]) + ',')
    print('];')
    print(f'pub(crate) static {name}_BLOCKS: [[{ty}; 256]; {len(blocks)}] = [')
    for blk in blocks:
        print('    [')
        for i in range(0, 256, 32):
            print('        ' + ', '.join(str(x) for x in blk[i:i + 32]) + ',')
        print('    ],')
    print('];')
    print()

print('//! Generated by `tools/gen_unicode.py` from the Unicode Character Database')
print('//! (Unicode License v3, https://www.unicode.org/license.txt). Do not edit.')
print()
print('#![allow(clippy::unreadable_literal)]')
print()

# --- Unicode 17: java.lang.Character -------------------------------------------------------
gc = [0] * MAXCP
lower = [0] * MAXCP
upper = [0] * MAXCP
title = [0] * MAXCP
for cp, p in unicode_data(os.path.join(D, '17', 'UnicodeData.txt')):
    gc[cp] = JAVA_GC[p[2]]
    if p[12]:
        upper[cp] = int(p[12], 16) - cp
    if p[13]:
        lower[cp] = int(p[13], 16) - cp
    if p[14]:
        title[cp] = int(p[14], 16) - cp
    elif p[12]:
        title[cp] = upper[cp]

emit_two_level('GC', gc, 'u8', "General category (java.lang.Character.getType values), Unicode 17.")

def emit_delta(name, deltas, doc):
    uniq = sorted(set(deltas))
    uniq.remove(0)
    uniq = [0] + uniq
    assert len(uniq) < 256
    ids = {d: i for i, d in enumerate(uniq)}
    print(f'/// Deltas for {name}_INDEX/{name}_BLOCKS.')
    print(f'pub(crate) static {name}_DELTAS: [i32; {len(uniq)}] = [{", ".join(str(d) for d in uniq)}];')
    emit_two_level(name, [ids[d] for d in deltas], 'u8', doc)

emit_delta('LOWER', lower, 'Simple lowercase mapping (Character.toLowerCase(int)), Unicode 17: ids into LOWER_DELTAS.')
emit_delta('UPPER', upper, 'Simple uppercase mapping (Character.toUpperCase(int)), Unicode 17: ids into UPPER_DELTAS.')

props = prop_file(os.path.join(D, '17', 'PropList.txt'))
derived = prop_file(os.path.join(D, '17', 'DerivedCoreProperties.txt'))
emit_ranges('OTHER_LOWERCASE', props['Other_Lowercase'], 'Other_Lowercase, Unicode 17.')
emit_ranges('OTHER_UPPERCASE', props['Other_Uppercase'], 'Other_Uppercase, Unicode 17.')
emit_ranges('ALPHABETIC', derived['Alphabetic'], 'Alphabetic, Unicode 17 (Character.isAlphabetic).')
emit_ranges('IDEOGRAPHIC', props['Ideographic'], 'Ideographic, Unicode 17 (Character.isIdeographic).')

# --- Unicode 12.1: JFlex grammars -----------------------------------------------------------
wb = prop_file(os.path.join(D, '12.1', 'WordBreakProperty.txt'))
for v in ['ALetter', 'Hebrew_Letter', 'Numeric', 'Katakana', 'MidLetter', 'MidNumLet', 'MidNum',
          'Single_Quote', 'Double_Quote', 'ExtendNumLet', 'Regional_Indicator', 'Format', 'Extend', 'ZWJ',
          'CR', 'LF', 'Newline', 'WSegSpace']:
    emit_ranges('WB12_' + v.upper(), wb[v], f'Word_Break={v}, Unicode 12.1.')
scripts = prop_file(os.path.join(D, '12.1', 'Scripts.txt'))
for v in ['Han', 'Hiragana', 'Hangul']:
    emit_ranges('SCRIPT12_' + v.upper(), scripts[v], f'Script={v}, Unicode 12.1.')
lb = prop_file(os.path.join(D, '12.1', 'LineBreak.txt'))
emit_ranges('LB12_SA', lb['SA'], 'Line_Break=Complex_Context (SA), Unicode 12.1.')
emoji = prop_file(os.path.join(D, '12.1', 'emoji-data.txt'))
for v in ['Emoji', 'Emoji_Modifier', 'Emoji_Modifier_Base', 'Extended_Pictographic']:
    emit_ranges('EMOJI12_' + v.upper(), emoji[v], f'{v}, Unicode (emoji) 12.1.')
gc12 = [''] * MAXCP
for cp, p in unicode_data(os.path.join(D, '12.1', 'UnicodeData.txt')):
    gc12[cp] = p[2]
emit_ranges('GC12_LETTER', ranges_of([g.startswith('L') for g in gc12]),
            'General_Category=L (letters), Unicode 12.1.')
emit_ranges('GC12_ND', ranges_of([g == 'Nd' for g in gc12]), 'General_Category=Nd, Unicode 12.1.')
emit_ranges('GC12_MARK', ranges_of([g.startswith('M') for g in gc12]), 'General_Category=M, Unicode 12.1.')
emit_ranges('GC12_PC', ranges_of([g == 'Pc' for g in gc12]), 'General_Category=Pc, Unicode 12.1.')
derived12 = prop_file(os.path.join(D, '12.1', 'DerivedCoreProperties.txt'))
emit_ranges('ALPHABETIC12', derived12['Alphabetic'], 'Alphabetic, Unicode 12.1.')
emit_ranges('ID_START12', derived12['ID_Start'], 'ID_Start, Unicode 12.1.')
emit_ranges('ID_CONTINUE12', derived12['ID_Continue'], 'ID_Continue, Unicode 12.1.')
props12 = prop_file(os.path.join(D, '12.1', 'PropList.txt'))
emit_ranges('WHITE_SPACE12', props12['White_Space'], 'White_Space, Unicode 12.1 (JFlex \\s).')

# --- Unicode 3.0: JFlex ClassicTokenizer ----------------------------------------------------
gc3 = [''] * MAXCP
for cp, p in unicode_data(os.path.join(D, '3.0', 'UnicodeData.txt')):
    gc3[cp] = p[2]
emit_ranges('GC3_LETTER', ranges_of([g.startswith('L') for g in gc3]), 'General_Category=L, Unicode 3.0.')
emit_ranges('GC3_ND', ranges_of([g == 'Nd' for g in gc3]), 'General_Category=Nd, Unicode 3.0.')
