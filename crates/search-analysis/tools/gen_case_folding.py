#!/usr/bin/env python3
"""Generates src/unicode/case_folding.rs: the simple and Turkic case foldings (statuses C, S
and T) of the Unicode Character Database, which Java's case-insensitive character class ranges
use to close a range over case (`CaseFolding.getClassRangeClosingCharacters`).

usage: python3 -I tools/gen_case_folding.py <path to CaseFolding.txt (Unicode 17)> > src/unicode/case_folding.rs
"""
import sys

pairs = []
for line in open(sys.argv[1], encoding='utf-8'):
    if line.startswith('#') or not line.strip():
        continue
    cols = line.split('; ')
    if cols[1] in ('C', 'S', 'T'):
        pairs.append((int(cols[0], 16), int(cols[2], 16)))
print('//! Generated by `tools/gen_case_folding.py` from the Unicode Character Database\'s')
print('//! CaseFolding.txt (Unicode License v3, https://www.unicode.org/license.txt). Do not edit.')
print()
print('/// (code point, folding) for the C, S and T entries, in file order.')
print('pub(crate) static CASE_FOLDING_CST: &[(u32, u32)] = &[')
for i in range(0, len(pairs), 6):
    print('    ' + ' '.join(f'(0x{a:04X}, 0x{b:04X}),' for a, b in pairs[i:i + 6]))
print('];')
