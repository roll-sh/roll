#!/usr/bin/env python3
"""Generates src/unicode/blocks.rs: the Unicode blocks and scripts `java.lang.Character` knows
(`UnicodeBlock`, `UnicodeScript`), with every name `forName` accepts (Java's `\\p{InX}`,
`\\p{block=X}`, `\\p{IsX}`, `\\p{script=X}`), and their code point ranges. Only the names and
ranges are extracted (they are Unicode data: Blocks.txt, Scripts.txt and ISO 15924 codes, plus
the JDK's historical identifiers such as GREEK for "Greek and Coptic").

usage: python3 -I tools/gen_blocks.py <path to java/lang/Character.java> > src/unicode/blocks.rs
"""
import re, sys

s = open(sys.argv[1], encoding='utf-8').read()
decl = re.findall(r'public static final UnicodeBlock\s+(\w+)\s*=\s*new UnicodeBlock\(([^;]*?)\);', s, re.S)
# (A declaration may repeat an alias, as CYPRO_MINOAN does.)
names = {const: list(dict.fromkeys(re.findall(r'"([^"]*)"', args))) for const, args in decl}
starts = s[s.index('private static final int[] blockStarts = {'):]
starts = [int(x, 16) for x in re.findall(r'0x([0-9A-Fa-f]+)\s*,', starts[:starts.index('};')])]
blocks = s[s.index('private static final UnicodeBlock[] blocks = {'):]
blocks = re.findall(r'^\s*(\w+),', blocks[:blocks.index('};')], re.M)
assert len(starts) == len(blocks)
ranges = {}
for i, b in enumerate(blocks):
    if b == 'null':
        continue
    end = (starts[i + 1] if i + 1 < len(starts) else 0x110000) - 1
    ranges.setdefault(b, []).append((starts[i], end))
order = list(names)
aliases = sorted((a, order.index(c)) for c, al in names.items() for a in al)
assert len({a for a, _ in aliases}) == len(aliases)
out = ['//! Generated by `tools/gen_blocks.py` from the JDK\'s `Character.UnicodeBlock` (block names',
       '//! and ranges, i.e. Unicode\'s Blocks.txt). Do not edit.', '',
       '/// Code point ranges of each block (deprecated `SURROGATES_AREA` has none).',
       'pub(crate) static BLOCK_RANGES: &[&[(u32, u32)]] = &[']
for c in order:
    r = ranges.get(c, [])
    out.append('    &[' + ', '.join(f'(0x{a:04X}, 0x{b:04X})' for a, b in r) + f'], // {c}')
out.append('];')
out.append('')
out.append('/// Every name `UnicodeBlock.forName` accepts (upper case, compared after `toUpperCase`),')
out.append('/// sorted, with its index into [`BLOCK_RANGES`].')
out.append('pub(crate) static BLOCK_NAMES: &[(&str, u16)] = &[')
for a, i in aliases:
    out.append(f'    ("{a}", {i}),')
out.append('];')

starts = s[s.index('private static final int[] scriptStarts = {'):]
starts = [int(x, 16) for x in re.findall(r'0x([0-9A-Fa-f]+)\s*,', starts[:starts.index('};')])]
scripts = s[s.index('private static final UnicodeScript[] scripts = {'):]
scripts = re.findall(r'^\s*(\w+),', scripts[:scripts.index('};')], re.M)
assert len(starts) == len(scripts)
sranges = {}
for i, sc in enumerate(scripts):
    end = (starts[i + 1] if i + 1 < len(starts) else 0x110000) - 1
    r = sranges.setdefault(sc, [])
    if r and r[-1][1] + 1 == starts[i]:
        r[-1] = (r[-1][0], end)
    else:
        r.append((starts[i], end))
salias = re.findall(r'aliases\.put\("(\w+)", (\w+)\);', s)
sorder = sorted(sranges)
snames = sorted({(sc, sorder.index(sc)) for sc in sorder} | {(a, sorder.index(t)) for a, t in salias})
assert len({a for a, _ in snames}) == len(snames)
out.append('')
out.append('/// Code point ranges of each script (`Character.UnicodeScript.of`).')
out.append('pub(crate) static SCRIPT_RANGES: &[&[(u32, u32)]] = &[')
for sc in sorder:
    out.append('    &[' + ', '.join(f'(0x{a:04X}, 0x{b:04X})' for a, b in sranges[sc]) + f'], // {sc}')
out.append('];')
out.append('')
out.append('/// Every name `UnicodeScript.forName` accepts (upper case: the constant names and the ISO')
out.append('/// 15924 aliases), sorted, with its index into [`SCRIPT_RANGES`].')
out.append('pub(crate) static SCRIPT_NAMES: &[(&str, u16)] = &[')
for a, i in snames:
    out.append(f'    ("{a}", {i}),')
out.append('];')
print('\n'.join(out))
