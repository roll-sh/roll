#!/usr/bin/env python3
"""Generates src/stem/kstem_data.rs from Lucene's KStemmer.java and KStemData1-8.java
(Apache-2.0; the word lists come from the University of Massachusetts KStem distribution).

usage: python3 -I tools/gen_kstem.py <dir with KStemmer.java and KStemData*.java> > src/stem/kstem_data.rs
"""
import re, sys

D = sys.argv[1]
src = open(f'{D}/KStemmer.java', encoding='utf-8').read()


def block(name):
    m = re.search(r'\b' + name + r'\s*=\s*\{(.*?)\n  \};', src, re.S)
    # Entries commented out in the Java source (`// {"netherlands", "dutch"},`) are not data.
    return '\n'.join(l for l in m.group(1).split('\n') if not l.strip().startswith('//'))


def strings(text):
    return re.findall(r'"((?:[^"\\]|\\.)*)"', text)


def pairs(text):
    return re.findall(r'\{\s*"([^"]*)"\s*,\s*"([^"]*)"\s*\}', text)


exceptions = strings(block('exceptionWords'))
conflations = pairs(block('directConflations')) + pairs(block('countryNationality'))
words = []
for i in range(1, 9):
    data = open(f'{D}/KStemData{i}.java', encoding='utf-8').read()
    m = re.search(r'static final String\[\] data\s*=\s*\{(.*?)\};', data, re.S)
    words += strings(m.group(1))
words += strings(block('supplementDict'))
words += strings(block('properNouns'))
for w in words:
    assert '\n' not in w and w.isascii(), w

print('//! Generated by `tools/gen_kstem.py` from Lucene\'s `KStemmer` and `KStemData*` (Apache-2.0).')
print('//! Do not edit.')
print()
print('/// Words whose `-e` form must not be produced (`exceptionWords`).')
print('pub(crate) static EXCEPTIONS: &[&str] = &[')
for w in exceptions:
    print(f'    "{w}",')
print('];')
print()
print('/// Direct mappings (`directConflations`, then `countryNationality`).')
print('pub(crate) static CONFLATIONS: &[(&str, &str)] = &[')
for a, b in conflations:
    print(f'    ("{a}", "{b}"),')
print('];')
print()
print(f'/// The dictionary ({len(words)} words, newline-separated): `KStemData1`-`8`, `supplementDict`,')
print('/// `properNouns`.')
print('pub(crate) static WORDS: &str = "\\')
line = ''
for w in words:
    piece = w + '\\n'
    if len(line) + len(piece) > 100:
        print(line + '\\')
        line = ''
    line += piece
print(line + '";')
